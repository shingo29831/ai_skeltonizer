"""Module: @role: クライアント側コマンド実行追跡・サーバー側実行状態マージ・実行中高頻度ポーリングのJavaScriptを生成する。"""

def build_monitor_execution_js() -> str:
    """実行中コマンドの状態追跡・サーバー状態抽出・1秒ポーリング制御のJSコード群を返す。"""
    return (
        "  const RUNNING_STATUS_POLL_MS = 1000;\n"
        "  let commandExecSeq = 0;\n"
        "  const activeCommandExecutions = new Map();\n"
        "  let serverCommandState = { running: false, label: '', detail: '', startedAt: 0, count: 0 };\n"
        "  let lastCommandEndedAt = 0;\n"
        "  let runningStatusPollTimer = null;\n"
        "  let runningStatusPollInFlight = false;\n\n"
        "  function formatBridgeCommandKindLabel(kind, fallbackCommand) {\n"
        "    const k = String(kind || '').toLowerCase();\n"
        "    if (k === 'execute') return 'aiskel c 実行中';\n"
        "    if (k === 'auto_check') return 'aiskel a --check 実行中';\n"
        "    if (k === 'auto_apply') return 'aiskel a 実行中';\n"
        "    if (k === 'run_command') return 'コマンド実行中';\n"
        "    if (k === 'aiskel_patch_handoff') return 'aiskel a / 引き継ぎ中';\n"
        "    if (k === 'aiskel_split_handoff') return '自動分割引き継ぎ準備中';\n"
        "    if (k === 'aiskel_organize_handoff') return '階層整理引き継ぎ準備中';\n"
        "    if (k === 'aiskel_config_handoff') return '設定推論引き継ぎ準備中';\n"
        "    return fallbackCommand || 'コマンド実行中';\n"
        "  }\n\n"
        "  function parseServerCommandStartedAt(rawVal, rawElapsedMs, rawElapsedSec) {\n"
        "    const now = Date.now();\n"
        "    if (typeof rawElapsedMs === 'number' && Number.isFinite(rawElapsedMs) && rawElapsedMs >= 0) {\n"
        "      return now - rawElapsedMs;\n"
        "    }\n"
        "    if (typeof rawElapsedSec === 'number' && Number.isFinite(rawElapsedSec) && rawElapsedSec >= 0) {\n"
        "      return now - rawElapsedSec * 1000;\n"
        "    }\n"
        "    if (typeof rawVal === 'number' && Number.isFinite(rawVal) && rawVal > 0) {\n"
        "      if (rawVal >= 1e12) return rawVal;\n"
        "      if (rawVal >= 1e9) return rawVal * 1000;\n"
        "    }\n"
        "    if (typeof rawVal === 'string' && rawVal.trim()) {\n"
        "      const parsed = Date.parse(rawVal.trim());\n"
        "      if (!Number.isNaN(parsed) && parsed > 0) return parsed;\n"
        "    }\n"
        "    return 0;\n"
        "  }\n\n"
        "  function extractServerCommandExecutionState(connected, data) {\n"
        "    if (!connected || !data || typeof data !== 'object') {\n"
        "      return { running: false, label: '', detail: '', startedAt: 0, count: 0 };\n"
        "    }\n"
        "    const execObj = data.execution && typeof data.execution === 'object' ? data.execution : null;\n"
        "    const topListSource = Array.isArray(data.running_commands) && data.running_commands.length\n"
        "      ? data.running_commands\n"
        "      : (Array.isArray(data.active_commands) && data.active_commands.length ? data.active_commands : null);\n"
        "    const cmdObj = execObj || [\n"
        "      data.active_command,\n"
        "      data.running_command,\n"
        "      data.current_command,\n"
        "      data.command_execution,\n"
        "      data.execution_state,\n"
        "      data.command_status,\n"
        "    ].find((v) => v && typeof v === 'object') || (topListSource && topListSource[0] && typeof topListSource[0] === 'object' ? topListSource[0] : null);\n"
        "    const nestedList = cmdObj && Array.isArray(cmdObj.commands) && cmdObj.commands.length ? cmdObj.commands : null;\n"
        "    const listSource = topListSource || nestedList;\n"
        "    const firstEntry = listSource && listSource[0] && typeof listSource[0] === 'object' ? listSource[0] : null;\n"
        "    const primary = firstEntry || cmdObj;\n"
        "    let isRunning = false;\n"
        "    if (cmdObj) {\n"
        "      if (typeof cmdObj.running === 'boolean') isRunning = cmdObj.running;\n"
        "      else if (typeof cmdObj.is_running === 'boolean') isRunning = cmdObj.is_running;\n"
        "      else if (typeof cmdObj.active === 'boolean') isRunning = cmdObj.active;\n"
        "      else if (typeof cmdObj.in_progress === 'boolean') isRunning = cmdObj.in_progress;\n"
        "      else isRunning = Boolean(cmdObj.command || cmdObj.cmd || cmdObj.label || cmdObj.command_name || cmdObj.kind);\n"
        "    }\n"
        "    if (!isRunning && !execObj) {\n"
        "      isRunning = Boolean(\n"
        "        data.command_running ||\n"
        "        data.is_command_running ||\n"
        "        data.executing ||\n"
        "        data.is_executing ||\n"
        "        (topListSource && topListSource.length > 0)\n"
        "      );\n"
        "    }\n"
        "    if (!isRunning) {\n"
        "      return { running: false, label: '', detail: '', startedAt: 0, count: 0 };\n"
        "    }\n"
        "    const kind = String((primary && primary.kind) || (cmdObj && cmdObj.kind) || '');\n"
        "    const rawCmd = String(\n"
        "      (primary && (primary.command || primary.cmd || primary.label || primary.title || primary.command_name)) ||\n"
        "      (cmdObj && (cmdObj.command || cmdObj.cmd || cmdObj.label || cmdObj.title || cmdObj.command_name)) ||\n"
        "      data.active_command_label || data.running_command_name || data.command_label || data.executing_command || ''\n"
        "    ).trim();\n"
        "    const label = formatBridgeCommandKindLabel(kind, rawCmd);\n"
        "    const explicitDetail = String(\n"
        "      (primary && (primary.detail || primary.phase || primary.stage || primary.description || primary.target)) ||\n"
        "      (cmdObj && (cmdObj.detail || cmdObj.phase || cmdObj.stage || cmdObj.description || cmdObj.target)) ||\n"
        "      data.active_command_detail || data.active_command_phase || data.command_phase || ''\n"
        "    ).trim();\n"
        "    const detail = explicitDetail || (rawCmd && rawCmd !== label ? rawCmd : '');\n"
        "    const parsedStart = parseServerCommandStartedAt(\n"
        "      (primary && (primary.started_at_ms || primary.started_at || primary.start_time || primary.started_ms)) ||\n"
        "        (cmdObj && (cmdObj.started_at_ms || cmdObj.started_at || cmdObj.start_time || cmdObj.started_ms)) ||\n"
        "        data.command_started_at || data.active_command_started_at,\n"
        "      (primary && primary.elapsed_ms) != null\n"
        "        ? primary.elapsed_ms\n"
        "        : ((cmdObj && cmdObj.elapsed_ms) != null ? cmdObj.elapsed_ms : data.command_elapsed_ms),\n"
        "      (primary && (primary.elapsed_sec != null ? primary.elapsed_sec : primary.elapsed_seconds)) != null\n"
        "        ? (primary.elapsed_sec != null ? primary.elapsed_sec : primary.elapsed_seconds)\n"
        "        : ((cmdObj && (cmdObj.elapsed_sec != null ? cmdObj.elapsed_sec : cmdObj.elapsed_seconds)) != null\n"
        "          ? (cmdObj.elapsed_sec != null ? cmdObj.elapsed_sec : cmdObj.elapsed_seconds)\n"
        "          : (data.command_elapsed_sec != null ? data.command_elapsed_sec : data.command_elapsed_seconds))\n"
        "    );\n"
        "    // ポーリングRTT揺らぎで経過秒が前後しないよう同一実行中は開始時刻を安定化\n"
        "    let startedAt = parsedStart > 0 ? parsedStart : Date.now();\n"
        "    if (\n"
        "      serverCommandState.running &&\n"
        "      serverCommandState.startedAt > 0 &&\n"
        "      serverCommandState.label === label &&\n"
        "      serverCommandState.detail === detail\n"
        "    ) {\n"
        "      if (parsedStart <= 0 || Math.abs(parsedStart - serverCommandState.startedAt) < 1500) {\n"
        "        startedAt = serverCommandState.startedAt;\n"
        "      }\n"
        "    }\n"
        "    const count = (cmdObj && typeof cmdObj.count === 'number' && cmdObj.count > 0)\n"
        "      ? cmdObj.count\n"
        "      : (listSource ? listSource.length : (typeof data.running_command_count === 'number' && data.running_command_count > 0 ? data.running_command_count : 1));\n"
        "    return { running: true, label, detail, startedAt, count };\n"
        "  }\n\n"
        "  function getEffectiveCommandExecutionState() {\n"
        "    const serverCount = serverCommandState.running ? (serverCommandState.count || 1) : 0;\n"
        "    if (activeCommandExecutions.size > 0) {\n"
        "      let latestEntry = null;\n"
        "      let earliestStartedAt = 0;\n"
        "      for (const entry of activeCommandExecutions.values()) {\n"
        "        latestEntry = entry;\n"
        "        if (!earliestStartedAt || (entry.startedAt > 0 && entry.startedAt < earliestStartedAt)) {\n"
        "          earliestStartedAt = entry.startedAt;\n"
        "        }\n"
        "      }\n"
        "      const serverDetail = serverCommandState.running && serverCommandState.detail ? serverCommandState.detail : '';\n"
        "      const detail = (latestEntry && latestEntry.detail) || serverDetail || '';\n"
        "      return {\n"
        "        commandRunning: true,\n"
        "        commandLabel: (latestEntry && latestEntry.label) || 'コマンド実行中',\n"
        "        commandDetail: detail,\n"
        "        commandStartedAt: (latestEntry && latestEntry.startedAt) || earliestStartedAt || Date.now(),\n"
        "        commandCount: Math.max(activeCommandExecutions.size, serverCount),\n"
        "      };\n"
        "    }\n"
        "    if (serverCommandState.running) {\n"
        "      return {\n"
        "        commandRunning: true,\n"
        "        commandLabel: serverCommandState.label || 'コマンド実行中',\n"
        "        commandDetail: serverCommandState.detail || '',\n"
        "        commandStartedAt: serverCommandState.startedAt || Date.now(),\n"
        "        commandCount: serverCount || 1,\n"
        "      };\n"
        "    }\n"
        "    return {\n"
        "      commandRunning: false,\n"
        "      commandLabel: '',\n"
        "      commandDetail: '',\n"
        "      commandStartedAt: 0,\n"
        "      commandCount: 0,\n"
        "    };\n"
        "  }\n\n"
        "  function syncRunningStatusPolling() {\n"
        "    const shouldPoll = Boolean(\n"
        "      hasBindingTransport &&\n"
        "      bindingState &&\n"
        "      bindingState.connected &&\n"
        "      (activeCommandExecutions.size > 0 || serverCommandState.running)\n"
        "    );\n"
        "    if (!shouldPoll) {\n"
        "      if (runningStatusPollTimer !== null) {\n"
        "        window.clearTimeout(runningStatusPollTimer);\n"
        "        runningStatusPollTimer = null;\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    if (runningStatusPollTimer !== null || runningStatusPollInFlight) return;\n"
        "    runningStatusPollTimer = window.setTimeout(() => {\n"
        "      runningStatusPollTimer = null;\n"
        "      if (!hasBindingTransport || runningStatusPollInFlight || typeof refreshBindingStatus !== 'function') {\n"
        "        return;\n"
        "      }\n"
        "      runningStatusPollInFlight = true;\n"
        "      refreshBindingStatus(() => {\n"
        "        runningStatusPollInFlight = false;\n"
        "        syncRunningStatusPolling();\n"
        "      });\n"
        "    }, RUNNING_STATUS_POLL_MS);\n"
        "  }\n\n"
        "  function syncCommandExecutionUiState() {\n"
        "    const execSummary = getEffectiveCommandExecutionState();\n"
        "    bindingState = Object.assign({}, bindingState, execSummary);\n"
        "    if (bindingUi && typeof bindingUi.render === 'function') {\n"
        "      bindingUi.render(bindingState);\n"
        "    }\n"
        "    syncRunningStatusPolling();\n"
        "  }\n\n"
        "  function beginTrackedCommand(options) {\n"
        "    const opts = options || {};\n"
        "    const id = ++commandExecSeq;\n"
        "    activeCommandExecutions.set(id, {\n"
        "      id,\n"
        "      kind: String(opts.kind || 'command'),\n"
        "      label: String(opts.label || 'コマンド実行中'),\n"
        "      detail: String(opts.detail || ''),\n"
        "      startedAt: Date.now(),\n"
        "    });\n"
        "    syncCommandExecutionUiState();\n"
        "    return id;\n"
        "  }\n\n"
        "  function endTrackedCommand(id) {\n"
        "    if (!id || !activeCommandExecutions.has(id)) return;\n"
        "    activeCommandExecutions.delete(id);\n"
        "    lastCommandEndedAt = Date.now();\n"
        "    // ポーリングで取得済みだった同一コマンドの実行中表示が完了後も1秒残留するのを防止\n"
        "    const shouldVerifyServer = activeCommandExecutions.size === 0 && serverCommandState.running;\n"
        "    if (shouldVerifyServer) {\n"
        "      serverCommandState = { running: false, label: '', detail: '', startedAt: 0, count: 0 };\n"
        "    }\n"
        "    syncCommandExecutionUiState();\n"
        "    if (shouldVerifyServer && hasBindingTransport && bindingState && bindingState.connected && typeof refreshBindingStatus === 'function') {\n"
        "      refreshBindingStatus();\n"
        "    }\n"
        "  }\n\n"
        "  function clearTrackedCommands() {\n"
        "    let changed = false;\n"
        "    if (activeCommandExecutions.size > 0) {\n"
        "      activeCommandExecutions.clear();\n"
        "      changed = true;\n"
        "    }\n"
        "    if (serverCommandState.running) {\n"
        "      serverCommandState = { running: false, label: '', detail: '', startedAt: 0, count: 0 };\n"
        "      changed = true;\n"
        "    }\n"
        "    lastCommandEndedAt = Date.now();\n"
        "    if (changed) {\n"
        "      syncCommandExecutionUiState();\n"
        "    } else {\n"
        "      syncRunningStatusPolling();\n"
        "    }\n"
        "  }\n\n"
    )
