        "                ok: false,\n"
        "                status: 'skipped',\n"
        "                reason: 'duplicate_skipped',\n"
        "                action: actionName,\n"
        "                data,\n"
        "                message: dupMsg,\n"
        "              });\n"
        "            }\n"
        "            return;\n"
        "          }\n"
        "          if (!data.skipped) {\n"
        "            if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "            if (data.discovery_handoff) {\n"
