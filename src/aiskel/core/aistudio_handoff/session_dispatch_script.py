        "      if (onDone) onDone({ ok: false, status: 'error', reason: 'no_handoff_transport', action: 'no_patch', message: '未出力通知機能が利用できません' });\n"
        "      return;\n"
        "    }\n"
        "    if (typeof isMonitoringActive === 'function' && !isMonitoringActive()) {\n"
        "      if (onDone) onDone({ ok: false, status: 'aborted', reason: 'monitoring_inactive', action: 'no_patch', message: 'タブの監視が停止しています' });\n"
        "      return;\n"
        "    }\n"
        "    const responseText = extractFullResponseText(ctx.modelTurns);\n"
        "    const hasCodeBlocks = typeof opts.hasCodeBlock === 'boolean'\n"
        "      ? opts.hasCodeBlock\n"
        "      : (typeof hasCodeBlockInTurns === 'function' && hasCodeBlockInTurns(ctx.modelTurns));\n"
        "    const hasApplyCommandMention = typeof opts.hasApplyCommandMention === 'boolean'\n"
        "      ? opts.hasApplyCommandMention\n"
        "      : (typeof hasApplyCommandInTurns === 'function' && hasApplyCommandInTurns(ctx.modelTurns));\n"
        "    const isDiscoveryCtx = Boolean(opts.discoveryContext);\n"
        "    const isStopHandoff = Boolean(opts.stopHandoff);\n"
        "    const baseTurnId = typeof buildBaseTurnIdentifier === 'function'\n"
        "      ? buildBaseTurnIdentifier(ctx)\n"
        "      : buildTurnIdentifier(ctx, finishedRunSeq);\n"
        "    const epoch = typeof manualActionEpoch === 'number' ? manualActionEpoch : 0;\n"
        "    // runSeq変動による同一応答の再通知を防ぐため基本ターンID・本文ハッシュ・手動操作エポックで識別\n"
        "    const stableTurnId = baseTurnId + ':c' + hashText(responseText || '') + ':m' + epoch;\n"
        "    const dedupKey = stableTurnId + '::NO_PATCH';\n"
        "    if ((!forceReverify && executedKeys.has(dedupKey)) || inFlightKeys.has(dedupKey)) {\n"
        "      if (onDone) {\n"
        "        onDone({\n"
        "          ok: false,\n"
        "          status: 'skipped',\n"
        "          reason: inFlightKeys.has(dedupKey) ? 'in_flight' : 'already_executed',\n"
        "          action: 'no_patch',\n"
        "          message: inFlightKeys.has(dedupKey) ? '同じ応答の通知を送信中です' : 'この応答は既に検証済みです',\n"
        "        });\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    const newChatUrl = buildSameAccountNewChatUrl(window.location.href);\n"
        "    const activeOrganize = typeof getActiveAutoSplitStateForCurrentProject === 'function'\n"
        "      ? getActiveAutoSplitStateForCurrentProject()\n"
        "      : null;\n"
        "    const isOrganizeActive = Boolean(activeOrganize && activeOrganize.mode === 'organize');\n"
        "    const activeConfigInfer = typeof getActiveConfigInferStateForCurrentProject === 'function'\n"
        "      ? getActiveConfigInferStateForCurrentProject()\n"
        "      : null;\n"
        "    const isConfigInferActive = Boolean(activeConfigInfer && activeConfigInfer.active);\n"
        "    inFlightKeys.add(dedupKey);\n"
        "    const trackId = typeof beginTrackedCommand === 'function'\n"
        "      ? beginTrackedCommand({\n"
        "          kind: 'no_patch_task',\n"
        "          label: isDiscoveryCtx ? '探索出力を検証中' : 'タスク状態を更新中',\n"
        "          detail: 'ローカルブリッジへ結果を送信しています',\n"
        "        })\n"
        "      : 0;\n"
        "    handoffTransport.reportNoPatchTask(\n"
        "      {\n"
        "        turn_id: stableTurnId,\n"
        "        response_text: responseText || '',\n"
        "        has_code_blocks: hasCodeBlocks,\n"
        "        has_apply_command_mention: hasApplyCommandMention,\n"
        "        no_code_block: !hasCodeBlocks,\n"
        "        new_chat_url: newChatUrl,\n"
        "        stop_handoff: isStopHandoff,\n"
        "        discovery_mode: isDiscoveryCtx,\n"
        "        organize_mode: isOrganizeActive,\n"
        "        allow_rename: isOrganizeActive ? Boolean(activeOrganize.allowRename) : undefined,\n"
        "        config_infer_mode: isConfigInferActive,\n"
        "        config_infer_target: isConfigInferActive ? String(activeConfigInfer.targetFile || 'ai_meta/config.json') : undefined,\n"
        "      },\n"
        "      (res) => {\n"
        "        if (trackId && typeof endTrackedCommand === 'function') endTrackedCommand(trackId);\n"
        "        inFlightKeys.delete(dedupKey);\n"
        "        if (typeof isMonitoringActive === 'function' && !isMonitoringActive()) {\n"
        "          if (onDone) onDone({ ok: false, status: 'aborted', reason: 'monitoring_inactive', action: 'no_patch', message: 'タブの監視が停止しました' });\n"
        "          return;\n"
        "        }\n"
        "        const data = (res && res.data) || {};\n"
        "        if (res && res.connected && data.ok) {\n"
        "          markExecuted(dedupKey);\n"
        "          if (data.duplicate_skipped) {\n"
        "            const dupMsg = String(data.message || 'この応答は既に検証済みです');\n"
        "            if (forceReverify) {\n"
        "              showToast('aiskel 再検証: ' + dupMsg, false);\n"
        "            }\n"
        "            if (onDone) {\n"
        "              onDone({\n"
        "                ok: false,\n"
        "                status: 'skipped',\n"
        "                reason: 'duplicate_skipped',\n"
        "                action: 'no_patch',\n"
        "                data,\n"
        "                message: dupMsg,\n"
        "              });\n"
        "            }\n"
        "            return;\n"
        "          }\n"
        "          handleNoPatchTaskResult(data);\n"
        "          const isSilentNoOp = (\n"
        "            data.action === 'no_op' &&\n"
        "            !data.stop_signal_detected &&\n"
        "            !data.has_apply_command_mention &&\n"
        "            !data.next_task_handoff &&\n"
        "            !data.all_tasks_completed &&\n"
        "            !data.next_task_error &&\n"
        "            !data.should_retry &&\n"
        "            !data.discovery_stopped &&\n"
        "            !data.exhausted\n"
        "          );\n"
        "          if (forceReverify && isSilentNoOp) {\n"
        "            showToast('aiskel 再検証: 適用可能なパッチやコマンドは見つかりませんでした', false);\n"
        "          }\n"
        "          if (onDone) {\n"
        "            const isExhausted = Boolean(data.exhausted && !data.next_task_handoff && !data.all_tasks_completed);\n"
        "            onDone({\n"
        "              ok: !isSilentNoOp && !isExhausted,\n"
        "              status: isSilentNoOp ? 'not_found' : (isExhausted ? 'error' : 'dispatched'),\n"
        "              reason: isSilentNoOp ? 'no_actionable_target' : (isExhausted ? 'exhausted' : ''),\n"
        "              action: 'no_patch',\n"
        "              data,\n"
        "              message: String(data.message || (isSilentNoOp ? '適用可能なパッチやコマンドは見つかりませんでした' : '応答の検証を完了しました')),\n"
        "            });\n"
        "          }\n"
        "          return;\n"
        "        }\n"
        "        if (res && res.status === 409) {\n"
        "          if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "          const msg = data.message || 'タブがVSCodeと紐づけられていません';\n"
        "          showToast('aiskel スキップ: ' + msg, true);\n"
        "          if (onDone) onDone({ ok: false, status: 'error', reason: 'not_bound', httpStatus: 409, action: 'no_patch', data, message: msg });\n"
        "          return;\n"
        "        }\n"
        "        if (!res || !res.reachable) {\n"
        "          showToast('aiskel パッチ未出力通知エラー: ローカルブリッジに接続できません', true);\n"
