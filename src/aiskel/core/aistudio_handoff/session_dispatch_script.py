        "                ? (' [タスク 1/' + data.total_tasks + ']')\n"
        "                : '';\n"
        "              const discoveryToast = (\n"
        "                'aiskel 探索結果のスコープ限定バンドル' + taskTag + ' (対象 ' +\n"
        "                (data.scoped_primary_count || 0) + ' + 依存 ' + (data.scoped_dependency_count || 0) +\n"
        "                ' 件) で2度目タブを開きました'\n"
        "              );\n"
        "              showToast(discoveryToast, false);\n"
        "              if (onDone) onDone({ ok: true, status: 'dispatched', action: actionName, data, message: discoveryToast });\n"
        "              return;\n"
        "            }\n"
        "            const remainNote = typeof data.remaining_auto_tabs === 'number'\n"
        "              ? '（生成タブの残り自動作成回数: ' + data.remaining_auto_tabs + '）'\n"
        "              : '';\n"
        "            const hasCheckError = Boolean(data.check_attempted && data.check_passed === false);\n"
