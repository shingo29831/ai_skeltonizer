        "    handoffTransport.createHandoff(\n"
        "      {\n"
        "        turn_id: turnId,\n"
        "        response_text: responseText,\n"
        "        source_url: window.location.href,\n"
        "        new_chat_url: newChatUrl,\n"
        "        tab_title: document.title || '',\n"
        "        page_focused: document.hasFocus() && document.visibilityState === 'visible',\n"
        "        stop_handoff: isStopRequested,\n"
        "        discovery_mode: isDiscoveryMode,\n"
        "        user_prompt_text: isDiscoveryMode ? String(opts.userPromptText || '') : undefined,\n"
        "        organize_mode: isOrganizeActive,\n"
        "        allow_rename: isOrganizeActive ? Boolean(activeOrganize.allowRename) : undefined,\n"
        "        config_infer_mode: isConfigInferActive,\n"
        "        config_infer_target: isConfigInferActive ? String(activeConfigInfer.targetFile || 'ai_meta/config.json') : undefined,\n"
        "      },\n"
