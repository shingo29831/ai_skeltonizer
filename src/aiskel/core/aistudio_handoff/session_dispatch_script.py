        "        onDone({\n"
        "          ok: false,\n"
        "          status: 'skipped',\n"
        "          reason: inFlightKeys.has(dedupKey) ? 'in_flight' : 'already_executed',\n"
        "          action: actionName,\n"
        "          message: inFlightKeys.has(dedupKey) ? '引き継ぎ処理を送信中です' : 'この応答は既に実行済みです',\n"
        "        });\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    const newChatUrl = buildSameAccountNewChatUrl(window.location.href);\n"
        "    const activeOrganize = typeof getActiveAutoSplitStateForCurrentProject === 'function'\n"
        "      ? getActiveAutoSplitStateForCurrentProject()\n"
        "      : null;\n"
        "    const isOrganizeActive = Boolean(activeOrganize && activeOrganize.mode === 'organize');\n"
        "    const activeConfigInfer = typeof getActiveConfigInferStateForCurrentProject === 'function'\n"
        "      ? getActiveConfigInferStateForCurrentProject()\n"
        "      : null;\n"
        "    const isConfigInferActive = Boolean(activeConfigInfer && activeConfigInfer.active);\n"
        "    inFlightKeys.add(dedupKey);\n"
        "    const trackLabel = isDiscoveryMode\n"
        "      ? 'aiskel -g スコープ探索中'\n"
        "      : (isOrganizeActive\n"
        "        ? 'aiskel a 実行中 (階層整理)'\n"
        "        : (isConfigInferActive\n"
        "          ? 'aiskel a 実行中 (設定推論)'\n"
