        "    const trackDetail = isDiscoveryMode\n"
        "      ? '対象ファイルと依存バンドルを生成しています'\n"
        "      : (isStopRequested\n"
        "        ? 'パッチの事前検証・適用・テストを実行しています'\n"
        "        : 'パッチ検証・適用および引き継ぎを実行しています');\n"
        "    const trackId = typeof beginTrackedCommand === 'function'\n"
        "      ? beginTrackedCommand({\n"
        "          kind: isDiscoveryMode ? 'discovery_handoff' : 'patch_handoff',\n"
        "          label: trackLabel,\n"
        "          detail: trackDetail,\n"
