        "          return;\n"
        "        }\n"
        "        const errMsg = data.message || res.error || ('HTTP ' + (res.status || '?'));\n"
        "        showToast('aiskel パッチ未出力通知エラー: ' + errMsg, true);\n"
        "        if (onDone) onDone({ ok: false, status: 'error', reason: 'http_error', httpStatus: res.status || 0, action: 'no_patch', data, message: String(errMsg) });\n"
        "      }\n"
