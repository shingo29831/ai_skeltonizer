"""Module: @role: 自動適用エラー再送・終端適用通知・未出力結果処理のクライアントJavaScriptを生成する。"""

def build_handoff_error_js() -> str:
    """自動適用エラーのチャット再送・終端適用通知・未出力タスク結果処理のJSコード群を返す。"""
    return (
        "  const MAX_AUTO_APPLY_ERROR_RETRIES = 2;\n"
        "  const autoApplyErrorRetriesByThread = new Map();\n"
        "  let lastAutoApplyErrorThreadKey = '';\n\n"
        "  function getAutoApplyThreadKey() {\n"
        "    if (typeof parseThreadLocation === 'function') {\n"
        "      const loc = parseThreadLocation(window.location.href);\n"
        "      if (loc && loc.threadKey) return loc.threadKey;\n"
        "    }\n"
        "    return window.location.pathname || '__NEW_CHAT__';\n"
        "  }\n\n"
        "  function resetAutoApplyErrorRetries() {\n"
        "    autoApplyErrorRetriesByThread.delete(getAutoApplyThreadKey());\n"
        "    autoApplyErrorRetriesByThread.delete('__NEW_CHAT__');\n"
        "    lastAutoApplyErrorThreadKey = '';\n"
        "  }\n\n"
        "  function sendAutoApplyErrorToChat(data, detail, errorTitle, options) {\n"
        "    if (typeof isMonitoringActive === 'function' && !isMonitoringActive()) return;\n"
        "    const opts = options || {};\n"
        "    const useServerRetryBudget = Boolean(opts.useServerRetryBudget);\n"
        "    const errorReport = String(data.apply_error_report || detail || 'パッチの適用に失敗しました');\n"
        "    const autoRunActive = typeof isAutoRunEffectiveEnabled === 'function' && isAutoRunEffectiveEnabled();\n"
        "    if (!autoRunActive || typeof waitAndPasteText !== 'function') {\n"
        "      if (typeof reportBridgeError === 'function') {\n"
        "        reportBridgeError(errorTitle, detail, errorReport);\n"
        "      } else {\n"
        "        showToast(errorTitle + ': ' + detail, true);\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    const threadKey = getAutoApplyThreadKey();\n"
        "    // 新規チャット送信後に/prompts/<id>へURL昇格した場合でも連続失敗回数を引き継ぐ\n"
        "    if (\n"
        "      threadKey !== '__NEW_CHAT__' &&\n"
        "      lastAutoApplyErrorThreadKey === '__NEW_CHAT__' &&\n"
        "      !autoApplyErrorRetriesByThread.has(threadKey) &&\n"
        "      autoApplyErrorRetriesByThread.has('__NEW_CHAT__')\n"
        "    ) {\n"
        "      autoApplyErrorRetriesByThread.set(threadKey, autoApplyErrorRetriesByThread.get('__NEW_CHAT__'));\n"
        "      autoApplyErrorRetriesByThread.delete('__NEW_CHAT__');\n"
        "    }\n"
        "    let nextRetry = 0;\n"
        "    let maxRetryLimit = MAX_AUTO_APPLY_ERROR_RETRIES;\n"
        "    if (useServerRetryBudget) {\n"
        "      nextRetry = opts.retryCount != null ? Number(opts.retryCount) : (data.retry_count != null ? Number(data.retry_count) : 1);\n"
        "      maxRetryLimit = opts.maxRetries != null ? Number(opts.maxRetries) : (data.max_retries != null ? Number(data.max_retries) : MAX_AUTO_APPLY_ERROR_RETRIES);\n"
        "    } else {\n"
        "      nextRetry = Number(autoApplyErrorRetriesByThread.get(threadKey) || 0) + 1;\n"
        "      if (nextRetry > MAX_AUTO_APPLY_ERROR_RETRIES) {\n"
        "        if (typeof reportBridgeError === 'function') {\n"
        "          reportBridgeError(errorTitle + ' (連続エラー停止)', detail, errorReport);\n"
        "        } else {\n"
        "          showToast(errorTitle + ': 連続失敗のため自動送信を停止しました', true);\n"
        "        }\n"
        "        return;\n"
        "      }\n"
        "      autoApplyErrorRetriesByThread.set(threadKey, nextRetry);\n"
        "      lastAutoApplyErrorThreadKey = threadKey;\n"
        "    }\n"
        "    const showFallbackError = (prefix) => {\n"
        "      const msg = prefix ? (prefix + '\\n' + detail) : detail;\n"
        "      if (typeof reportBridgeError === 'function') {\n"
        "        reportBridgeError(errorTitle, msg, errorReport);\n"
        "      } else {\n"
        "        showToast(errorTitle + ': ' + detail, true);\n"
        "      }\n"
        "    };\n"
        "    showToast(errorTitle + ': ' + detail, true);\n"
        "    showToast('aiskel エラー内容をチャットへ送信します (' + nextRetry + '/' + maxRetryLimit + ')', true);\n"
        "    const started = waitAndPasteText({\n"
        "      textToPaste: errorReport,\n"
        "      priority: 'normal',\n"
        "      timeoutMs: typeof SUMMARY_PROMPT_PASTE_TIMEOUT_MS === 'number' ? SUMMARY_PROMPT_PASTE_TIMEOUT_MS : 10000,\n"
        "      settleMs: 120,\n"
        "      requireEmptyInput: false,\n"
        "      replaceExisting: false,\n"
        "      exactDuplicateCheck: false,\n"
        "      abortIf: () => typeof isMonitoringActive === 'function' && !isMonitoringActive(),\n"
        "      onSuccess: (_alreadyPresent, _insertedWithDraft, pasteMeta) => {\n"
        "        if (typeof isMonitoringActive === 'function' && !isMonitoringActive()) return;\n"
        "        if (typeof scheduleAutoRunAfterPaste !== 'function' || typeof shouldScheduleAutoRun !== 'function') {\n"
        "          showFallbackError('自動送信機能が利用できないためエラー文を貼り付けました:');\n"
        "          return;\n"
        "        }\n"
        "        const preSnap = pasteMeta && pasteMeta.preSnap ? pasteMeta.preSnap : null;\n"
        "        const turnCtx = typeof getTurnContext === 'function'\n"
        "          ? getTurnContext()\n"
        "          : { userTurnCount: 0, modelTurns: [], modelIndices: [] };\n"
        "        const dispatchCtx = {\n"
        "          url: window.location.href,\n"
        "          resolvedUrl: window.location.href,\n"
        "          allowBackgroundDomSubmit: true,\n"
        "          domPasteVerified: true,\n"
        "          resetConsecutiveCounter: true,\n"
        "          modelTurnRefs: turnCtx.modelTurns.slice(),\n"
        "          modelTurnSigs: turnCtx.modelTurns.map((turn) => buildModelTurnsContentSignature([turn])),\n"
        "          modelContentSig: buildModelContentSignature(turnCtx),\n"
        "          userTurnCountBefore: turnCtx.userTurnCount,\n"
        "          commandsKey: 'APPLY_ERR::' + threadKey + '::' + nextRetry + '::' + Date.now(),\n"
        "          pasteSeqBefore: pasteEventSeq,\n"
        "          inputTextBefore: preSnap ? preSnap.text : '',\n"
        "          chipCountBefore: preSnap ? preSnap.chipCount : 0,\n"
        "          chipSignatureBefore: preSnap ? preSnap.chipSignature : '0::',\n"
        "          hadContentBefore: preSnap ? preSnap.hasContent : false,\n"
        "          responsePasted: true,\n"
        "          commandOk: true,\n"
        "        };\n"
        "        const syntheticResponse = {\n"
        "          pasted: true,\n"
        "          auto_run: isAutoRunEffectiveEnabled(),\n"
        "          auto_run_allowed: autoRunAllowed,\n"
        "        };\n"
        "        if (!shouldScheduleAutoRun(syntheticResponse, dispatchCtx)) {\n"
        "          showFallbackError('自動送信をスケジュールできませんでした:');\n"
        "          return;\n"
        "        }\n"
        "        scheduleAutoRunAfterPaste(dispatchCtx);\n"
        "      },\n"
        "      onAborted: () => {\n"
        "        if (typeof isMonitoringActive === 'function' && !isMonitoringActive()) return;\n"
        "        showFallbackError('チャット欄へのエラー貼付が中断されました:');\n"
        "      },\n"
        "      onTimeout: () => {\n"
        "        if (typeof isMonitoringActive === 'function' && !isMonitoringActive()) return;\n"
        "        showFallbackError('チャット入力欄が見つからずエラーを送信できませんでした:');\n"
        "      },\n"
        "      onVerifyFailed: () => {\n"
        "        if (typeof isMonitoringActive === 'function' && !isMonitoringActive()) return;\n"
        "        showFallbackError('チャット欄へのエラー反映を確認できませんでした:');\n"
        "      },\n"
        "    });\n"
        "    if (!started) {\n"
        "      showFallbackError('チャット貼付タスクを開始できませんでした:');\n"
        "    }\n"
        "  }\n\n"
        "  function formatAppliedCommandNotice(data, fallbackMessage) {\n"
        "    const rawDetail = String((data && data.apply_message) || '').trim();\n"
        "    if (!rawDetail) return fallbackMessage;\n"
        "    if (!fallbackMessage || rawDetail === fallbackMessage) return rawDetail;\n"
        "    if (data && data.stop_signal_detected) {\n"
        "      return 'aiskel 欠陥なし合図を検知 -> ' + rawDetail;\n"
        "    }\n"
        "    if (data && data.limit_reached) {\n"
        "      return 'aiskel 新規タブ上限到達 -> ' + rawDetail;\n"
        "    }\n"
        "    return rawDetail;\n"
        "  }\n\n"
        "  function handleTerminalAutoApplyNotice(data, appliedMessage, skippedFallback) {\n"
        "    if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "    if (typeof handleConfigInferTerminalApplyResult === 'function' && handleConfigInferTerminalApplyResult(data)) {\n"
        "      return;\n"
        "    }\n"
        "    if (typeof handleAutoSplitTerminalApplyResult === 'function' && handleAutoSplitTerminalApplyResult(data)) {\n"
        "      return;\n"
        "    }\n"
        "    if (data.apply_attempted) {\n"
        "      if (data.applied) {\n"
        "        resetAutoApplyErrorRetries();\n"
        "        if (typeof clearErrorPanel === 'function') clearErrorPanel();\n"
        "        showToast(formatAppliedCommandNotice(data, appliedMessage), Boolean(data.apply_test_failed));\n"
        "        if (data.next_task_handoff) {\n"
        "          showToast(\n"
        "            'aiskel 分割タスク (' + (data.task_index || '?') + '/' + (data.total_tasks || '?') + ') を新タブで開始します',\n"
        "            false\n"
        "          );\n"
        "        } else if (data.all_tasks_completed) {\n"
        "          showToast(\n"
        "            'aiskel 分割タスク: 全 ' + (data.total_tasks || 0) + ' 件の実装・適用が完了しました！',\n"
        "            false\n"
        "          );\n"
        "        } else if (data.next_task_error) {\n"
        "          showToast('aiskel 次タスク引き継ぎエラー: ' + data.next_task_error, true);\n"
        "        }\n"
        "      } else {\n"
        "        const detail = data.apply_message || 'パッチの自動適用に失敗しました';\n"
        "        const errorTitle = data.apply_phase === 'check'\n"
        "          ? 'aiskel 置換検証エラー (aiskel check)'\n"
        "          : 'aiskel 自動適用エラー (aiskel a)';\n"
        "        sendAutoApplyErrorToChat(data, detail, errorTitle);\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    if (data.next_task_handoff) {\n"
        "      resetAutoApplyErrorRetries();\n"
        "      if (typeof clearErrorPanel === 'function') clearErrorPanel();\n"
        "      const prefix = data.task_skipped ? 'aiskel タスクスキップ' : 'aiskel 変更なし完了';\n"
        "      showToast(\n"
        "        prefix + ' -> 分割タスク (' + (data.task_index || '?') + '/' + (data.total_tasks || '?') + ') を新タブで開始します',\n"
        "        false\n"
        "      );\n"
        "      return;\n"
        "    }\n"
        "    if (data.all_tasks_completed) {\n"
        "      resetAutoApplyErrorRetries();\n"
        "      if (typeof clearErrorPanel === 'function') clearErrorPanel();\n"
        "      showToast(\n"
        "        'aiskel 分割タスク: 全 ' + (data.total_tasks || 0) + ' 件が完了しました！',\n"
        "        false\n"
        "      );\n"
        "      return;\n"
        "    }\n"
        "    if (data.next_task_error) {\n"
        "      showToast('aiskel 次タスク引き継ぎエラー: ' + data.next_task_error, true);\n"
        "      return;\n"
        "    }\n"
        "    skippedFallback();\n"
        "  }\n\n"
        "  function handleNoPatchTaskResult(data) {\n"
        "    if (!data || data.duplicate_skipped) return;\n"
        "    if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "    if (data.should_retry && data.apply_error_report) {\n"
        "      const retryTitle = data.discovery_mode\n"
        "        ? 'aiskel 探索出力不備（<task>/<dirs> 再出力要求）'\n"
        "        : 'aiskel パッチ未出力（再出力要求）';\n"
        "      const retryFallback = data.discovery_mode\n"
        "        ? '有効な <task> / <dirs> が出力されませんでした'\n"
        "        : 'コードブロック・パッチが出力されませんでした';\n"
        "      sendAutoApplyErrorToChat(\n"
        "        data,\n"
        "        data.message || retryFallback,\n"
        "        retryTitle,\n"
        "        {\n"
        "          useServerRetryBudget: true,\n"
        "          retryCount: data.retry_count,\n"
        "          maxRetries: data.max_retries,\n"
        "        }\n"
        "      );\n"
        "      return;\n"
        "    }\n"
        "    if (data.next_task_handoff || data.all_tasks_completed || data.next_task_error) {\n"
        "      handleTerminalAutoApplyNotice(data, data.message || 'タスクを進行しました', () => {});\n"
        "      return;\n"
        "    }\n"
        "    if (data.discovery_stopped || data.action === 'discovery_stopped') {\n"
        "      resetAutoApplyErrorRetries();\n"
        "      if (typeof clearErrorPanel === 'function') clearErrorPanel();\n"
        "      showToast('aiskel 終了合図を検知したため1度目探索を完了しました', false);\n"
        "      return;\n"
        "    }\n"
        "    if (data.action === 'no_op' && data.stop_signal_detected) {\n"
        "      resetAutoApplyErrorRetries();\n"
        "      if (typeof clearErrorPanel === 'function') clearErrorPanel();\n"
        "      showToast('aiskel 完了合図を検知しました（適用対象の置換コードがないためスキップしました）', false);\n"
        "      return;\n"
        "    }\n"
        "    if (data.action === 'no_op' && data.has_apply_command_mention) {\n"
        "      showToast('aiskel a が検出されましたが適用可能なパッチが見つかりませんでした', false);\n"
        "      return;\n"
        "    }\n"
        "    if (data.exhausted) {\n"
        "      if (typeof isAutoSplitActiveForCurrentProject === 'function' && isAutoSplitActiveForCurrentProject()) {\n"
        "        if (typeof clearAutoSplitState === 'function') clearAutoSplitState();\n"
        "        if (typeof syncAutoSplitUiState === 'function') syncAutoSplitUiState();\n"
        "      }\n"
        "      if (typeof isConfigInferActiveForCurrentProject === 'function' && isConfigInferActiveForCurrentProject()) {\n"
        "        if (typeof clearConfigInferState === 'function') clearConfigInferState();\n"
        "        if (typeof syncConfigInferUiState === 'function') syncConfigInferUiState();\n"
        "      }\n"
        "      const stopTitle = data.discovery_mode\n"
        "        ? 'aiskel 探索出力未検知停止'\n"
        "        : 'aiskel パッチ未出力停止';\n"
        "      const defaultMsg = data.discovery_mode\n"
        "        ? '1度目探索の <task>/<dirs> 未出力が連続したため停止しました'\n"
        "        : 'コードブロック・パッチ未出力が連続したため停止しました';\n"
        "      const msg = String(data.message || defaultMsg);\n"
        "      if (typeof reportBridgeError === 'function') {\n"
        "        reportBridgeError(stopTitle, msg, msg);\n"
        "      } else {\n"
        "        showToast(msg, true);\n"
        "      }\n"
        "    }\n"
        "  }\n\n"
    )
