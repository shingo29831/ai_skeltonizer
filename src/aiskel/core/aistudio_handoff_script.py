"""Module: @role: パッチ出力検知時の応答・要約引き継ぎおよび新規タブ貼り付けのクライアントJavaScriptを生成する。"""


def build_patch_handoff_js() -> str:
    """パッチ検知時の新規タブ引き継ぎ送信および遷移先タブでの自動貼り付け・紐づけスクリプトを返す。"""
    return (
        "  const hasHandoffTransport = typeof handoffTransport !== 'undefined' && handoffTransport !== null;\n"
        "  const HANDOFF_PASTE_TIMEOUT_MS = 25000;\n"
        "  const HANDOFF_PASTE_POLL_MS = 250;\n"
        "  const HANDOFF_HYDRATION_SETTLE_MS = 400;\n"
        "  const HANDOFF_VERIFY_DELAY_MS = 350;\n"
        "  const HANDOFF_MAX_PASTE_RETRIES = 2;\n"
        "  const HANDOFF_CLAIM_RETRY_MS = 500;\n"
        "  const HANDOFF_MAX_CLAIM_RETRIES = 3;\n\n"
        "  const BIND_PROMPT_PASTE_TIMEOUT_MS = 8000;\n"
        "  let activePasteTask = null;\n"
        "  let pasteTaskSeq = 0;\n"
        "  let handoffSessionActive = false;\n\n"
        "  function hasActiveHandoffUrlMarker() {\n"
        "    if (typeof readExtensionHandoffIdFromHash === 'function' && readExtensionHandoffIdFromHash()) {\n"
        "      return true;\n"
        "    }\n"
        "    if (typeof readPendingUserscriptHandoffId === 'function' && readPendingUserscriptHandoffId()) {\n"
        "      return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function isHandoffPendingOrActive() {\n"
        "    if (handoffSessionActive || hasActiveHandoffUrlMarker()) return true;\n"
        "    return Boolean(activePasteTask && activePasteTask.priority === 'handoff');\n"
        "  }\n\n"
        "  function normalizeVerifyText(text) {\n"
        "    return String(text || '').replace(/\\r\\n/g, '\\n').trim();\n"
        "  }\n\n"
        "  function collapseWhitespaceForVerify(text) {\n"
        "    return String(text || '').replace(/\\s+/g, ' ').trim();\n"
        "  }\n\n"
        "  function matchAnchoredText(haystack, needle) {\n"
        "    if (!haystack || !needle) return false;\n"
        "    if (needle.length <= 120) {\n"
        "      return haystack.includes(needle);\n"
        "    }\n"
        "    return haystack.includes(needle.slice(0, 60)) && haystack.includes(needle.slice(-60));\n"
        "  }\n\n"
        "  function isHandoffTextPresent(currentVal, expectedText) {\n"
        "    const normCurrent = normalizeVerifyText(currentVal);\n"
        "    const normExpected = normalizeVerifyText(expectedText);\n"
        "    if (!normCurrent || !normExpected) return false;\n"
        "    if (matchAnchoredText(normCurrent, normExpected)) return true;\n"
        "    // contenteditableでの連続改行/空白のDOM正規化差異を許容するため空白縮約でも照合\n"
        "    return matchAnchoredText(\n"
        "      collapseWhitespaceForVerify(currentVal),\n"
        "      collapseWhitespaceForVerify(expectedText)\n"
        "    );\n"
        "  }\n\n"
        "  function triggerPatchHandoff(ctx, finishedRunSeq) {\n"
        "    if (!hasHandoffTransport) return;\n"
        "    const responseText = extractFullResponseText(ctx.modelTurns);\n"
        "    if (!responseText) return;\n"
        "    const turnId = buildTurnIdentifier(ctx, finishedRunSeq);\n"
        "    const dedupKey = turnId + '::PATCH::' + hashText(responseText);\n"
        "    if (executedKeys.has(dedupKey) || inFlightKeys.has(dedupKey)) return;\n"
        "    const newChatUrl = buildSameAccountNewChatUrl(window.location.href);\n"
        "    inFlightKeys.add(dedupKey);\n"
        "    handoffTransport.createHandoff(\n"
        "      {\n"
        "        turn_id: turnId,\n"
        "        response_text: responseText,\n"
        "        source_url: window.location.href,\n"
        "        new_chat_url: newChatUrl,\n"
        "        tab_title: document.title || '',\n"
        "        page_focused: document.hasFocus() && document.visibilityState === 'visible',\n"
        "      },\n"
        "      (res) => {\n"
        "        inFlightKeys.delete(dedupKey);\n"
        "        const data = (res && res.data) || {};\n"
        "        if (res && res.connected && data.ok) {\n"
        "          markExecuted(dedupKey);\n"
        "          if (!data.skipped) {\n"
        "            if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "            showToast('aiskel パッチ応答をコピーし、新しいタブへ要約とともに引き継ぎました', false);\n"
        "          }\n"
        "          return;\n"
        "        }\n"
        "        if (res && res.status === 409) {\n"
        "          if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "          showToast('aiskel スキップ: ' + (data.message || 'タブがVSCodeと紐づけられていません'), true);\n"
        "          return;\n"
        "        }\n"
        "        if (!res || !res.reachable) {\n"
        "          showToast('aiskel 新規タブ引き継ぎエラー: ローカルブリッジに接続できません', true);\n"
        "          return;\n"
        "        }\n"
        "        showToast('aiskel 新規タブ引き継ぎエラー: ' + (data.message || res.error || ('HTTP ' + (res.status || '?'))), true);\n"
        "      }\n"
        "    );\n"
        "  }\n\n"
        "  function cancelActivePasteTask() {\n"
        "    if (activePasteTask && typeof activePasteTask.cancel === 'function') {\n"
        "      activePasteTask.cancel();\n"
        "    }\n"
        "    activePasteTask = null;\n"
        "  }\n\n"
        "  function waitAndPasteText(options) {\n"
        "    const textToPaste = options.textToPaste;\n"
        "    const priority = options.priority || 'normal';\n"
        "    if (activePasteTask && activePasteTask.priority === 'handoff' && priority !== 'handoff') {\n"
        "      return false;\n"
        "    }\n"
        "    cancelActivePasteTask();\n"
        "    const taskId = ++pasteTaskSeq;\n"
        "    const timeoutMs = options.timeoutMs || HANDOFF_PASTE_TIMEOUT_MS;\n"
        "    const settleMs = options.settleMs !== undefined ? options.settleMs : HANDOFF_HYDRATION_SETTLE_MS;\n"
        "    const requireEmptyInput = Boolean(options.requireEmptyInput);\n"
        "    const abortIf = options.abortIf || null;\n"
        "    const deadline = Date.now() + timeoutMs;\n"
        "    let finished = false;\n"
        "    let observerHandle = null;\n"
        "    let pollTimer = null;\n"
        "    let settleTimer = null;\n"
        "    let verifyTimer = null;\n"
        "    let settlingPaste = false;\n"
        "    let pasteRetries = 0;\n"
        "    let draftPrefix = '';\n\n"
        "    const cleanup = () => {\n"
        "      if (observerHandle) {\n"
        "        observerHandle.disconnect();\n"
        "        observerHandle = null;\n"
        "      }\n"
        "      if (pollTimer !== null) {\n"
        "        window.clearTimeout(pollTimer);\n"
        "        pollTimer = null;\n"
        "      }\n"
        "      if (settleTimer !== null) {\n"
        "        window.clearTimeout(settleTimer);\n"
        "        settleTimer = null;\n"
        "      }\n"
        "      if (verifyTimer !== null) {\n"
        "        window.clearTimeout(verifyTimer);\n"
        "        verifyTimer = null;\n"
        "      }\n"
        "      if (activePasteTask && activePasteTask.id === taskId) {\n"
        "        activePasteTask = null;\n"
        "      }\n"
        "    };\n\n"
        "    const isInactive = () => finished || taskId !== pasteTaskSeq;\n"
        "    const finishWithAbort = () => {\n"
        "      finished = true;\n"
        "      cleanup();\n"
        "      if (options.onAborted) options.onAborted();\n"
        "    };\n\n"
        "    activePasteTask = {\n"
        "      id: taskId,\n"
        "      priority,\n"
        "      cancel: () => {\n"
        "        if (finished) return;\n"
        "        finished = true;\n"
        "        cleanup();\n"
        "      },\n"
        "    };\n\n"
        "    const attemptPaste = () => {\n"
        "      if (isInactive() || settlingPaste) return;\n"
        "      if (abortIf && abortIf()) {\n"
        "        finishWithAbort();\n"
        "        return;\n"
        "      }\n"
        "      if (Date.now() > deadline) {\n"
        "        finished = true;\n"
        "        cleanup();\n"
        "        if (options.onTimeout) options.onTimeout();\n"
        "        return;\n"
        "      }\n"
        "      if (isInferring()) {\n"
        "        pollTimer = window.setTimeout(attemptPaste, HANDOFF_PASTE_POLL_MS);\n"
        "        return;\n"
        "      }\n"
        "      const inputEl = findPromptInputElement();\n"
        "      if (!inputEl) {\n"
        "        pollTimer = window.setTimeout(attemptPaste, HANDOFF_PASTE_POLL_MS);\n"
        "        return;\n"
        "      }\n"
        "      settlingPaste = true;\n"
        "      // Angular SPAの初期フォームリセットで入力が消されないよう少し待機してから貼り付ける\n"
        "      settleTimer = window.setTimeout(() => {\n"
        "        settleTimer = null;\n"
        "        if (isInactive()) return;\n"
        "        if (abortIf && abortIf()) {\n"
        "          finishWithAbort();\n"
        "          return;\n"
        "        }\n"
        "        const readyEl = findPromptInputElement() || inputEl;\n"
        "        if (!readyEl || !readyEl.isConnected) {\n"
        "          settlingPaste = false;\n"
        "          pollTimer = window.setTimeout(attemptPaste, HANDOFF_PASTE_POLL_MS);\n"
        "          return;\n"
        "        }\n"
        "        const existing = getEditableInputText(readyEl);\n"
        "        if (isHandoffTextPresent(existing, textToPaste)) {\n"
        "          finished = true;\n"
        "          cleanup();\n"
        "          if (options.onSuccess) options.onSuccess(true);\n"
        "          return;\n"
        "        }\n"
        "        // リトライ時は初回貼付の未反映断片が残るため空入力検査と下書き取得は初回のみ実施\n"
        "        if (pasteRetries === 0) {\n"
        "          if (requireEmptyInput && typeof isPromptInputEmpty === 'function' && !isPromptInputEmpty(readyEl)) {\n"
        "            finished = true;\n"
        "            cleanup();\n"
        "            if (options.onSkippedNonEmpty) options.onSkippedNonEmpty();\n"
        "            return;\n"
        "          }\n"
        "          const placeholder = (readyEl.getAttribute('placeholder') || readyEl.getAttribute('data-placeholder') || '').trim();\n"
        "          const existingTrimmed = existing.trim();\n"
        "          if (!requireEmptyInput && existingTrimmed && existingTrimmed !== placeholder) {\n"
        "            draftPrefix = existing + '\\n\\n';\n"
        "          }\n"
        "        }\n"
        "        const nextValue = draftPrefix + textToPaste;\n"
        "        const ok = pasteTextIntoPromptInput(readyEl, nextValue);\n"
        "        if (!ok) {\n"
        "          settlingPaste = false;\n"
        "          pollTimer = window.setTimeout(attemptPaste, HANDOFF_PASTE_POLL_MS);\n"
        "          return;\n"
        "        }\n"
        "        verifyTimer = window.setTimeout(() => {\n"
        "          verifyTimer = null;\n"
        "          if (isInactive()) return;\n"
        "          // 貼付直後の手動送信や画面遷移で空になった場合に誤リトライ・誤エラーを出さないよう検証前にも確認\n"
        "          if (abortIf && abortIf()) {\n"
        "            finishWithAbort();\n"
        "            return;\n"
        "          }\n"
        "          const verifyEl = findPromptInputElement() || readyEl;\n"
        "          const currentVal = verifyEl ? getEditableInputText(verifyEl) : '';\n"
        "          // 既存下書きやプレースホルダーのみ残った場合を弾くため貼付テキスト本体のアンカー一致を検証\n"
        "          if (!verifyEl || !isHandoffTextPresent(currentVal, textToPaste)) {\n"
        "            if (pasteRetries < HANDOFF_MAX_PASTE_RETRIES) {\n"
        "              pasteRetries += 1;\n"
        "              settlingPaste = false;\n"
        "              pollTimer = window.setTimeout(attemptPaste, HANDOFF_PASTE_POLL_MS);\n"
        "              return;\n"
        "            }\n"
        "            finished = true;\n"
        "            cleanup();\n"
        "            if (options.onVerifyFailed) options.onVerifyFailed();\n"
        "            return;\n"
        "          }\n"
        "          finished = true;\n"
        "          cleanup();\n"
        "          if (options.onSuccess) options.onSuccess(false);\n"
        "        }, HANDOFF_VERIFY_DELAY_MS);\n"
        "      }, settleMs);\n"
        "    };\n\n"
        "    observerHandle = new MutationObserver(() => {\n"
        "      if (!isInactive() && !settlingPaste && findPromptInputElement()) {\n"
        "        attemptPaste();\n"
        "      }\n"
        "    });\n"
        "    if (document.body) {\n"
        "      observerHandle.observe(document.body, { childList: true, subtree: true });\n"
        "    }\n"
        "    attemptPaste();\n"
        "    return true;\n"
        "  }\n\n"
        "  function pasteBindPromptIfChatEmpty(promptText, options) {\n"
        "    const cleanPrompt = String(promptText || '').trim();\n"
        "    if (!cleanPrompt || isHandoffPendingOrActive()) return false;\n"
        "    if (typeof isMonitoringActive === 'function' && !isMonitoringActive()) return false;\n"
        "    if (typeof isChatConversationEmpty !== 'function' || !isChatConversationEmpty()) return false;\n"
        "    const opts = typeof options === 'function' ? { onPasted: options } : (options || {});\n"
        "    return waitAndPasteText({\n"
        "      textToPaste: cleanPrompt,\n"
        "      priority: 'normal',\n"
        "      timeoutMs: BIND_PROMPT_PASTE_TIMEOUT_MS,\n"
        "      settleMs: 120,\n"
        "      requireEmptyInput: true,\n"
        "      abortIf: () => (typeof isMonitoringActive === 'function' && !isMonitoringActive()) || isHandoffPendingOrActive() || !isChatConversationEmpty() || document.visibilityState !== 'visible',\n"
        "      onAborted: opts.onAborted,\n"
        "      onSuccess: (alreadyPresent) => {\n"
        "        if (!alreadyPresent) {\n"
        "          showToast('aiskel デフォルトプロンプトを貼り付けました', false);\n"
        "        }\n"
        "        if (opts.onPasted) opts.onPasted(alreadyPresent);\n"
        "      },\n"
        "      onSkippedNonEmpty: () => {},\n"
        "      onTimeout: () => {\n"
        "        showToast('aiskel プロンプト入力欄が見つからず貼り付けをスキップしました', true);\n"
        "      },\n"
        "      onVerifyFailed: () => {\n"
        "        showToast('aiskel デフォルトプロンプトの貼り付けを確認できませんでした', true);\n"
        "      },\n"
        "    });\n"
        "  }\n\n"
        "  function waitAndPasteHandoff(handoffId, textToPaste) {\n"
        "    handoffSessionActive = true;\n"
        "    waitAndPasteText({\n"
        "      textToPaste,\n"
        "      priority: 'handoff',\n"
        "      timeoutMs: HANDOFF_PASTE_TIMEOUT_MS,\n"
        "      settleMs: HANDOFF_HYDRATION_SETTLE_MS,\n"
        "      requireEmptyInput: false,\n"
        "      onSuccess: () => {\n"
        "        handoffSessionActive = false;\n"
        "        handoffTransport.ackHandoff(handoffId, () => {});\n"
        "        showToast('aiskel レビュー指示・応答・要約を貼り付け、VSCodeと紐づけました', false);\n"
        "      },\n"
        "      onAborted: () => {\n"
        "        handoffSessionActive = false;\n"
        "      },\n"
        "      onTimeout: () => {\n"
        "        handoffSessionActive = false;\n"
        "        showToast('aiskel 新規タブの入力欄検出がタイムアウトしました（手動で貼り付けてください）', true);\n"
        "      },\n"
        "      onVerifyFailed: () => {\n"
        "        handoffSessionActive = false;\n"
        "        showToast('aiskel 自動貼り付けの反映を確認できませんでした（手動で貼り付けてください）', true);\n"
        "      },\n"
        "    });\n"
        "  }\n\n"
        "  function runPendingHandoffPasteOnLoad(attempt) {\n"
        "    if (!hasHandoffTransport || typeof handoffTransport.claimHandoff !== 'function') return;\n"
        "    const retryCount = attempt || 0;\n"
        "    if (hasActiveHandoffUrlMarker()) {\n"
        "      handoffSessionActive = true;\n"
        "    }\n"
        "    handoffTransport.claimHandoff((res) => {\n"
        "      if (!res || !res.reachable) {\n"
        "        if (retryCount < HANDOFF_MAX_CLAIM_RETRIES) {\n"
        "          window.setTimeout(() => runPendingHandoffPasteOnLoad(retryCount + 1), HANDOFF_CLAIM_RETRY_MS);\n"
        "        } else {\n"
        "          handoffSessionActive = false;\n"
        "        }\n"
        "        return;\n"
        "      }\n"
        "      if (!res.data || !res.data.found || !res.data.handoff) {\n"
        "        handoffSessionActive = false;\n"
        "        return;\n"
        "      }\n"
        "      if (res.data.binding && typeof applyBindingResponse === 'function') {\n"
        "        applyBindingResponse({\n"
        "          reachable: true,\n"
        "          connected: true,\n"
        "          status: 200,\n"
        "          data: res.data.binding,\n"
        "          error: '',\n"
        "        });\n"
        "      }\n"
        "      const handoff = res.data.handoff;\n"
        "      const textToPaste = handoff.combined_text || [handoff.response_text, handoff.summary_text].filter(Boolean).join('\\n\\n');\n"
        "      if (!textToPaste) {\n"
        "        handoffSessionActive = false;\n"
        "        handoffTransport.ackHandoff(handoff.handoff_id, () => {});\n"
        "        return;\n"
        "      }\n"
        "      waitAndPasteHandoff(handoff.handoff_id, textToPaste);\n"
        "    });\n"
        "  }\n\n"
    )
