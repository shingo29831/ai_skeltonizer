def build_extension_handoff_transport_js() -> str:
    """Chrome/Edge/Firefox拡張機能Content Script用の新規タブ引き継ぎ通信アダプタを生成する。"""
    return (
        "  function readExtensionHandoffIdFromHash() {\n"
        "    const rawHash = (window.location.hash || '').replace(/^#/, '');\n"
        "    if (!rawHash) return '';\n"
        "    for (const part of rawHash.split('&')) {\n"
        "      if (part.startsWith('aiskel_handoff=')) {\n"
        "        try {\n"
        "          return decodeURIComponent(part.slice('aiskel_handoff='.length));\n"
        "        } catch (_e) {\n"
        "          return part.slice('aiskel_handoff='.length);\n"
        "        }\n"
        "      }\n"
        "    }\n"
        "    return '';\n"
        "  }\n"
        "  function stripExtensionHandoffHash() {\n"
        "    try {\n"
        "      const rawHash = (window.location.hash || '').replace(/^#/, '');\n"
        "      if (!rawHash) return;\n"
        "      const kept = rawHash.split('&').filter((part) => part && !part.startsWith('aiskel_handoff='));\n"
        "      const nextHash = kept.length ? '#' + kept.join('&') : '';\n"
        "      window.history.replaceState(null, '', window.location.pathname + window.location.search + nextHash);\n"
        "    } catch (_e) {}\n"
        "  }\n"
        "  const handoffTransport = {\n"
        "    createHandoff: (payload, onDone) => {\n"
        "      try {\n"
        "        chrome.runtime.sendMessage({ type: 'AISKEL_PATCH_HANDOFF', payload }, (res) => {\n"
        "          if (chrome.runtime.lastError || !res) {\n"
        "            if (onDone) onDone({ reachable: false, connected: false, status: 0, data: {}, error: '' });\n"
        "            return;\n"
        "          }\n"
        "          if (onDone) onDone(res);\n"
        "        });\n"
        "      } catch (_err) {\n"
        "        if (onDone) onDone({ reachable: false, connected: false, status: 0, data: {}, error: '' });\n"
        "      }\n"
        "    },\n"
        "    claimHandoff: (cb) => {\n"
        "      try {\n"
        "        chrome.runtime.sendMessage(\n"
        "          {\n"
        "            type: 'AISKEL_TAKE_HANDOFF',\n"
        "            handoff_id: readExtensionHandoffIdFromHash(),\n"
        "            tab_title: document.title || '',\n"
        "            tab_url: window.location.href,\n"
        "          },\n"
        "          (res) => {\n"
        "            if (chrome.runtime.lastError || !res) {\n"
        "              cb({ reachable: false, connected: false, data: {} });\n"
        "              return;\n"
        "            }\n"
        "            cb(res);\n"
        "          }\n"
        "        );\n"
        "      } catch (_err) {\n"
        "        cb({ reachable: false, connected: false, data: {} });\n"
        "      }\n"
        "    },\n"
        "    ackHandoff: (handoffId, cb) => {\n"
        "      stripExtensionHandoffHash();\n"
        "      try {\n"
        "        chrome.runtime.sendMessage({ type: 'AISKEL_ACK_HANDOFF', handoff_id: handoffId || '' }, (res) => {\n"
        "          if (cb) cb(res || {});\n"
        "        });\n"
        "      } catch (_err) {\n"
        "        if (cb) cb({});\n"
        "      }\n"
        "    },\n"
        "  };\n"
    )


def build_userscript_binding_transport_js(
    base_url: str,
    token: Optional[str] = None,
) -> str:
    """Tampermonkey/Violentmonkey用のタブ紐づけ通信アダプタを生成する。"""
    base_literal = json.dumps(base_url.rstrip("/"))
    token_literal = json.dumps(token or "")
    return (
        f"  const BRIDGE_BASE_URL = {base_literal};\n"
        f"  const BRIDGE_TOKEN = {token_literal};\n"
        "  let userscriptTabBound = false;\n"
        "  let userscriptUnbindSent = false;\n"
        "  function getUserscriptTabId() {\n"
        "    const KEY = 'aiskel_userscript_tab_id';\n"
        "    try {\n"
        "      let existing = window.sessionStorage.getItem(KEY);\n"
        "      if (!existing) {\n"
        "        existing = 'us-tab-' + (typeof crypto !== 'undefined' && crypto.randomUUID ? crypto.randomUUID() : Math.random().toString(36).slice(2));\n"
        "        window.sessionStorage.setItem(KEY, existing);\n"
        "      }\n"
        "      return existing;\n"
        "    } catch (_e) {\n"
        "      return 'us-tab-fallback';\n"
        "    }\n"
        "  }\n"
        "  function gmRequest(path, method, bodyObj, cb) {\n"
        "    if (typeof GM_xmlhttpRequest !== 'function') {\n"
        "      cb({ reachable: false, connected: false, status: 0, data: {}, error: 'GM_xmlhttpRequest unavailable' });\n"
        "      return;\n"
        "    }\n"
        "    const headers = { 'Content-Type': 'application/json' };\n"
        "    if (BRIDGE_TOKEN) headers['X-Aiskel-Token'] = BRIDGE_TOKEN;\n"
        "    try {\n"
        "      GM_xmlhttpRequest({\n"
        "        method,\n"
        "        url: BRIDGE_BASE_URL + path,\n"
        "        headers,\n"
        "        data: bodyObj ? JSON.stringify(bodyObj) : undefined,\n"
        "        onload: (resp) => {\n"
        "          let data = {};\n"
        "          try {\n"
        "            data = JSON.parse(resp.responseText || '{}');\n"
        "          } catch (_e) {\n"
        "            data = {};\n"
        "          }\n"
        "          const apiOk = resp.status >= 200 && resp.status < 300 && Boolean(data && data.ok === true);\n"
        "          const tabId = getUserscriptTabId();\n"
        "          data.current_tab_id = tabId;\n"
        "          data.is_current_tab_bound = Boolean(apiOk && data.bound && data.tab_id === tabId);\n"
        "          cb({\n"
        "            reachable: true,\n"
        "            connected: apiOk,\n"
        "            status: resp.status,\n"
        "            data,\n"
        "            error: apiOk ? '' : String((data && data.message) || ('HTTP ' + resp.status)),\n"
        "          });\n"
        "        },\n"
        "        onerror: () => cb({ reachable: false, connected: false, status: 0, data: {}, error: '' }),\n"
        "        ontimeout: () => cb({ reachable: false, connected: false, status: 0, data: {}, error: '' }),\n"
        "        onabort: () => cb({ reachable: false, connected: false, status: 0, data: {}, error: '' }),\n"
        "      });\n"
        "    } catch (_e) {\n"
        "      cb({ reachable: false, connected: false, status: 0, data: {}, error: '' });\n"
        "    }\n"
        "  }\n"
        "  function handleUserscriptLeave(ev) {\n"
        "    if (ev && ev.persisted) return;\n"
        "    // 新規タブ引き継ぎのリダイレクト中は紐づけ維持のためunbindを送らない\n"
        "    if (typeof readPendingUserscriptHandoffId === 'function' && readPendingUserscriptHandoffId()) return;\n"
        "    if (!userscriptTabBound || userscriptUnbindSent) return;\n"
        "    userscriptUnbindSent = true;\n"
        "    gmRequest('/api/unbind', 'POST', { tab_id: getUserscriptTabId() }, () => {});\n"
        "  }\n"
        "  window.addEventListener('pagehide', handleUserscriptLeave);\n"
        "  window.addEventListener('beforeunload', handleUserscriptLeave);\n"
        "  window.addEventListener('pageshow', () => { userscriptUnbindSent = false; });\n"
        "  const userscriptSyncChannel = typeof BroadcastChannel === 'function' ? new BroadcastChannel('aiskel_userscript_binding_sync') : null;\n"
        "  let userscriptUpdateHandler = null;\n"
        "  if (userscriptSyncChannel) {\n"
        "    userscriptSyncChannel.onmessage = (ev) => {\n"
        "      const msg = ev && ev.data;\n"
        "      if (!msg || typeof userscriptUpdateHandler !== 'function') return;\n"
        "      const localTabId = getUserscriptTabId();\n"
        "      const binding = msg.binding || {};\n"
        "      const isCurrentBound = Boolean(binding.bound && binding.tab_id === localTabId);\n"
        "      if (msg.type === 'explicit_unbind') {\n"
        "        const isStillBound = Boolean(binding.bound);\n"
        "        const payload = Object.assign({}, binding, {\n"
        "          current_tab_id: localTabId,\n"
        "          is_current_tab_bound: isCurrentBound,\n"
        "          explicit_unbind: !isStillBound,\n"
        "        });\n"
        "        userscriptUpdateHandler({ reachable: true, connected: true, status: 200, data: payload, error: '' });\n"
        "      } else if (msg.type === 'explicit_bind') {\n"
        "        const payload = Object.assign({}, binding, {\n"
        "          current_tab_id: localTabId,\n"
        "          is_current_tab_bound: isCurrentBound,\n"
        "          auto_bind_suppressed: false,\n"
        "        });\n"
        "        userscriptUpdateHandler({ reachable: true, connected: true, status: 200, data: payload, error: '' });\n"
        "      } else if (msg.type === 'binding_updated') {\n"
        "        const payload = Object.assign({}, binding, {\n"
        "          current_tab_id: localTabId,\n"
        "          is_current_tab_bound: isCurrentBound,\n"
        "        });\n"
        "        userscriptUpdateHandler({ reachable: true, connected: true, status: 200, data: payload, error: '' });\n"
        "      }\n"
        "    };\n"
        "  }\n"
        "  const bindingTransport = {\n"
        "    getLocalTabId: getUserscriptTabId,\n"
        "    notifyState: (st) => {\n"
        "      userscriptTabBound = Boolean(st && st.isCurrentTabBound);\n"
        "      if (userscriptTabBound) userscriptUnbindSent = false;\n"
        "    },\n"
        "    getStatus: (cb) => gmRequest('/api/binding', 'GET', null, cb),\n"
        "    bindTab: (cb, options) => {\n"
        "      const autoBind = Boolean(options && options.autoBind);\n"
        "      const localTabId = getUserscriptTabId();\n"
        "      const body = { tab_id: localTabId, tab_title: document.title || '', tab_url: window.location.href };\n"
        "      if (autoBind) {\n"
        "        body.only_if_unbound = true;\n"
        "      }\n"
        "      gmRequest('/api/bind', 'POST', body, (res) => {\n"
        "        if (userscriptSyncChannel && res && res.connected && res.data && res.data.bound) {\n"
        "          const msgType = !autoBind ? 'explicit_bind' : (res.data.tab_id === localTabId ? 'binding_updated' : '');\n"
        "          if (msgType) {\n"
        "            try { userscriptSyncChannel.postMessage({ type: msgType, binding: res.data }); } catch (_e) {}\n"
        "          }\n"
        "        }\n"
        "        cb(res);\n"
        "      });\n"
        "    },\n"
        "    unbindTab: (cb) => {\n"
        "      gmRequest('/api/unbind', 'POST', { tab_id: getUserscriptTabId() }, (res) => {\n"
        "        if (userscriptSyncChannel && res && res.connected && res.data && !res.data.bound) {\n"
        "          try { userscriptSyncChannel.postMessage({ type: 'explicit_unbind', binding: res.data }); } catch (_e) {}\n"
        "        }\n"
        "        cb(res);\n"
        "      });\n"
        "    },\n"
        "    getPrompt: (pattern, cb) => gmRequest('/api/prompt?pattern=' + encodeURIComponent(pattern || 'default'), 'GET', null, cb),\n"
        "    onUpdate: (handler) => { userscriptUpdateHandler = handler; },\n"
        "    onBindPrompt: () => {},\n"
        "  };\n"
    )


def build_userscript_handoff_transport_js() -> str:
    """Tampermonkey/Violentmonkey用の新規タブ引き継ぎ通信アダプタを生成する。"""
    return (
        "  const USERSCRIPT_HANDOFF_KEY = 'aiskel_userscript_pending_handoff';\n"
        "  const USERSCRIPT_HANDOFF_TTL_MS = 120000;\n"
        "  function readPendingUserscriptHandoffId() {\n"
        "    const rawHash = (window.location.hash || '').replace(/^#/, '');\n"
        "    if (rawHash) {\n"
        "      for (const part of rawHash.split('&')) {\n"
        "        if (part.startsWith('aiskel_handoff=')) {\n"
        "          let hid = part.slice('aiskel_handoff='.length);\n"
        "          try { hid = decodeURIComponent(hid); } catch (_e) {}\n"
        "          if (hid) {\n"
        "            try {\n"
        "              window.sessionStorage.setItem(USERSCRIPT_HANDOFF_KEY, JSON.stringify({ handoff_id: hid, created_at: Date.now() }));\n"
        "            } catch (_e) {}\n"
        "            return hid;\n"
        "          }\n"
        "        }\n"
        "      }\n"
        "    }\n"
        "    try {\n"
        "      const raw = window.sessionStorage.getItem(USERSCRIPT_HANDOFF_KEY);\n"
        "      if (!raw) return '';\n"
        "      const parsed = JSON.parse(raw);\n"
        "      if (parsed && parsed.handoff_id && (Date.now() - Number(parsed.created_at || 0)) <= USERSCRIPT_HANDOFF_TTL_MS) {\n"
        "        return String(parsed.handoff_id);\n"
        "      }\n"
        "      window.sessionStorage.removeItem(USERSCRIPT_HANDOFF_KEY);\n"
        "    } catch (_e) {}\n"
        "    return '';\n"
        "  }\n"
        "  function clearPendingUserscriptHandoffMarker() {\n"
        "    try { window.sessionStorage.removeItem(USERSCRIPT_HANDOFF_KEY); } catch (_e) {}\n"
        "    try {\n"
        "      const rawHash = (window.location.hash || '').replace(/^#/, '');\n"
        "      if (!rawHash) return;\n"
        "      const kept = rawHash.split('&').filter((part) => part && !part.startsWith('aiskel_handoff='));\n"
        "      const nextHash = kept.length ? '#' + kept.join('&') : '';\n"
        "      window.history.replaceState(null, '', window.location.pathname + window.location.search + nextHash);\n"
        "    } catch (_e) {}\n"
        "  }\n"
        "  function appendUserscriptHandoffHash(baseUrl, handoffId) {\n"
        "    try {\n"
        "      const u = new URL(baseUrl);\n"
        "      const raw = (u.hash || '').replace(/^#/, '');\n"
        "      const kept = raw ? raw.split('&').filter((p) => p && !p.startsWith('aiskel_handoff=')) : [];\n"
        "      kept.push('aiskel_handoff=' + encodeURIComponent(handoffId));\n"
        "      u.hash = kept.join('&');\n"
        "      return u.toString();\n"
        "    } catch (_e) {\n"
        "      const sep = baseUrl.indexOf('#') === -1 ? '#' : '&';\n"
        "      return baseUrl + sep + 'aiskel_handoff=' + encodeURIComponent(handoffId);\n"
        "    }\n"
        "  }\n"
        "  const handoffTransport = {\n"
        "    createHandoff: (payload, onDone) => {\n"
        "      const body = Object.assign({}, payload, { tab_id: getUserscriptTabId() });\n"
        "      gmRequest('/api/handoff', 'POST', body, (res) => {\n"
        "        const data = (res && res.data) || {};\n"
        "        const ok = Boolean(res && res.connected && data.ok);\n"
        "        if (ok && !data.skipped && data.handoff_id) {\n"
        "          const baseNewUrl = data.new_chat_url || payload.new_chat_url || 'https://aistudio.google.com/prompts/new_chat';\n"
        "          const targetUrl = appendUserscriptHandoffHash(baseNewUrl, data.handoff_id);\n"
        "          if (typeof GM_openInTab === 'function') {\n"
        "            GM_openInTab(targetUrl, { active: true, insert: true });\n"
        "          } else {\n"
        "            window.open(targetUrl, '_blank');\n"
        "          }\n"
        "        }\n"
        "        if (onDone) onDone(res);\n"
        "      });\n"
        "    },\n"
        "    claimHandoff: (cb) => {\n"
        "      const handoffId = readPendingUserscriptHandoffId();\n"
        "      if (!handoffId) {\n"
        "        cb({ reachable: true, connected: true, data: { ok: true, found: false } });\n"
        "        return;\n"
        "      }\n"
        "      gmRequest('/api/handoff/claim', 'POST', {\n"
        "        handoff_id: handoffId,\n"
        "        tab_id: getUserscriptTabId(),\n"
        "        tab_title: document.title || '',\n"
        "        tab_url: window.location.href,\n"
        "      }, cb);\n"
        "    },\n"
        "    ackHandoff: (handoffId, cb) => {\n"
        "      clearPendingUserscriptHandoffMarker();\n"
        "      gmRequest('/api/handoff/ack', 'POST', {\n"
        "        handoff_id: handoffId || '',\n"
        "        tab_id: getUserscriptTabId(),\n"
        "      }, (res) => { if (cb) cb(res || {}); });\n"
        "    },\n"
        "  };\n"
    )


