"""Module: @role: ブラウザ側での自動階層整理モード開始・対象ディレクトリ一覧取得・状態登録のJavaScriptを生成する。"""

def build_auto_organize_js() -> str:
    """ブラウザlocalStorage保持による自動階層整理モード開始スクリプトを返す。"""
    return (
        "  function startAutoOrganizeMode(options, done) {\n"
        "    const finish = () => {\n"
        "      autoSplitStartInFlight = false;\n"
        "      if (typeof done === 'function') done();\n"
        "    };\n"
        "    if (autoSplitStartInFlight) {\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (!bindingState || !bindingState.connected || !bindingState.isCurrentTabBound) {\n"
        "      showToast('VSCodeと紐づけ中のタブでのみ階層整理を実行できます', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (!autoRunAllowed) {\n"
        "      showToast('自動送信が無効化されているため階層整理モードを開始できません', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (!hasBindingTransport || typeof bindingTransport.getOrganizeTargets !== 'function') {\n"
        "      showToast('階層整理対象取得機能が利用できません', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    const allowRename = Boolean(options && options.allowRename);\n"
        "    autoSplitStartInFlight = true;\n"
        "    bindingTransport.getOrganizeTargets((res) => {\n"
        "      const data = (res && res.data) || {};\n"
        "      if (!res || !res.reachable) {\n"
        "        showToast('VSCodeブリッジへ接続できませんでした', true);\n"
        "        finish();\n"
        "        return;\n"
        "      }\n"
        "      if (!res.connected || !data.ok) {\n"
        "        const errMsg = (data && data.message) || res.error || ('HTTP ' + (res.status || '?'));\n"
        "        showToast('階層整理対象取得エラー: ' + errMsg, true);\n"
        "        finish();\n"
        "        return;\n"
        "      }\n"
        "      const dirs = Array.isArray(data.dirs) ? data.dirs : [];\n"
        "      if (!dirs.length) {\n"
        "        clearAutoSplitState();\n"
        "        syncAutoSplitUiState();\n"
        "        showToast('階層整理: 閾値 (' + (data.max_files || 10) + 'ファイル以上) の過密ディレクトリは検出されませんでした', false);\n"
        "        finish();\n"
        "        return;\n"
        "      }\n"
        "      const totalTargetFiles = Number(\n"
        "        data.total_target_files || dirs.reduce((acc, d) => acc + Number(d.file_count || 0), 0)\n"
        "      );\n"
        "      const topDir = dirs[0] && dirs[0].rel_dir ? String(dirs[0].rel_dir) : '';\n"
        "      const topCount = dirs[0] && typeof dirs[0].file_count === 'number' ? dirs[0].file_count : 0;\n"
        "      const renameLabel = allowRename ? 'リネーム許可' : 'リネーム禁止';\n"
        "      showToast(\n"
        "        '階層整理対象抽出: 対象ファイル ' + totalTargetFiles + '件 (' + dirs.length + '階層'\n"
        "          + (topDir ? ' / 最多: ' + topDir + ' ' + topCount + '件' : '') + ' · ' + renameLabel + ')',\n"
        "        false\n"
        "      );\n"
        "      const mappedFiles = dirs.map((d) => ({\n"
        "        rel_path: String(d.rel_dir || ''),\n"
        "        file_count: Number(d.file_count || 0),\n"
        "        total_lines: Number(d.total_lines || 0),\n"
        "        total_chars: Number(d.total_chars || 0),\n"
        "      }));\n"
        "      const nextState = {\n"
        "        version: 1,\n"
        "        mode: 'organize',\n"
        "        allowRename,\n"
        "        projectRoot: String(data.project_root || bindingState.projectRoot || ''),\n"
        "        active: true,\n"
        "        files: mappedFiles,\n"
        "        currentIndex: 0,\n"
        "        maxFiles: Number(data.max_files || 10),\n"
        "        totalTargetFiles,\n"
        "        applyRetryCount: 0,\n"
        "        updatedAt: Date.now(),\n"
        "      };\n"
        "      saveAutoSplitState(nextState);\n"
        "      syncAutoSplitUiState();\n"
        "      dispatchCurrentSplitFile(nextState, { allowCurrentEmptyTab: true }, (ok) => {\n"
        "        if (!ok) {\n"
        "          clearAutoSplitState();\n"
        "          syncAutoSplitUiState();\n"
        "        }\n"
        "        finish();\n"
        "      });\n"
        "    });\n"
        "  }\n\n"
    )
