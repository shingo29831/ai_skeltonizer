"""Module: @role: ブラウザ側での自動階層整理モード開始・対象ディレクトリ一覧取得・状態登録のJavaScriptを生成する。"""

def build_auto_organize_js() -> str:
    """ブラウザlocalStorage保持による自動階層整理モード開始スクリプトを返す。"""
    return (
        "  function startAutoOrganizeMode(options, done) {\n"
        "    const finish = () => {\n"
        "      autoSplitStartInFlight = false;\n"
        "      if (typeof done === 'function') done();\n"
        "    };\n"
        "    if (autoSplitStartInFlight) {\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (!bindingState || !bindingState.connected || !bindingState.isCurrentTabBound) {\n"
        "      showToast('VSCodeと紐づけ中のタブでのみ階層整理を実行できます', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (!autoRunAllowed) {\n"
        "      showToast('自動送信が無効化されているため階層整理モードを開始できません', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (typeof isConfigInferActiveForCurrentProject === 'function' && isConfigInferActiveForCurrentProject()) {\n"
        "      showToast('設定推論モードの実行中は階層整理を開始できません', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (!hasBindingTransport || typeof bindingTransport.getOrganizeTargets !== 'function') {\n"
        "      showToast('階層整理対象取得機能が利用できません', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    const allowRename = Boolean(options && options.allowRename);\n"
        "    autoSplitStartInFlight = true;\n"
        "    bindingTransport.getOrganizeTargets((res) => {\n"
        "      const data = (res && res.data) || {};\n"
        "      if (!res || !res.reachable) {\n"
        "        showToast('VSCodeブリッジへ接続できませんでした', true);\n"
        "        finish();\n"
        "        return;\n"
        "      }\n"
        "      if (!res.connected || !data.ok) {\n"
        "        const errMsg = (data && data.message) || res.error || ('HTTP ' + (res.status || '?'));\n"
        "        showToast('階層整理対象取得エラー: ' + errMsg, true);\n"
        "        finish();\n"
        "        return;\n"
        "      }\n"
        "      const dirs = Array.isArray(data.dirs) ? data.dirs : [];\n"
        "      if (!dirs.length) {\n"
        "        clearAutoSplitState();\n"
        "        syncAutoSplitUiState();\n"
        "        showToast('階層整理: 閾値 (' + (data.max_files || 10) + 'ファイル以上) の過密ディレクトリは検出されませんでした', false);\n"
        "        finish();\n"
        "        return;\n"
        "      }\n"
        "      const totalTargetFiles = Number(\n"
        "        data.total_target_files || dirs.reduce((acc, d) => acc + Number(d.file_count || 0), 0)\n"
        "      );\n"
        "      const topDir = dirs[0] && dirs[0].rel_dir ? String(dirs[0].rel_dir) : '';\n"
        "      const topCount = dirs[0] && typeof dirs[0].file_count === 'number' ? dirs[0].file_count : 0;\n"
        "      const renameLabel = allowRename ? 'リネーム許可' : 'リネーム禁止';\n"
        "      showToast(\n"
        "        '階層整理対象抽出: 対象ファイル ' + totalTargetFiles + '件 (' + dirs.length + '階層'\n"
        "          + (topDir ? ' / 最多: ' + topDir + ' ' + topCount + '件' : '') + ' · ' + renameLabel + ')',\n"
        "        false\n"
        "      );\n"
        "      const mappedFiles = dirs.map((d) => ({\n"
        "        rel_path: String(d.rel_dir || ''),\n"
        "        file_count: Number(d.file_count || 0),\n"
        "        total_lines: Number(d.total_lines || 0),\n"
        "        total_chars: Number(d.total_chars || 0),\n"
        "      }));\n"
        "      const nextState = {\n"
        "        version: 1,\n"
        "        mode: 'organize',\n"
        "        allowRename,\n"
        "        projectRoot: String(data.project_root || bindingState.projectRoot || ''),\n"
        "        active: true,\n"
        "        files: mappedFiles,\n"
        "        currentIndex: 0,\n"
        "        batchIndexInDir: 1,\n"
        "        stagnationCount: 0,\n"
        "        completedDirs: [],\n"
        "        maxFiles: Number(data.max_files || 10),\n"
        "        totalTargetFiles,\n"
        "        applyRetryCount: 0,\n"
        "        updatedAt: Date.now(),\n"
        "      };\n"
        "      saveAutoSplitState(nextState);\n"
        "      syncAutoSplitUiState();\n"
        "      dispatchCurrentSplitFile(nextState, { allowCurrentEmptyTab: true }, (ok) => {\n"
        "        if (!ok) {\n"
        "          clearAutoSplitState();\n"
        "          syncAutoSplitUiState();\n"
        "        }\n"
        "        finish();\n"
        "      });\n"
        "    });\n"
        "  }\n\n"
        "  function advanceOrganizeAfterApply(splitState, applyNotice, applyHasWarn) {\n"
        "    const curFile = splitState.files[splitState.currentIndex] || { rel_path: '', file_count: 0 };\n"
        "    const curRelDir = String(curFile.rel_path || '');\n"
        "    const prevFileCount = Number(curFile.file_count || 0);\n"
        "    const completedDirs = Array.isArray(splitState.completedDirs) ? splitState.completedDirs.slice() : [];\n"
        "    const prevBatchIndex = Number(splitState.batchIndexInDir || 1);\n"
        "    const prevStagnation = Number(splitState.stagnationCount || 0);\n\n"
        "    if (!hasBindingTransport || typeof bindingTransport.getOrganizeTargets !== 'function') {\n"
        "      clearAutoSplitState();\n"
        "      syncAutoSplitUiState();\n"
        "      if (typeof reportBridgeError === 'function') {\n"
        "        reportBridgeError('aiskel 階層整理停止', '階層整理対象の取得機能が利用できません');\n"
        "      }\n"
        "      return;\n"
        "    }\n\n"
        "    autoSplitAdvanceInFlight = true;\n"
        "    bindingTransport.getOrganizeTargets((res) => {\n"
        "      const activeNow = getActiveAutoSplitStateForCurrentProject();\n"
        "      if (!activeNow || activeNow.updatedAt !== splitState.updatedAt || !isOrganizeModeState(activeNow)) {\n"
        "        autoSplitAdvanceInFlight = false;\n"
        "        return;\n"
        "      }\n"
        "      const data = (res && res.data) || {};\n"
        "      if (!res || !res.connected || !data.ok) {\n"
        "        autoSplitAdvanceInFlight = false;\n"
        "        const errMsg = (data && data.message) || (res && res.error) || '次ステップの階層整理対象取得に失敗しました';\n"
        "        clearAutoSplitState();\n"
        "        syncAutoSplitUiState();\n"
        "        if (typeof reportBridgeError === 'function') {\n"
        "          reportBridgeError('aiskel 階層整理エラー', errMsg, errMsg);\n"
        "        } else {\n"
        "          showToast('aiskel 階層整理エラー: ' + errMsg, true);\n"
        "        }\n"
        "        return;\n"
        "      }\n\n"
        "      const latestDirs = (Array.isArray(data.dirs) ? data.dirs : []).map((d) => ({\n"
        "        rel_path: String(d.rel_dir || ''),\n"
        "        file_count: Number(d.file_count || 0),\n"
        "        total_lines: Number(d.total_lines || 0),\n"
        "        total_chars: Number(d.total_chars || 0),\n"
        "      }));\n\n"
        "      const sameDirEntry = latestDirs.find((d) => d.rel_path === curRelDir);\n"
        "      const nextCompletedDirs = completedDirs.slice();\n"
        "      let nextBatchIndex = 1;\n"
        "      let nextStagnation = 0;\n"
        "      let stagnationNotice = '';\n\n"
        "      if (sameDirEntry && !nextCompletedDirs.includes(curRelDir)) {\n"
        "        if (prevFileCount > 0 && sameDirEntry.file_count >= prevFileCount) {\n"
        "          nextStagnation = prevStagnation + 1;\n"
        "          if (nextStagnation >= 2) {\n"
        "            // 直下ファイル数が連続して減らない場合の無限ループを防止\n"
        "            nextCompletedDirs.push(curRelDir);\n"
        "            stagnationNotice = '⚠ ' + curRelDir + ' の直下ファイル数が減少しないため次の階層へ進みます';\n"
        "            showToast(stagnationNotice, true);\n"
        "          } else {\n"
        "            nextBatchIndex = prevBatchIndex + 1;\n"
        "          }\n"
        "        } else {\n"
        "          nextBatchIndex = prevBatchIndex + 1;\n"
        "          nextStagnation = 0;\n"
        "        }\n"
        "      } else if (curRelDir && !nextCompletedDirs.includes(curRelDir)) {\n"
        "        nextCompletedDirs.push(curRelDir);\n"
        "      }\n\n"
        "      let remainingDirs = latestDirs.filter((d) => !nextCompletedDirs.includes(d.rel_path));\n"
        "      if (!remainingDirs.length) {\n"
        "        autoSplitAdvanceInFlight = false;\n"
        "        clearAutoSplitState();\n"
        "        syncAutoSplitUiState();\n"
        "        if (stagnationNotice) {\n"
        "          showToast('aiskel 階層整理: 停滞スキップにより残りの対象ディレクトリがなくなったため終了しました', true);\n"
        "        } else {\n"
        "          if (typeof clearErrorPanel === 'function') clearErrorPanel();\n"
        "          showToast('aiskel 階層整理: 全対象ディレクトリの整理・適用が完了しました！', false);\n"
        "        }\n"
        "        return;\n"
        "      }\n\n"
        "      if (sameDirEntry && !nextCompletedDirs.includes(curRelDir)) {\n"
        "        remainingDirs = [sameDirEntry].concat(remainingDirs.filter((d) => d.rel_path !== curRelDir));\n"
        "      } else {\n"
        "        nextBatchIndex = 1;\n"
        "        nextStagnation = 0;\n"
        "      }\n\n"
        "      const totalTargetFiles = remainingDirs.reduce((acc, d) => acc + Number(d.file_count || 0), 0);\n"
        "      const nextState = Object.assign({}, splitState, {\n"
        "        files: remainingDirs,\n"
        "        currentIndex: 0,\n"
        "        batchIndexInDir: nextBatchIndex,\n"
        "        stagnationCount: nextStagnation,\n"
        "        completedDirs: nextCompletedDirs,\n"
        "        maxFiles: Number(data.max_files || splitState.maxFiles || 10),\n"
        "        totalTargetFiles,\n"
        "        applyRetryCount: 0,\n"
        "        updatedAt: Date.now(),\n"
        "      });\n"
        "      saveAutoSplitState(nextState);\n"
        "      syncAutoSplitUiState();\n"
        "      if (typeof clearErrorPanel === 'function') clearErrorPanel();\n\n"
        "      const combinedNotice = [applyNotice, stagnationNotice].filter(Boolean).join('\\n');\n"
        "      dispatchCurrentSplitFile(\n"
        "        nextState,\n"
        "        {\n"
        "          allowCurrentEmptyTab: false,\n"
        "          prevApplyNotice: combinedNotice,\n"
        "          prevApplyIsError: applyHasWarn || Boolean(stagnationNotice),\n"
        "        },\n"
        "        () => {\n"
        "          autoSplitAdvanceInFlight = false;\n"
        "        }\n"
        "      );\n"
        "    });\n"
        "  }\n\n"
    )
