"""Module: @role: AI Studioタブ紐づけUIの状態描画およびユーザー操作イベントハンドラのクライアントJavaScriptを生成する。"""

def build_tab_binding_ui_render_js() -> str:
    """状態に応じたUIレンダリング関数および各種ボタン・入力イベントハンドラのJSコードを返す。"""
    return (
        "    function render(state) {\n"
        "      ensureMounted();\n"
        "      currentState = state;\n"
        "      const projectLabel = state.projectName || 'VSCode';\n"
        "      let dotVariant = '';\n"
        "      primaryBtn.disabled = actionPending;\n"
        "      if (!state.connected) {\n"
        "        if (state.reachable) {\n"
        "          dotVariant = 'dot-error';\n"
        "          titleEl.textContent = 'aiskel 接続エラー (HTTP ' + (state.status || '?') + ')';\n"
        "          subEl.textContent = state.errorMessage || '拡張機能の更新や認証設定を確認してください';\n"
        "          primaryBtn.textContent = '再確認';\n"
        "          primaryBtn.className = 'btn btn-ghost';\n"
        "          pillLabel.textContent = 'aiskel: エラー';\n"
        "        } else {\n"
        "          dotVariant = '';\n"
        "          titleEl.textContent = 'aiskel ブリッジ未接続';\n"
        "          subEl.textContent = 'aiskel s または aiskel listen 待機中';\n"
        "          primaryBtn.textContent = '再確認';\n"
        "          primaryBtn.className = 'btn btn-ghost';\n"
        "          pillLabel.textContent = 'aiskel: 未接続';\n"
        "        }\n"
        "      } else if (state.isCurrentTabBound) {\n"
        "        dotVariant = 'dot-bound';\n"
        "        titleEl.textContent = 'VSCodeと紐づけ中 (' + projectLabel + ')';\n"
        "        const baseSub = state.autoRunAllowed && state.autoRunEnabled ? 'このタブを監視・貼付後自動送信中' : 'このタブの aiskel c を監視中';\n"
        "        const remainSuffix = typeof state.remainingAutoTabs === 'number' ? ' ・ 自動新タブ残:' + state.remainingAutoTabs : '';\n"
        "        const splitSuffix = state.autoSplitActive && state.autoSplitTotalCount\n"
        "          ? ' ・ 分割中(' + (state.autoSplitCurrentIndex + 1) + '/' + state.autoSplitTotalCount + '): ' + (state.autoSplitCurrentFile || '')\n"
        "          : '';\n"
        "        subEl.textContent = baseSub + remainSuffix + splitSuffix;\n"
        "        primaryBtn.textContent = '解除';\n"
        "        primaryBtn.className = 'btn btn-ghost';\n"
        "        pillLabel.textContent = state.autoSplitActive && state.autoSplitTotalCount\n"
        "          ? '自動分割 ' + (state.autoSplitCurrentIndex + 1) + '/' + state.autoSplitTotalCount\n"
        "          : (state.autoRunAllowed && state.autoRunEnabled ? 'VSCode自動送信' : 'VSCode監視中');\n"
        "      } else if (state.bound) {\n"
        "        dotVariant = 'dot-other';\n"
        "        titleEl.textContent = '別タブが紐づけ中 (' + projectLabel + ')';\n"
        "        subEl.textContent = state.boundTabTitle ? '対象: ' + state.boundTabTitle : '他タブを監視中';\n"
        "        primaryBtn.textContent = 'このタブに切替';\n"
        "        primaryBtn.className = 'btn btn-primary';\n"
        "        pillLabel.textContent = 'VSCodeと紐づける';\n"
        "      } else {\n"
        "        dotVariant = 'dot-unbound';\n"
        "        titleEl.textContent = 'VSCode未紐づけ (' + projectLabel + ')';\n"
        "        subEl.textContent = 'ボタンでこのタブを監視対象にします';\n"
        "        primaryBtn.textContent = 'VSCodeと紐づける';\n"
        "        primaryBtn.className = 'btn btn-primary';\n"
        "        pillLabel.textContent = 'VSCodeと紐づける';\n"
        "      }\n"
        "      if (state.connected && state.isCurrentTabBound) {\n"
        "        if (!state.autoRunAllowed) {\n"
        "          autoRunBtn.disabled = true;\n"
        "          autoRunBtn.className = 'btn btn-ghost';\n"
        "          autoRunBtn.textContent = '自動送信: 無効';\n"
        "          autoRunBtn.title = 'CLIオプションにより自動送信は無効化されています';\n"
        "        } else if (state.autoRunEnabled) {\n"
        "          autoRunBtn.disabled = actionPending;\n"
        "          autoRunBtn.className = 'btn btn-auto-on';\n"
        "          autoRunBtn.textContent = '自動送信: ON';\n"
        "          autoRunBtn.title = 'クリックで貼り付け後の自動送信を停止';\n"
        "        } else {\n"
        "          autoRunBtn.disabled = actionPending;\n"
        "          autoRunBtn.className = 'btn btn-ghost';\n"
        "          autoRunBtn.textContent = '自動送信: OFF';\n"
        "          autoRunBtn.title = 'クリックで貼り付け後の自動送信を有効化';\n"
        "        }\n"
        "      } else {\n"
        "        autoRunBtn.className = 'btn btn-ghost btn-hidden';\n"
        "      }\n"
        "      if (state.connected && typeof state.patchHandoffMaxTabs === 'number') {\n"
        "        const maxTabsVal = Math.max(0, Math.min(999, Math.floor(state.patchHandoffMaxTabs)));\n"
        "        autoTabCtrl.className = 'auto-tab-ctrl';\n"
        "        // ユーザー入力中のカーソルや値をポーリング再描画で上書きしないためフォーカス中は保持\n"
        "        if (shadow.activeElement !== autoTabInput) {\n"
        "          autoTabInput.value = String(maxTabsVal);\n"
        "        }\n"
        "        const ctrlDisabled = actionPending || maxTabsPending;\n"
        "        autoTabInput.disabled = ctrlDisabled;\n"
        "        autoTabDecBtn.disabled = ctrlDisabled || maxTabsVal <= 0;\n"
        "        autoTabIncBtn.disabled = ctrlDisabled || maxTabsVal >= 999;\n"
        "      } else {\n"
        "        autoTabCtrl.className = 'auto-tab-ctrl btn-hidden';\n"
        "      }\n"
        "      if (state.connected && state.isCurrentTabBound) {\n"
        "        if (state.autoSplitActive) {\n"
        "          splitBtn.disabled = actionPending || splitPending;\n"
        "          splitBtn.className = 'btn btn-split-stop';\n"
        "          const idxNum = (typeof state.autoSplitCurrentIndex === 'number' ? state.autoSplitCurrentIndex : 0) + 1;\n"
        "          const totNum = typeof state.autoSplitTotalCount === 'number' ? state.autoSplitTotalCount : 0;\n"
        "          splitBtn.textContent = totNum ? '分割停止 (' + idxNum + '/' + totNum + ')' : '分割停止';\n"
        "          splitBtn.title = '自動分割モードを停止します (対象: ' + (state.autoSplitCurrentFile || '') + ')';\n"
        "        } else if (!state.autoRunAllowed) {\n"
        "          splitBtn.disabled = true;\n"
        "          splitBtn.className = 'btn btn-split';\n"
        "          splitBtn.textContent = '自動分割';\n"
        "          splitBtn.title = 'CLIオプションにより自動送信が無効化されているため利用できません';\n"
        "        } else {\n"
        "          splitBtn.disabled = actionPending || splitPending || insertPending;\n"
        "          splitBtn.className = 'btn btn-split';\n"
        "          splitBtn.textContent = splitPending ? '準備中...' : '自動分割';\n"
        "          splitBtn.title = 'aiskel b で肥大化ファイルを検出し、大きい順に1ファイルずつ自動分割します';\n"
        "        }\n"
        "      } else {\n"
        "        splitBtn.className = 'btn btn-split btn-hidden';\n"
        "      }\n"
        "      if (state.connected) {\n"
        "        insertBtn.disabled = actionPending || insertPending || splitPending;\n"
        "        insertBtn.className = 'btn btn-insert';\n"
        "        insertBtn.textContent = insertPending ? '挿入中...' : '要約+プロンプト';\n"
        "      } else {\n"
        "        insertBtn.className = 'btn btn-insert btn-hidden';\n"
        "      }\n"
        "      const dotClass = dotVariant ? 'dot ' + dotVariant : 'dot';\n"
        "      dot.className = dotClass;\n"
        "      pillDot.className = dotClass;\n"
        "      setMinimized(minimized);\n"
        "    }\n\n"
        "    function submitAutoTabCount(rawValue, options) {\n"
        "      if (actionPending || maxTabsPending || !currentState || !currentState.connected) return;\n"
        "      if (typeof actions.onSetPatchHandoffMaxTabs !== 'function') return;\n"
        "      const fallbackVal = typeof currentState.patchHandoffMaxTabs === 'number' ? currentState.patchHandoffMaxTabs : 1;\n"
        "      const trimmed = String(rawValue).trim();\n"
        "      if (!/^-?\\d+$/.test(trimmed)) {\n"
        "        autoTabInput.value = String(fallbackVal);\n"
        "        return;\n"
        "      }\n"
        "      const parsed = Number.parseInt(trimmed, 10);\n"
        "      const clamped = Math.max(0, Math.min(999, parsed));\n"
        "      autoTabInput.value = String(clamped);\n"
        "      if (options && options.skipIfUnchanged && clamped === fallbackVal) return;\n"
        "      maxTabsPending = true;\n"
        "      render(currentState);\n"
        "      actions.onSetPatchHandoffMaxTabs(clamped, () => {\n"
        "        maxTabsPending = false;\n"
        "        if (currentState) render(currentState);\n"
        "      });\n"
        "    }\n\n"
        "    autoTabDecBtn.addEventListener('click', () => {\n"
        "      const cur = currentState && typeof currentState.patchHandoffMaxTabs === 'number' ? currentState.patchHandoffMaxTabs : 1;\n"
        "      submitAutoTabCount(cur - 1);\n"
        "    });\n"
        "    autoTabIncBtn.addEventListener('click', () => {\n"
        "      const cur = currentState && typeof currentState.patchHandoffMaxTabs === 'number' ? currentState.patchHandoffMaxTabs : 1;\n"
        "      submitAutoTabCount(cur + 1);\n"
        "    });\n"
        "    autoTabInput.addEventListener('change', () => {\n"
        "      submitAutoTabCount(autoTabInput.value, { skipIfUnchanged: true });\n"
        "    });\n"
        "    autoTabInput.addEventListener('keydown', (ev) => {\n"
        "      ev.stopPropagation();\n"
        "      if (ev.key === 'Enter' && !ev.isComposing && ev.keyCode !== 229) {\n"
        "        ev.preventDefault();\n"
        "        submitAutoTabCount(autoTabInput.value, { skipIfUnchanged: true });\n"
        "        autoTabInput.blur();\n"
        "      }\n"
        "    });\n"
        "    autoTabInput.addEventListener('input', (ev) => ev.stopPropagation());\n"
        "    autoRunBtn.addEventListener('click', () => {\n"
        "      if (!currentState || !currentState.isCurrentTabBound || !currentState.autoRunAllowed) return;\n"
        "      if (typeof actions.onToggleAutoRun === 'function') actions.onToggleAutoRun();\n"
        "    });\n"
        "    splitBtn.addEventListener('click', () => {\n"
        "      if (actionPending || splitPending || !currentState || !currentState.connected || !currentState.isCurrentTabBound) return;\n"
        "      if (currentState.autoSplitActive) {\n"
        "        if (typeof actions.onStopAutoSplit === 'function') actions.onStopAutoSplit();\n"
        "        return;\n"
        "      }\n"
        "      if (!currentState.autoRunAllowed || typeof actions.onStartAutoSplit !== 'function') return;\n"
        "      splitPending = true;\n"
        "      render(currentState);\n"
        "      actions.onStartAutoSplit(() => {\n"
        "        splitPending = false;\n"
        "        if (currentState) render(currentState);\n"
        "      });\n"
        "    });\n"
        "    insertBtn.addEventListener('click', () => {\n"
        "      if (actionPending || insertPending || !currentState || !currentState.connected) return;\n"
        "      if (typeof actions.onInsertSummaryPrompt !== 'function') return;\n"
        "      insertPending = true;\n"
        "      render(currentState);\n"
        "      actions.onInsertSummaryPrompt(() => {\n"
        "        insertPending = false;\n"
        "        if (currentState) render(currentState);\n"
        "      });\n"
        "    });\n"
        "    primaryBtn.addEventListener('click', () => {\n"
        "      if (actionPending || !currentState) return;\n"
        "      actionPending = true;\n"
        "      primaryBtn.disabled = true;\n"
        "      const done = () => {\n"
        "        actionPending = false;\n"
        "        if (currentState) render(currentState);\n"
        "      };\n"
        "      if (!currentState.connected) {\n"
        "        actions.onRefresh(done);\n"
        "      } else if (currentState.isCurrentTabBound) {\n"
        "        actions.onUnbind(done);\n"
        "      } else {\n"
        "        actions.onBind(done);\n"
        "      }\n"
        "    });\n"
        "    minBtn.addEventListener('click', () => setMinimized(true));\n"
        "    pill.addEventListener('click', () => setMinimized(false));\n\n"
        "    return { render, ensureMounted };\n"
        "  }\n\n"
    )
