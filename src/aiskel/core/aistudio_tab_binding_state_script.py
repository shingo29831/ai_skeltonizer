        "        if (currentState) render(currentState);\n"
        "      });\n"
        "    });\n"
        "    primaryBtn.addEventListener('click', () => {\n"
        "      if (actionPending || !currentState) return;\n"
        "      actionPending = true;\n"
        "      primaryBtn.disabled = true;\n"
