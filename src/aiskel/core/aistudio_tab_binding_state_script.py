        "      organizeMenuOpen = false;\n"
        "      splitPending = true;\n"
        "      render(currentState);\n"
        "      actions.onStartAutoOrganize({ allowRename }, () => {\n"
        "        splitPending = false;\n"
        "        if (currentState) render(currentState);\n"
        "      });\n"
        "    });\n"
        "    insertBtn.addEventListener('click', () => {\n"
        "      if (actionPending || insertPending || !currentState || !currentState.connected) return;\n"
        "      if (typeof actions.onInsertSummaryPrompt !== 'function') return;\n"
        "      insertPending = true;\n"
        "      render(currentState);\n"
        "      actions.onInsertSummaryPrompt(() => {\n"
        "        insertPending = false;\n"
        "        if (currentState) render(currentState);\n"
        "      });\n"
        "    });\n"
        "    configInferBtn.addEventListener('click', () => {\n"
        "      if (actionPending || configInferPending || !currentState || !currentState.connected || !currentState.isCurrentTabBound) return;\n"
        "      if (currentState.configInferActive) {\n"
        "        if (typeof actions.onStopConfigInfer === 'function') actions.onStopConfigInfer();\n"
        "        return;\n"
        "      }\n"
        "      if (!currentState.autoRunAllowed || currentState.autoSplitActive || typeof actions.onStartConfigInfer !== 'function') return;\n"
