        "    organizeCodeSplitBtn.addEventListener('click', () => {\n"
        "      if (actionPending || splitPending || !currentState || !currentState.connected || !currentState.isCurrentTabBound) return;\n"
        "      if (!currentState.autoRunAllowed || typeof actions.onStartAutoSplit !== 'function') return;\n"
        "      organizeMenuOpen = false;\n"
        "      splitPending = true;\n"
        "      render(currentState);\n"
        "      actions.onStartAutoSplit(() => {\n"
        "        splitPending = false;\n"
        "        if (currentState) render(currentState);\n"
        "      });\n"
        "    });\n"
        "    organizeHierarchyBtn.addEventListener('click', () => {\n"
        "      if (actionPending || splitPending || !currentState || !currentState.connected || !currentState.isCurrentTabBound) return;\n"
