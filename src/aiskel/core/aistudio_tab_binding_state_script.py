        "        }\n"
        "        const ctrlDisabled = actionPending || maxTabsPending;\n"
        "        autoTabInput.disabled = ctrlDisabled;\n"
        "        autoTabDecBtn.disabled = ctrlDisabled || maxTabsVal <= 0;\n"
        "        autoTabIncBtn.disabled = ctrlDisabled || maxTabsVal >= 999;\n"
        "      } else {\n"
        "        autoTabRow.className = 'ctrl-row btn-hidden';\n"
        "        autoTabCtrl.className = 'auto-tab-ctrl btn-hidden';\n"
