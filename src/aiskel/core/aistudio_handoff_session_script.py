"""Module: @role: パッチ出力検知時の引き継ぎ送信・新規タブ取得・自動Run制御のクライアントJavaScriptを生成する。"""

def build_handoff_session_js() -> str:
    """引き継ぎレコード生成・終端自動適用通知・新規タブ取得と自動Run起動のJSコード群を返す。"""
    return (
        "  const hasHandoffTransport = typeof handoffTransport !== 'undefined' && handoffTransport !== null;\n"
        "  const HANDOFF_CLAIM_RETRY_MS = 500;\n"
        "  const HANDOFF_MAX_CLAIM_RETRIES = 3;\n\n"
        "  function handleTerminalAutoApplyNotice(data, appliedMessage, skippedFallback) {\n"
        "    if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "    if (typeof handleAutoSplitTerminalApplyResult === 'function' && handleAutoSplitTerminalApplyResult(data)) {\n"
        "      return;\n"
        "    }\n"
        "    if (data.apply_attempted) {\n"
        "      if (data.applied) {\n"
        "        if (typeof clearErrorPanel === 'function') clearErrorPanel();\n"
        "        showToast(appliedMessage, false);\n"
        "      } else {\n"
        "        const detail = data.apply_message || 'パッチの自動適用に失敗しました';\n"
        "        if (typeof reportBridgeError === 'function') {\n"
        "          reportBridgeError('aiskel 自動適用エラー (aiskel a)', detail, detail);\n"
        "        } else {\n"
        "          showToast('aiskel 自動適用エラー: ' + detail, true);\n"
        "        }\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    skippedFallback();\n"
        "  }\n\n"
        "  function triggerPatchHandoff(ctx, finishedRunSeq, stopRequested) {\n"
        "    if (!hasHandoffTransport) return;\n"
        "    const responseText = extractFullResponseText(ctx.modelTurns);\n"
        "    if (!responseText) return;\n"
        "    const isStopRequested = Boolean(stopRequested) || (\n"
        "      typeof hasHandoffStopSignalInTurns === 'function' && hasHandoffStopSignalInTurns(ctx.modelTurns)\n"
        "    );\n"
        "    const turnId = buildTurnIdentifier(ctx, finishedRunSeq);\n"
        "    const dedupKey = turnId + '::PATCH::' + hashText(responseText);\n"
        "    if (executedKeys.has(dedupKey) || inFlightKeys.has(dedupKey)) return;\n"
        "    const newChatUrl = buildSameAccountNewChatUrl(window.location.href);\n"
        "    inFlightKeys.add(dedupKey);\n"
        "    handoffTransport.createHandoff(\n"
        "      {\n"
        "        turn_id: turnId,\n"
        "        response_text: responseText,\n"
        "        source_url: window.location.href,\n"
        "        new_chat_url: newChatUrl,\n"
        "        tab_title: document.title || '',\n"
        "        page_focused: document.hasFocus() && document.visibilityState === 'visible',\n"
        "        stop_handoff: isStopRequested,\n"
        "      },\n"
        "      (res) => {\n"
        "        inFlightKeys.delete(dedupKey);\n"
        "        const data = (res && res.data) || {};\n"
        "        if (res && res.connected && data.ok) {\n"
        "          markExecuted(dedupKey);\n"
        "          if (!data.skipped) {\n"
        "            if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "            const remainNote = typeof data.remaining_auto_tabs === 'number'\n"
        "              ? '（生成タブの残り自動作成回数: ' + data.remaining_auto_tabs + '）'\n"
        "              : '';\n"
        "            showToast('aiskel パッチ応答をコピーし、新しいタブへ要約とともに引き継ぎました' + remainNote, false);\n"
        "          } else if (data.stop_signal_detected && !data.duplicate_skipped) {\n"
        "            handleTerminalAutoApplyNotice(\n"
        "              data,\n"
        "              'aiskel 欠陥なし合図を検知し、最後の置換コードを aiskel a で適用しました',\n"
        "              () => showToast('aiskel 完了合図を検知しました（適用対象の置換コードがないためスキップしました）', false)\n"
        "            );\n"
        "          } else if (data.limit_reached && !data.duplicate_skipped) {\n"
        "            handleTerminalAutoApplyNotice(\n"
        "              data,\n"
        "              'aiskel 新規タブ上限に達したため、最後の置換コードを aiskel a で適用しました',\n"
        "              () => showToast(\n"
        "                data.copied_to_clipboard\n"
        "                  ? 'aiskel パッチ応答をコピーしました（新規タブ自動作成の回数制限に達したため新規タブは開きません）'\n"
        "                  : 'aiskel 新規タブ自動作成の回数制限に達したため新規タブ作成をスキップしました（コピー失敗）',\n"
        "                !data.copied_to_clipboard\n"
        "              )\n"
        "            );\n"
        "          }\n"
        "          return;\n"
        "        }\n"
        "        if (res && res.status === 409) {\n"
        "          if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "          showToast('aiskel スキップ: ' + (data.message || 'タブがVSCodeと紐づけられていません'), true);\n"
        "          return;\n"
        "        }\n"
        "        if (!res || !res.reachable) {\n"
        "          showToast('aiskel 新規タブ引き継ぎエラー: ローカルブリッジに接続できません', true);\n"
        "          return;\n"
        "        }\n"
        "        showToast('aiskel 新規タブ引き継ぎエラー: ' + (data.message || res.error || ('HTTP ' + (res.status || '?'))), true);\n"
        "      }\n"
        "    );\n"
        "  }\n\n"
        "  function scheduleHandoffAutoRun(handoffId, pasteMeta) {\n"
        "    if (typeof scheduleAutoRunAfterPaste !== 'function' || typeof shouldScheduleAutoRun !== 'function') {\n"
        "      return false;\n"
        "    }\n"
        "    const preSnap = pasteMeta && pasteMeta.preSnap ? pasteMeta.preSnap : null;\n"
        "    const turnCtx = typeof getTurnContext === 'function'\n"
        "      ? getTurnContext()\n"
        "      : { userTurnCount: 0, modelTurns: [], modelIndices: [] };\n"
        "    const dispatchCtx = {\n"
        "      url: window.location.href,\n"
        "      resolvedUrl: window.location.href,\n"
        "      isNewChatHandoff: true,\n"
        "      allowBackgroundDomSubmit: true,\n"
        "      domPasteVerified: true,\n"
        "      modelTurnRefs: turnCtx.modelTurns.slice(),\n"
        "      modelTurnSigs: turnCtx.modelTurns.map((turn) => buildModelTurnsContentSignature([turn])),\n"
        "      modelContentSig: buildModelContentSignature(turnCtx),\n"
        "      userTurnCountBefore: turnCtx.userTurnCount,\n"
        "      commandsKey: 'HANDOFF::' + String(handoffId || ''),\n"
        "      pasteSeqBefore: pasteEventSeq,\n"
        "      inputTextBefore: preSnap ? preSnap.text : '',\n"
        "      chipCountBefore: preSnap ? preSnap.chipCount : 0,\n"
        "      chipSignatureBefore: preSnap ? preSnap.chipSignature : '0::',\n"
        "      hadContentBefore: preSnap ? preSnap.hasContent : false,\n"
        "      responsePasted: true,\n"
        "      commandOk: true,\n"
        "    };\n"
        "    const syntheticResponse = {\n"
        "      pasted: true,\n"
        "      auto_run: isAutoRunEffectiveEnabled(),\n"
        "      auto_run_allowed: autoRunAllowed,\n"
        "    };\n"
        "    if (!shouldScheduleAutoRun(syntheticResponse, dispatchCtx)) {\n"
        "      return false;\n"
        "    }\n"
        "    scheduleAutoRunAfterPaste(dispatchCtx);\n"
        "    return true;\n"
        "  }\n\n"
        "  function waitAndPasteHandoff(handoffId, textToPaste, remainingAutoTabs, handoffKind, targetFile) {\n"
        "    handoffSessionActive = true;\n"
        "    waitAndPasteText({\n"
        "      textToPaste,\n"
        "      priority: 'handoff',\n"
        "      timeoutMs: HANDOFF_PASTE_TIMEOUT_MS,\n"
        "      settleMs: HANDOFF_HYDRATION_SETTLE_MS,\n"
        "      requireEmptyInput: false,\n"
        "      onSuccess: (_alreadyPresent, _insertedWithDraft, pasteMeta) => {\n"
        "        handoffSessionActive = false;\n"
        "        handoffTransport.ackHandoff(handoffId, () => {});\n"
        "        const remainNote = typeof remainingAutoTabs === 'number'\n"
        "          ? '（新規タブ自動作成の残り回数: ' + remainingAutoTabs + '）'\n"
        "          : '';\n"
        "        const toastTitle = handoffKind === 'file_split'\n"
        "          ? 'aiskel 自動分割対象 (' + (targetFile || '') + ') の指示・要約を貼り付け、VSCodeと紐づけました'\n"
        "          : 'aiskel レビュー指示・応答・要約を貼り付け、VSCodeと紐づけました';\n"
        "        showToast(toastTitle + remainNote, false);\n"
        "        scheduleHandoffAutoRun(handoffId, pasteMeta);\n"
        "      },\n"
        "      onAborted: () => {\n"
        "        handoffSessionActive = false;\n"
        "      },\n"
        "      onTimeout: () => {\n"
        "        handoffSessionActive = false;\n"
        "        showToast('aiskel 新規タブの入力欄検出がタイムアウトしました（手動で貼り付けてください）', true);\n"
        "      },\n"
        "      onVerifyFailed: () => {\n"
        "        handoffSessionActive = false;\n"
        "        showToast('aiskel 自動貼り付けの反映を確認できませんでした（手動で貼り付けてください）', true);\n"
        "      },\n"
        "    });\n"
        "  }\n\n"
        "  function runPendingHandoffPasteOnLoad(attempt) {\n"
        "    if (!hasHandoffTransport || typeof handoffTransport.claimHandoff !== 'function') return;\n"
        "    const retryCount = attempt || 0;\n"
        "    if (hasActiveHandoffUrlMarker()) {\n"
        "      handoffSessionActive = true;\n"
        "    }\n"
        "    handoffTransport.claimHandoff((res) => {\n"
        "      if (!res || !res.reachable) {\n"
        "        if (retryCount < HANDOFF_MAX_CLAIM_RETRIES) {\n"
        "          window.setTimeout(() => runPendingHandoffPasteOnLoad(retryCount + 1), HANDOFF_CLAIM_RETRY_MS);\n"
        "        } else {\n"
        "          handoffSessionActive = false;\n"
        "        }\n"
        "        return;\n"
        "      }\n"
        "      if (!res.data || !res.data.found || !res.data.handoff) {\n"
        "        handoffSessionActive = false;\n"
        "        return;\n"
        "      }\n"
        "      if (res.data.binding && typeof applyBindingResponse === 'function') {\n"
        "        const bindingData = Object.assign({}, res.data.binding);\n"
        "        if (\n"
        "          !bindingData.current_tab_id &&\n"
        "          typeof bindingTransport !== 'undefined' &&\n"
        "          bindingTransport &&\n"
        "          typeof bindingTransport.getLocalTabId === 'function'\n"
        "        ) {\n"
        "          const localId = bindingTransport.getLocalTabId();\n"
        "          if (localId) {\n"
        "            bindingData.current_tab_id = localId;\n"
        "            bindingData.is_current_tab_bound = Boolean(bindingData.bound && bindingData.tab_id === localId);\n"
        "          }\n"
        "        }\n"
        "        applyBindingResponse({\n"
        "          reachable: true,\n"
        "          connected: true,\n"
        "          status: 200,\n"
        "          data: bindingData,\n"
        "          error: '',\n"
        "        });\n"
        "      }\n"
        "      const handoff = res.data.handoff;\n"
        "      const textToPaste = handoff.combined_text || [handoff.response_text, handoff.summary_text].filter(Boolean).join('\\n\\n');\n"
        "      if (!textToPaste) {\n"
        "        handoffSessionActive = false;\n"
        "        handoffTransport.ackHandoff(handoff.handoff_id, () => {});\n"
        "        return;\n"
        "      }\n"
        "      waitAndPasteHandoff(handoff.handoff_id, textToPaste, handoff.remaining_auto_tabs, handoff.handoff_kind, handoff.target_file);\n"
        "    });\n"
        "  }\n\n"
    )
