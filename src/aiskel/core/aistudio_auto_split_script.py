"""Module: @role: ブラウザ側での自動分割対象ファイル保持・順次実行・次ファイル移行・適用失敗リトライ制御のJavaScriptを生成する。"""

def build_auto_split_js() -> str:
    """ブラウザlocalStorage保持による自動分割モード制御スクリプトを返す。"""
    return (
        "  const AUTO_SPLIT_STORAGE_KEY = 'aiskel_auto_split_state_v1';\n"
        "  const MAX_AUTO_SPLIT_APPLY_RETRIES = 2;\n"
        "  const AUTO_SPLIT_STALE_MS = 12 * 60 * 60 * 1000;\n"
        "  const BUNDLE_ONLY_INPUT_RE = /^<ai_architecture_bundle>[\\s\\S]*<\\/ai_architecture_bundle>$/;\n"
        "  let autoSplitStartInFlight = false;\n"
        "  let autoSplitAdvanceInFlight = false;\n\n"
        "  function readRawAutoSplitState() {\n"
        "    try {\n"
        "      const raw = window.localStorage.getItem(AUTO_SPLIT_STORAGE_KEY);\n"
        "      if (!raw) return null;\n"
        "      const parsed = JSON.parse(raw);\n"
        "      if (!parsed || parsed.version !== 1 || !parsed.active) return null;\n"
        "      if (!Array.isArray(parsed.files) || !parsed.files.length) return null;\n"
        "      const idx = Number(parsed.currentIndex);\n"
        "      if (!Number.isInteger(idx) || idx < 0 || idx >= parsed.files.length) return null;\n"
        "      const updatedAt = Number(parsed.updatedAt || 0);\n"
        "      if (!updatedAt || (Date.now() - updatedAt) > AUTO_SPLIT_STALE_MS) {\n"
        "        window.localStorage.removeItem(AUTO_SPLIT_STORAGE_KEY);\n"
        "        return null;\n"
        "      }\n"
        "      return parsed;\n"
        "    } catch (_e) {\n"
        "      return null;\n"
        "    }\n"
        "  }\n\n"
        "  function saveAutoSplitState(state) {\n"
        "    try {\n"
        "      window.localStorage.setItem(AUTO_SPLIT_STORAGE_KEY, JSON.stringify(state));\n"
        "    } catch (_e) {}\n"
        "  }\n\n"
        "  function clearAutoSplitState() {\n"
        "    try {\n"
        "      window.localStorage.removeItem(AUTO_SPLIT_STORAGE_KEY);\n"
        "    } catch (_e) {}\n"
        "  }\n\n"
        "  function getActiveAutoSplitStateForCurrentProject() {\n"
        "    const state = readRawAutoSplitState();\n"
        "    if (!state) return null;\n"
        "    if (!bindingState || !bindingState.connected || !bindingState.projectRoot) return null;\n"
        "    if (state.projectRoot !== bindingState.projectRoot) return null;\n"
        "    return state;\n"
        "  }\n\n"
        "  function isAutoSplitActiveForCurrentProject() {\n"
        "    return Boolean(getActiveAutoSplitStateForCurrentProject());\n"
        "  }\n\n"
        "  function getAutoSplitSummaryForUi() {\n"
        "    const state = getActiveAutoSplitStateForCurrentProject();\n"
        "    if (!state) {\n"
        "      return {\n"
        "        autoSplitActive: false,\n"
        "        autoSplitCurrentIndex: 0,\n"
        "        autoSplitTotalCount: 0,\n"
        "        autoSplitCurrentFile: '',\n"
        "      };\n"
        "    }\n"
        "    const cur = state.files[state.currentIndex] || {};\n"
        "    return {\n"
        "      autoSplitActive: true,\n"
        "      autoSplitCurrentIndex: state.currentIndex,\n"
        "      autoSplitTotalCount: state.files.length,\n"
        "      autoSplitCurrentFile: String(cur.rel_path || ''),\n"
        "    };\n"
        "  }\n\n"
        "  function syncAutoSplitUiState() {\n"
        "    const summary = getAutoSplitSummaryForUi();\n"
        "    bindingState = Object.assign({}, bindingState, summary, {\n"
        "      autoRunEnabled: isAutoRunEffectiveEnabled(),\n"
        "    });\n"
        "    if (bindingUi && typeof bindingUi.render === 'function') {\n"
        "      bindingUi.render(bindingState);\n"
        "    }\n"
        "  }\n\n"
        "  function canReuseCurrentTabForSplitStart() {\n"
        "    if (typeof isChatConversationEmpty !== 'function' || !isChatConversationEmpty()) return false;\n"
        "    if (typeof findPromptInputElement !== 'function') return false;\n"
        "    const inputEl = findPromptInputElement();\n"
        "    if (!inputEl) return false;\n"
        "    if (typeof isPromptInputEmpty === 'function' && isPromptInputEmpty(inputEl)) return true;\n"
        "    const trimmed = typeof getEditableInputText === 'function' ? getEditableInputText(inputEl).trim() : '';\n"
        "    return BUNDLE_ONLY_INPUT_RE.test(trimmed);\n"
        "  }\n\n"
        "  function scheduleAutoSplitRun(commandsKey, pasteMeta, options) {\n"
        "    if (typeof scheduleAutoRunAfterPaste !== 'function' || typeof shouldScheduleAutoRun !== 'function') {\n"
        "      return false;\n"
        "    }\n"
        "    const preSnap = pasteMeta && pasteMeta.preSnap ? pasteMeta.preSnap : null;\n"
        "    const turnCtx = typeof getTurnContext === 'function'\n"
        "      ? getTurnContext()\n"
        "      : { userTurnCount: 0, modelTurns: [], modelIndices: [] };\n"
        "    const dispatchCtx = {\n"
        "      url: window.location.href,\n"
        "      resolvedUrl: window.location.href,\n"
        "      isNewChatHandoff: Boolean(options && options.isEmptyChat),\n"
        "      allowBackgroundDomSubmit: true,\n"
        "      domPasteVerified: true,\n"
        "      resetConsecutiveCounter: Boolean(options && options.resetConsecutiveCounter),\n"
        "      modelTurnRefs: turnCtx.modelTurns.slice(),\n"
        "      modelTurnSigs: turnCtx.modelTurns.map((turn) => buildModelTurnsContentSignature([turn])),\n"
        "      modelContentSig: buildModelContentSignature(turnCtx),\n"
        "      userTurnCountBefore: turnCtx.userTurnCount,\n"
        "      commandsKey: String(commandsKey || ('SPLIT::' + Date.now())),\n"
        "      pasteSeqBefore: pasteEventSeq,\n"
        "      inputTextBefore: preSnap ? preSnap.text : '',\n"
        "      chipCountBefore: preSnap ? preSnap.chipCount : 0,\n"
        "      chipSignatureBefore: preSnap ? preSnap.chipSignature : '0::',\n"
        "      hadContentBefore: preSnap ? preSnap.hasContent : false,\n"
        "      responsePasted: true,\n"
        "      commandOk: true,\n"
        "    };\n"
        "    const syntheticResponse = {\n"
        "      pasted: true,\n"
        "      auto_run: isAutoRunEffectiveEnabled(),\n"
        "      auto_run_allowed: autoRunAllowed,\n"
        "    };\n"
        "    if (!shouldScheduleAutoRun(syntheticResponse, dispatchCtx)) {\n"
        "      return false;\n"
        "    }\n"
        "    scheduleAutoRunAfterPaste(dispatchCtx);\n"
        "    return true;\n"
        "  }\n\n"
        "  function pasteSplitTextAndAutoRun(textToPaste, commandsKey, options) {\n"
        "    const opts = options || {};\n"
        "    const onDone = typeof opts.onDone === 'function' ? opts.onDone : null;\n"
        "    return waitAndPasteText({\n"
        "      textToPaste,\n"
        "      priority: 'normal',\n"
        "      timeoutMs: SUMMARY_PROMPT_PASTE_TIMEOUT_MS,\n"
        "      settleMs: 120,\n"
        "      requireEmptyInput: false,\n"
        "      replaceExisting: Boolean(opts.replaceExisting),\n"
        "      exactDuplicateCheck: true,\n"
        "      onAborted: () => {\n"
        "        if (onDone) onDone(false, '挿入が中断されました');\n"
        "      },\n"
        "      onSuccess: (_alreadyPresent, _insertedWithDraft, pasteMeta) => {\n"
        "        const scheduled = scheduleAutoSplitRun(commandsKey, pasteMeta, {\n"
        "          isEmptyChat: Boolean(opts.isEmptyChat),\n"
        "          resetConsecutiveCounter: Boolean(opts.resetConsecutiveCounter),\n"
        "        });\n"
        "        if (onDone) onDone(scheduled, scheduled ? '' : '自動送信のスケジュールに失敗しました');\n"
        "      },\n"
        "      onTimeout: () => {\n"
        "        showToast('aiskel チャット入力欄が見つからず自動分割を開始できませんでした', true);\n"
        "        if (onDone) onDone(false, 'チャット入力欄が見つかりませんでした');\n"
        "      },\n"
        "      onVerifyFailed: () => {\n"
        "        showToast('aiskel 自動分割プロンプトの挿入を確認できませんでした', true);\n"
        "        if (onDone) onDone(false, 'チャット欄への挿入を確認できませんでした');\n"
        "      },\n"
        "    });\n"
        "  }\n\n"
        "  function buildSplitTargetRequestPayload(splitState) {\n"
        "    const target = splitState.files[splitState.currentIndex];\n"
        "    return {\n"
        "      target_file: target.rel_path,\n"
        "      lines: target.lines,\n"
        "      chars: target.chars,\n"
        "      max_lines: splitState.maxLines,\n"
        "      max_chars: splitState.maxChars,\n"
        "      file_index: splitState.currentIndex + 1,\n"
        "      total_files: splitState.files.length,\n"
        "    };\n"
        "  }\n\n"
        "  function dispatchCurrentSplitFile(splitState, options, done) {\n"
        "    const finish = (ok, message) => {\n"
        "      if (typeof done === 'function') done(ok, message || '');\n"
        "    };\n"
        "    const target = splitState.files[splitState.currentIndex];\n"
        "    const reqPayload = buildSplitTargetRequestPayload(splitState);\n"
        "    const useCurrentTab = Boolean(options && options.allowCurrentEmptyTab) && canReuseCurrentTabForSplitStart();\n"
        "    if (useCurrentTab) {\n"
        "      if (!hasBindingTransport || typeof bindingTransport.getSplitPrompt !== 'function') {\n"
        "        finish(false, '自動分割プロンプト取得機能が利用できません');\n"
        "        return;\n"
        "      }\n"
        "      bindingTransport.getSplitPrompt(reqPayload, (res) => {\n"
        "        const data = (res && res.data) || {};\n"
        "        if (!res || !res.connected || !data.ok || !data.combined_text) {\n"
        "          const errMsg = (data && data.message) || (res && res.error) || '分割プロンプトの取得に失敗しました';\n"
        "          reportBridgeError('aiskel 自動分割エラー', errMsg, errMsg);\n"
        "          finish(false, errMsg);\n"
        "          return;\n"
        "        }\n"
        "        const prevOverride = autoRunUserOverride;\n"
        "        autoRunUserOverride = true;\n"
        "        syncAutoSplitUiState();\n"
        "        showToast(\n"
        "          'aiskel 自動分割開始 (' + (splitState.currentIndex + 1) + '/' + splitState.files.length + '): ' + target.rel_path,\n"
        "          false\n"
        "        );\n"
        "        const started = pasteSplitTextAndAutoRun(\n"
        "          data.combined_text,\n"
        "          'SPLIT_START::' + target.rel_path + '::' + Date.now(),\n"
        "          {\n"
        "            replaceExisting: true,\n"
        "            isEmptyChat: true,\n"
        "            resetConsecutiveCounter: true,\n"
        "            onDone: (ok, message) => {\n"
        "              if (!ok) {\n"
        "                autoRunUserOverride = prevOverride;\n"
        "              }\n"
        "              finish(ok, message);\n"
        "            },\n"
        "          }\n"
        "        );\n"
        "        if (!started) {\n"
        "          autoRunUserOverride = prevOverride;\n"
        "          finish(false, '貼付タスクの開始に失敗しました');\n"
        "        }\n"
        "      });\n"
        "      return;\n"
        "    }\n"
        "    if (!hasHandoffTransport || typeof handoffTransport.createSplitHandoff !== 'function') {\n"
        "      finish(false, '新規タブ引き継ぎ機能が利用できません');\n"
        "      return;\n"
        "    }\n"
        "    const handoffPayload = Object.assign({}, reqPayload, {\n"
        "      new_chat_url: buildSameAccountNewChatUrl(window.location.href),\n"
        "    });\n"
        "    handoffTransport.createSplitHandoff(handoffPayload, (res) => {\n"
        "      const data = (res && res.data) || {};\n"
        "      if (!res || !res.connected || !data.ok) {\n"
        "        const errMsg = (data && data.message) || (res && res.error) || '次ファイルの新規タブ引き継ぎに失敗しました';\n"
        "        clearAutoSplitState();\n"
        "        syncAutoSplitUiState();\n"
        "        reportBridgeError('aiskel 自動分割引き継ぎエラー', errMsg, errMsg);\n"
        "        finish(false, errMsg);\n"
        "        return;\n"
        "      }\n"
        "      if (typeof refreshBindingStatus === 'function') refreshBindingStatus();\n"
        "      showToast(\n"
        "        'aiskel 自動分割 (' + (splitState.currentIndex + 1) + '/' + splitState.files.length + '): ' + target.rel_path + ' を新タブで開始します',\n"
        "        false\n"
        "      );\n"
        "      finish(true, '');\n"
        "    });\n"
        "  }\n\n"
        "  function startAutoSplitMode(done) {\n"
        "    const finish = () => {\n"
        "      autoSplitStartInFlight = false;\n"
        "      if (typeof done === 'function') done();\n"
        "    };\n"
        "    if (autoSplitStartInFlight) {\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (!bindingState || !bindingState.connected || !bindingState.isCurrentTabBound) {\n"
        "      showToast('VSCodeと紐づけ中のタブでのみ自動分割を実行できます', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (!autoRunAllowed) {\n"
        "      showToast('自動送信が無効化されているため自動分割モードを開始できません', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    if (!hasBindingTransport || typeof bindingTransport.getBloatTargets !== 'function') {\n"
        "      showToast('aiskel b 対象取得機能が利用できません', true);\n"
        "      if (typeof done === 'function') done();\n"
        "      return;\n"
        "    }\n"
        "    autoSplitStartInFlight = true;\n"
        "    bindingTransport.getBloatTargets((res) => {\n"
        "      const data = (res && res.data) || {};\n"
        "      if (!res || !res.reachable) {\n"
        "        showToast('VSCodeブリッジへ接続できませんでした', true);\n"
        "        finish();\n"
        "        return;\n"
        "      }\n"
        "      if (!res.connected || !data.ok) {\n"
        "        const errMsg = (data && data.message) || res.error || ('HTTP ' + (res.status || '?'));\n"
        "        showToast('aiskel b 取得エラー: ' + errMsg, true);\n"
        "        finish();\n"
        "        return;\n"
        "      }\n"
        "      const files = Array.isArray(data.files) ? data.files : [];\n"
        "      if (!files.length) {\n"
        "        clearAutoSplitState();\n"
        "        syncAutoSplitUiState();\n"
        "        showToast('aiskel b: 肥大化ファイルは検出されませんでした', false);\n"
        "        finish();\n"
        "        return;\n"
        "      }\n"
        "      const nextState = {\n"
        "        version: 1,\n"
        "        projectRoot: String(data.project_root || bindingState.projectRoot || ''),\n"
        "        active: true,\n"
        "        files,\n"
        "        currentIndex: 0,\n"
        "        maxLines: Number(data.max_lines || 500),\n"
        "        maxChars: Number(data.max_chars || 25000),\n"
        "        applyRetryCount: 0,\n"
        "        updatedAt: Date.now(),\n"
        "      };\n"
        "      saveAutoSplitState(nextState);\n"
        "      syncAutoSplitUiState();\n"
        "      dispatchCurrentSplitFile(nextState, { allowCurrentEmptyTab: true }, (ok) => {\n"
        "        if (!ok) {\n"
        "          clearAutoSplitState();\n"
        "          syncAutoSplitUiState();\n"
        "        }\n"
        "        finish();\n"
        "      });\n"
        "    });\n"
        "  }\n\n"
        "  function stopAutoSplitMode(done) {\n"
        "    clearAutoSplitState();\n"
        "    clearAutoRunTimer();\n"
        "    if (typeof cancelActivePasteTask === 'function' && (!activePasteTask || activePasteTask.priority !== 'handoff')) {\n"
        "      cancelActivePasteTask();\n"
        "    }\n"
        "    syncAutoSplitUiState();\n"
        "    showToast('aiskel 自動分割モードを停止しました', false);\n"
        "    if (typeof done === 'function') done();\n"
        "  }\n\n"
        "  function handleAutoSplitTerminalApplyResult(data) {\n"
        "    const splitState = getActiveAutoSplitStateForCurrentProject();\n"
        "    if (!splitState || !data) return false;\n"
        "    if (!data.apply_attempted) {\n"
        "      if (data.stop_signal_detected) {\n"
        "        clearAutoSplitState();\n"
        "        syncAutoSplitUiState();\n"
        "        if (typeof reportBridgeError === 'function') {\n"
        "          reportBridgeError('aiskel 自動分割停止', '適用対象のパッチが見つからないまま完了合図を受信したため停止しました');\n"
        "        } else {\n"
        "          showToast('aiskel 自動分割停止: 適用対象パッチなし', true);\n"
        "        }\n"
        "        return true;\n"
        "      }\n"
        "      return false;\n"
        "    }\n"
        "    if (autoSplitAdvanceInFlight) return true;\n"
        "    const curFile = splitState.files[splitState.currentIndex] || { rel_path: '' };\n"
        "    if (data.applied) {\n"
        "      const nextIndex = splitState.currentIndex + 1;\n"
        "      if (nextIndex >= splitState.files.length) {\n"
        "        clearAutoSplitState();\n"
        "        syncAutoSplitUiState();\n"
        "        if (typeof clearErrorPanel === 'function') clearErrorPanel();\n"
        "        showToast('aiskel 自動分割: 全 ' + splitState.files.length + ' 件の分割・適用が完了しました！', false);\n"
        "        return true;\n"
        "      }\n"
        "      autoSplitAdvanceInFlight = true;\n"
        "      const nextState = Object.assign({}, splitState, {\n"
        "        currentIndex: nextIndex,\n"
        "        applyRetryCount: 0,\n"
        "        updatedAt: Date.now(),\n"
        "      });\n"
        "      saveAutoSplitState(nextState);\n"
        "      syncAutoSplitUiState();\n"
        "      if (typeof clearErrorPanel === 'function') clearErrorPanel();\n"
        "      dispatchCurrentSplitFile(nextState, { allowCurrentEmptyTab: false }, () => {\n"
        "        autoSplitAdvanceInFlight = false;\n"
        "      });\n"
        "      return true;\n"
        "    }\n"
        "    const nextRetry = Number(splitState.applyRetryCount || 0) + 1;\n"
        "    const detail = data.apply_message || 'パッチの自動適用に失敗しました';\n"
        "    if (nextRetry > MAX_AUTO_SPLIT_APPLY_RETRIES) {\n"
        "      clearAutoSplitState();\n"
        "      syncAutoSplitUiState();\n"
        "      if (typeof reportBridgeError === 'function') {\n"
        "        reportBridgeError(\n"
        "          'aiskel 自動分割停止 (aiskel a 連続失敗)',\n"
        "          '対象ファイル: ' + curFile.rel_path + '\\n' + detail,\n"
        "          detail\n"
        "        );\n"
        "      } else {\n"
        "        showToast('aiskel 自動分割停止: ' + detail, true);\n"
        "      }\n"
        "      return true;\n"
        "    }\n"
        "    const nextState = Object.assign({}, splitState, {\n"
        "      applyRetryCount: nextRetry,\n"
        "      updatedAt: Date.now(),\n"
        "    });\n"
        "    saveAutoSplitState(nextState);\n"
        "    syncAutoSplitUiState();\n"
        "    const retryPrompt = [\n"
        "      '【自動分割モード: aiskel a 適用エラー修正依頼 (' + nextRetry + '/' + MAX_AUTO_SPLIT_APPLY_RETRIES + ')】',\n"
        "      '対象ファイル: ' + curFile.rel_path,\n"
        "      'エラー内容:',\n"
        "      detail,\n"
        "      '',\n"
        "      '上記エラーを解消し、未適用の現行コードベースに対して単体でそのまま aiskel a 適用できる完全版パッチ（aiskel a 準拠形式）を再出力してください。',\n"
        "      '調査が必要な場合は aiskel c -d ...（1行ワンライナー）で該当ファイルを取得してください。',\n"
        "    ].join('\\n');\n"
        "    showToast('aiskel a 失敗のため修正依頼を自動送信します (' + nextRetry + '/' + MAX_AUTO_SPLIT_APPLY_RETRIES + ')', true);\n"
        "    const retryStarted = pasteSplitTextAndAutoRun(\n"
        "      retryPrompt,\n"
        "      'SPLIT_RETRY::' + curFile.rel_path + '::' + nextRetry + '::' + Date.now(),\n"
        "      {\n"
        "        replaceExisting: false,\n"
        "        isEmptyChat: false,\n"
        "        resetConsecutiveCounter: true,\n"
        "        onDone: (ok, msg) => {\n"
        "          if (!ok) {\n"
        "            clearAutoSplitState();\n"
        "            syncAutoSplitUiState();\n"
        "            if (typeof reportBridgeError === 'function') {\n"
        "              reportBridgeError('aiskel 自動分割停止 (リトライ送信失敗)', msg || detail, detail);\n"
        "            }\n"
        "          }\n"
        "        },\n"
        "      }\n"
        "    );\n"
        "    if (!retryStarted) {\n"
        "      clearAutoSplitState();\n"
        "      syncAutoSplitUiState();\n"
        "    }\n"
        "    return true;\n"
        "  }\n\n"
        "  window.addEventListener('storage', (ev) => {\n"
        "    if (ev && ev.key === AUTO_SPLIT_STORAGE_KEY) {\n"
        "      syncAutoSplitUiState();\n"
        "    }\n"
        "  });\n\n"
    )
