"""Module: @role: Runボタン手動送信前にデフォルトaiskelプロンプトを末尾追記・再送信するクライアントJavaScriptを生成する。"""

def build_monitor_run_prompt_js() -> str:
    """手動Runクリック時のプロンプト自動追記・検証・再送信ハンドラのJSコードを生成する。"""
    return (
        "  const RUN_PROMPT_FETCH_TIMEOUT_MS = 3000;\n"
        "  const RUN_PROMPT_CLICK_DELAY_MS = 40;\n"
        "  const RUN_PROMPT_ENABLE_POLL_MS = 40;\n"
        "  const RUN_PROMPT_ENABLE_TIMEOUT_MS = 1500;\n"
        "  const RUN_PROMPT_EXCLUDED_HOST_SELECTOR = [\n"
        "    'ms-chat-turn',\n"
        "    'ms-system-instructions',\n"
        "    'ms-run-settings',\n"
        "    'ms-prompt-options',\n"
        "    'ms-toolbar',\n"
        "    '[role=\"dialog\"]',\n"
        "    '[role=\"toolbar\"]',\n"
        "    '[data-aiskel-ui=\"true\"]',\n"
        "  ].join(', ');\n\n"
        "  function hasSpecializedAiskelPromptInText(text) {\n"
        "    if (!text || !String(text).trim()) return false;\n"
        "    if (typeof hasDiscoveryPromptMarker === 'function' && hasDiscoveryPromptMarker(text)) {\n"
        "      return true;\n"
        "    }\n"
        "    const nonCode = typeof stripFencedCodeForMarker === 'function' ? stripFencedCodeForMarker(text) : String(text);\n"
        "    if (/^[ \\t]*【(?:依頼タスク|自動分割モード|階層整理モード|設定推論モード):/m.test(nonCode)) return true;\n"
        "    if (/^[ \\t]*<proposed_implementation(?:_\\d+)?>[ \\t]*$/im.test(nonCode)) return true;\n"
        "    if (/^[ \\t]*=== (?:事前検証結果 \\(aiskel a --check エラー\\)|指定ディレクトリ解決エラー|ユーザーリクエスト（原文）|整理済みタスク・確認方針) ===[ \\t]*$/m.test(nonCode)) {\n"
        "      return true;\n"
        "    }\n"
        "    if (/^[ \\t]*(?:階層整理モードでは「ファイル名変更を許可」が無効|設定推論モードでは|設定推論パッチ(?:に置換ブロック|の構文))/m.test(nonCode)) {\n"
        "      return true;\n"
        "    }\n"
        "    return /^[ \\t]*提示されたパッチの適用(?:後に行われた静的コード解析)?に失敗したため、|^[ \\t]*提示されたパッチの適用に失敗しました \\(/m.test(nonCode);\n"
        "  }\n\n"
        "  function isPromptAlreadyPresentInInput(currentText, promptText) {\n"
        "    if (!currentText || !promptText) return false;\n"
        "    if (typeof isHandoffTextPresent === 'function') {\n"
        "      return isHandoffTextPresent(currentText, promptText);\n"
        "    }\n"
        "    return String(currentText).includes(String(promptText).trim());\n"
        "  }\n\n"
        "  function isSameThreadForPromptAppend(startUrl, startLoc) {\n"
        "    if (!startLoc || typeof parseThreadLocation !== 'function') {\n"
        "      return window.location.href === startUrl;\n"
        "    }\n"
        "    const curLoc = parseThreadLocation(window.location.href);\n"
        "    if (!curLoc) return false;\n"
        "    return (\n"
        "      curLoc.origin === startLoc.origin &&\n"
        "      curLoc.accountPrefix === startLoc.accountPrefix &&\n"
        "      curLoc.authUser === startLoc.authUser &&\n"
        "      curLoc.isPromptRoute &&\n"
        "      curLoc.threadKey === startLoc.threadKey\n"
        "    );\n"
        "  }\n\n"
        "  function readComposerTextForAppend(inputEl) {\n"
        "    if (!inputEl) return '';\n"
        "    const raw = typeof getEditableInputText === 'function' ? getEditableInputText(inputEl) : '';\n"
        "    const isPh = typeof isPlaceholderOnlyInputText === 'function'\n"
        "      ? isPlaceholderOnlyInputText(inputEl, raw)\n"
        "      : !raw.trim();\n"
        "    return isPh ? '' : raw;\n"
        "  }\n\n"
        "  function appendPromptTextAtBottom(inputEl, promptText) {\n"
        "    if (!inputEl || typeof pasteTextIntoPromptInput !== 'function') return '';\n"
        "    const existingText = readComposerTextForAppend(inputEl);\n"
        "    const cleanPrompt = String(promptText || '').trim();\n"
        "    if (!cleanPrompt) return '';\n"
        "    const cleanExisting = existingText.replace(/[ \\t\\r\\n\\u00A0]+$/, '');\n"
        "    const nextValue = cleanExisting ? (cleanExisting + '\\n\\n' + cleanPrompt) : cleanPrompt;\n"
        "    // 通常優先の保留ペーストが後から上書きしないよう事前停止\n"
        "    if (typeof cancelActivePasteTask === 'function' && (!activePasteTask || activePasteTask.priority !== 'handoff')) {\n"
        "      cancelActivePasteTask();\n"
        "    }\n"
        "    return pasteTextIntoPromptInput(inputEl, nextValue) ? nextValue : '';\n"
        "  }\n\n"
        "  function isExplicitButtonDisabled(el) {\n"
        "    if (!el || !isElementVisible(el)) return true;\n"
        "    return Boolean(el.disabled || el.hasAttribute('disabled') || el.getAttribute('aria-disabled') === 'true');\n"
        "  }\n\n"
        "  function resolveActiveRunTargets(runHost, submitBtn) {\n"
        "    let activeHost = (runHost && runHost.isConnected) ? runHost : null;\n"
        "    let activeBtn = (submitBtn && submitBtn.isConnected) ? submitBtn : null;\n"
        "    if (activeBtn && !activeHost && typeof activeBtn.closest === 'function') {\n"
        "      activeHost = activeBtn.closest('ms-run-button');\n"
        "    }\n"
        "    if (!activeBtn && activeHost && typeof findSubmitButtonInRunHost === 'function') {\n"
        "      activeBtn = findSubmitButtonInRunHost(activeHost, null);\n"
        "    }\n"
        "    if (!activeBtn && typeof findPromptRunButton === 'function') {\n"
        "      activeBtn = findPromptRunButton();\n"
        "      if (activeBtn && !activeHost && typeof activeBtn.closest === 'function') {\n"
        "        activeHost = activeBtn.closest('ms-run-button');\n"
        "      }\n"
        "    }\n"
        "    return { activeHost, activeBtn };\n"
        "  }\n\n"
        "  function isTargetSendableForManualBypass(activeHost, activeBtn) {\n"
        "    const targetBtn = activeBtn || activeHost;\n"
        "    if (!targetBtn) return false;\n"
        "    if (activeHost) {\n"
        "      if (isExplicitButtonDisabled(activeHost)) return false;\n"
        "      if (activeBtn && activeBtn !== activeHost) {\n"
        "        if (isExplicitButtonDisabled(activeBtn)) return false;\n"
        "      } else if (isRunButtonDisabled(activeHost)) {\n"
        "        return false;\n"
        "      }\n"
        "      if (hasRunButtonStopSignal(targetBtn, activeHost)) return false;\n"
        "    } else if (isExplicitButtonDisabled(targetBtn) || hasRunButtonStopSignal(targetBtn, null)) {\n"
        "      return false;\n"
        "    }\n"
        "    return true;\n"
        "  }\n\n"
        "  function canContinuePromptAppendFlow(flowSeq, startUrl, startLoc) {\n"
        "    if (flowSeq !== runPromptAppendSeq) return false;\n"
        "    if (!isMonitoringActive() || isInferring() || !isSameThreadForPromptAppend(startUrl, startLoc)) {\n"
        "      return false;\n"
        "    }\n"
        "    if (typeof isHandoffPendingOrActive === 'function' && isHandoffPendingOrActive()) {\n"
        "      return false;\n"
        "    }\n"
        "    return true;\n"
        "  }\n\n"
        "  function waitForSendableAndClickRun(runHost, submitBtn, flowSeq, startUrl, startLoc, deadline, onDone) {\n"
        "    if (!canContinuePromptAppendFlow(flowSeq, startUrl, startLoc)) {\n"
        "      onDone(false, null, 'aborted');\n"
        "      return;\n"
        "    }\n"
        "    const { activeHost, activeBtn } = resolveActiveRunTargets(runHost, submitBtn);\n"
        "    const targetBtn = activeBtn || activeHost;\n"
        "    if (activeHost && targetBtn && hasRunButtonStopSignal(targetBtn, activeHost)) {\n"
        "      onDone(false, null, 'aborted');\n"
        "      return;\n"
        "    }\n"
        "    if (!targetBtn || !isTargetSendableForManualBypass(activeHost, activeBtn)) {\n"
        "      if (Date.now() < deadline) {\n"
        "        window.setTimeout(() => {\n"
        "          waitForSendableAndClickRun(runHost, submitBtn, flowSeq, startUrl, startLoc, deadline, onDone);\n"
        "        }, RUN_PROMPT_ENABLE_POLL_MS);\n"
        "        return;\n"
        "      }\n"
        "      onDone(false, null, 'timeout');\n"
        "      return;\n"
        "    }\n"
        "    onDone(true, targetBtn, '');\n"
        "  }\n\n"
        "  function matchesManualSubmitBypassTarget(rawTarget) {\n"
        "    if (!pendingManualSubmitTarget) return false;\n"
        "    const el = rawTarget && rawTarget.nodeType === 3 ? rawTarget.parentElement : rawTarget;\n"
        "    if (el === pendingManualSubmitTarget) return true;\n"
        "    return Boolean(el && typeof pendingManualSubmitTarget.contains === 'function' && pendingManualSubmitTarget.contains(el));\n"
        "  }\n\n"
        "  function triggerManualRunClickBypass(targetBtn) {\n"
        "    if (!targetBtn) return;\n"
        "    pendingManualSubmitTarget = targetBtn;\n"
        "    try {\n"
        "      targetBtn.click();\n"
        "    } finally {\n"
        "      pendingManualSubmitTarget = null;\n"
        "    }\n"
        "  }\n\n"
        "  function interceptRunClickAndAppendPrompt(runHost, submitBtn, inputEl) {\n"
        "    if (typeof clearAutoRunTimer === 'function') {\n"
        "      clearAutoRunTimer();\n"
        "    }\n"
        "    const flowSeq = ++runPromptAppendSeq;\n"
        "    runPromptAppendInFlight = true;\n"
        "    const startUrl = window.location.href;\n"
        "    const startLoc = typeof parseThreadLocation === 'function' ? parseThreadLocation(startUrl) : null;\n"
        "    let settled = false;\n"
        "    let fetchResolved = false;\n"
        "    let fetchTimeoutId = null;\n\n"
        "    const abortFlow = () => {\n"
        "      if (settled) return;\n"
        "      settled = true;\n"
        "      if (fetchTimeoutId !== null) {\n"
        "        window.clearTimeout(fetchTimeoutId);\n"
        "        fetchTimeoutId = null;\n"
        "      }\n"
        "      if (flowSeq === runPromptAppendSeq) {\n"
        "        runPromptAppendInFlight = false;\n"
        "      }\n"
        "    };\n\n"
        "    const submitNow = (targetBtn) => {\n"
        "      if (settled) return;\n"
        "      if (!canContinuePromptAppendFlow(flowSeq, startUrl, startLoc)) {\n"
        "        abortFlow();\n"
        "        return;\n"
        "      }\n"
        "      settled = true;\n"
        "      if (fetchTimeoutId !== null) {\n"
        "        window.clearTimeout(fetchTimeoutId);\n"
        "        fetchTimeoutId = null;\n"
        "      }\n"
        "      if (flowSeq === runPromptAppendSeq) {\n"
        "        runPromptAppendInFlight = false;\n"
        "      }\n"
        "      const { activeBtn, activeHost } = resolveActiveRunTargets(runHost, targetBtn || submitBtn);\n"
        "      if (!isTargetSendableForManualBypass(activeHost, activeBtn)) {\n"
        "        showToast('aiskel 送信ボタンが無効状態のため送信できませんでした（もう一度Runを押してください）', true);\n"
        "        return;\n"
        "      }\n"
        "      triggerManualRunClickBypass(activeBtn || activeHost);\n"
        "    };\n\n"
        "    const startSendWait = () => {\n"
        "      waitForSendableAndClickRun(\n"
        "        runHost,\n"
        "        submitBtn,\n"
        "        flowSeq,\n"
        "        startUrl,\n"
        "        startLoc,\n"
        "        Date.now() + RUN_PROMPT_ENABLE_TIMEOUT_MS,\n"
        "        (ok, targetBtn, reason) => {\n"
        "          if (!ok) {\n"
        "            abortFlow();\n"
        "            if (reason === 'timeout') {\n"
        "              showToast('aiskel プロンプト追記後の送信ボタン有効化がタイムアウトしました（もう一度Runを押してください）', true);\n"
        "            }\n"
        "            return;\n"
        "          }\n"
        "          submitNow(targetBtn);\n"
        "        }\n"
        "      );\n"
        "    };\n\n"
        "    const proceedWithPrompt = (promptText, usedFallbackWarning) => {\n"
        "      if (settled || fetchResolved) return;\n"
        "      fetchResolved = true;\n"
        "      try {\n"
        "        if (!canContinuePromptAppendFlow(flowSeq, startUrl, startLoc)) {\n"
        "          abortFlow();\n"
        "          return;\n"
        "        }\n"
        "        const composerRoot = typeof findOutermostPromptComposer === 'function' ? findOutermostPromptComposer(runHost) : null;\n"
        "        const activeInput = (inputEl && inputEl.isConnected)\n"
        "          ? inputEl\n"
        "          : (typeof findPromptInputElement === 'function' ? findPromptInputElement(composerRoot) : null);\n"
        "        const curText = readComposerTextForAppend(activeInput);\n"
        "        const curSnap = typeof getPromptInputSnapshot === 'function' ? getPromptInputSnapshot(submitBtn) : null;\n"
        "        if ((!curSnap || !curSnap.hasContent) && !curText.trim()) {\n"
        "          abortFlow();\n"
        "          return;\n"
        "        }\n"
        "        const cleanPrompt = String(promptText || '').trim();\n"
        "        if (!cleanPrompt || !activeInput) {\n"
        "          if (usedFallbackWarning) {\n"
        "            showToast('aiskel プロンプトの取得に失敗したためそのまま送信します', true);\n"
        "          }\n"
        "          submitNow(submitBtn);\n"
        "          return;\n"
        "        }\n"
        "        if (hasSpecializedAiskelPromptInText(curText) || isPromptAlreadyPresentInInput(curText, cleanPrompt)) {\n"
        "          submitNow(submitBtn);\n"
        "          return;\n"
        "        }\n"
        "        const nextValue = appendPromptTextAtBottom(activeInput, cleanPrompt);\n"
        "        if (!nextValue) {\n"
        "          showToast('aiskel プロンプトの追記に失敗したためそのまま送信します', true);\n"
        "          submitNow(submitBtn);\n"
        "          return;\n"
        "        }\n"
        "        // Angular側ControlValueAccessorの入力値反映後にRunクリックを発火する\n"
        "        window.setTimeout(() => {\n"
        "          if (settled) return;\n"
        "          try {\n"
        "            if (!canContinuePromptAppendFlow(flowSeq, startUrl, startLoc)) {\n"
        "              abortFlow();\n"
        "              return;\n"
        "            }\n"
        "            const verifyInput = activeInput.isConnected\n"
        "              ? activeInput\n"
        "              : (typeof findPromptInputElement === 'function' ? findPromptInputElement(composerRoot) : null);\n"
        "            if (verifyInput && !isPromptAlreadyPresentInInput(readComposerTextForAppend(verifyInput), cleanPrompt)) {\n"
        "              if (!pasteTextIntoPromptInput(verifyInput, nextValue)) {\n"
        "                showToast('aiskel プロンプトの追記反映に失敗したため送信を中断しました（もう一度Runを押してください）', true);\n"
        "                abortFlow();\n"
        "                return;\n"
        "              }\n"
        "              window.setTimeout(() => {\n"
        "                if (settled) return;\n"
        "                try {\n"
        "                  startSendWait();\n"
        "                } catch (_e) {\n"
        "                  abortFlow();\n"
        "                }\n"
        "              }, RUN_PROMPT_CLICK_DELAY_MS);\n"
        "              return;\n"
        "            }\n"
        "            startSendWait();\n"
        "          } catch (_e) {\n"
        "            abortFlow();\n"
        "          }\n"
        "        }, RUN_PROMPT_CLICK_DELAY_MS);\n"
        "      } catch (_e) {\n"
        "        abortFlow();\n"
        "      }\n"
        "    };\n\n"
        "    fetchTimeoutId = window.setTimeout(() => {\n"
        "      fetchTimeoutId = null;\n"
        "      const fallback = typeof getCachedDefaultPromptIfValid === 'function' ? getCachedDefaultPromptIfValid() : '';\n"
        "      proceedWithPrompt(fallback, !fallback);\n"
        "    }, RUN_PROMPT_FETCH_TIMEOUT_MS);\n\n"
        "    fetchDefaultPromptForSubmit((ok, promptText) => {\n"
        "      if (fetchTimeoutId !== null) {\n"
        "        window.clearTimeout(fetchTimeoutId);\n"
        "        fetchTimeoutId = null;\n"
        "      }\n"
        "      proceedWithPrompt(promptText, !ok && !promptText);\n"
        "    });\n"
        "  }\n\n"
        "  function handleRunButtonClickEvent(ev) {\n"
        "    if (typeof ev.button === 'number' && ev.button !== 0) return;\n"
        "    if (!ev.isTrusted && matchesManualSubmitBypassTarget(ev.target)) {\n"
        "      pendingManualSubmitTarget = null;\n"
        "      handleManualSubmitAction();\n"
        "      return;\n"
        "    }\n"
        "    const rawTarget = ev.target;\n"
        "    const targetEl = rawTarget && rawTarget.nodeType === 3 ? rawTarget.parentElement : rawTarget;\n"
        "    if (targetEl && typeof targetEl.closest === 'function' && targetEl.closest('[data-aiskel-ui=\"true\"]')) {\n"
        "      return;\n"
        "    }\n"
        "    const runHost = targetEl && typeof targetEl.closest === 'function' ? targetEl.closest('ms-run-button') : null;\n"
        "    if (!runHost) return;\n"
        "    const clickedBtn = targetEl && typeof targetEl.closest === 'function' ? targetEl.closest('button, [role=\"button\"]') : null;\n"
        "    const popupAttr = clickedBtn ? clickedBtn.getAttribute('aria-haspopup') : '';\n"
        "    if (popupAttr && popupAttr !== 'false') return;\n"
        "    const submitBtn = typeof findSubmitButtonInRunHost === 'function'\n"
        "      ? findSubmitButtonInRunHost(runHost, targetEl)\n"
        "      : (runHost.querySelector('button.ctrl-enter-submits, button, [role=\"button\"]') || runHost);\n"
        "    if (!isElementVisible(runHost) || isExplicitButtonDisabled(runHost)) return;\n"
        "    if (submitBtn && submitBtn !== runHost) {\n"
        "      if (isExplicitButtonDisabled(submitBtn)) return;\n"
        "    } else if (isRunButtonDisabled(runHost)) {\n"
        "      return;\n"
        "    }\n"
        "    if (!ev.isTrusted) {\n"
        "      handleAutoSubmitAction();\n"
        "      return;\n"
        "    }\n"
        "    if (runHost.closest(RUN_PROMPT_EXCLUDED_HOST_SELECTOR)) {\n"
        "      if (!isInferring()) {\n"
        "        handleManualSubmitAction();\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    if (isInferring() || hasRunButtonStopSignal(submitBtn, runHost)) {\n"
        "      clearAutoRunTimer();\n"
        "      userCancelledRun = true;\n"
        "      userCancelRequestedAt = Date.now();\n"
        "      resubmitRequestedAt = 0;\n"
        "      consecutiveAutoRuns = 0;\n"
        "      lastAutoRunCommandKey = '';\n"
        "      return;\n"
        "    }\n"
        "    if (\n"
        "      !hasBindingTransport ||\n"
        "      !isMonitoringActive() ||\n"
        "      typeof fetchDefaultPromptForSubmit !== 'function' ||\n"
        "      (typeof isHandoffPendingOrActive === 'function' && isHandoffPendingOrActive())\n"
        "    ) {\n"
        "      handleManualSubmitAction();\n"
        "      return;\n"
        "    }\n"
        "    if (runPromptAppendInFlight) {\n"
        "      ev.preventDefault();\n"
        "      ev.stopPropagation();\n"
        "      if (typeof ev.stopImmediatePropagation === 'function') {\n"
        "        ev.stopImmediatePropagation();\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    const composerRoot = typeof findOutermostPromptComposer === 'function' ? findOutermostPromptComposer(runHost) : null;\n"
        "    const inputEl = typeof findPromptInputElement === 'function' ? findPromptInputElement(composerRoot) : null;\n"
        "    if (!inputEl) {\n"
        "      handleManualSubmitAction();\n"
        "      return;\n"
        "    }\n"
        "    const snap = typeof getPromptInputSnapshot === 'function' ? getPromptInputSnapshot(submitBtn) : null;\n"
        "    const existingText = readComposerTextForAppend(inputEl);\n"
        "    if ((!snap || !snap.hasContent) && !existingText.trim()) {\n"
        "      handleManualSubmitAction();\n"
        "      return;\n"
        "    }\n"
        "    if (hasSpecializedAiskelPromptInText(existingText)) {\n"
        "      handleManualSubmitAction();\n"
        "      return;\n"
        "    }\n"
        "    const cachedPrompt = typeof getCachedDefaultPromptIfValid === 'function' ? getCachedDefaultPromptIfValid() : '';\n"
        "    if (cachedPrompt && isPromptAlreadyPresentInInput(existingText, cachedPrompt)) {\n"
        "      handleManualSubmitAction();\n"
        "      return;\n"
        "    }\n"
        "    ev.preventDefault();\n"
        "    ev.stopPropagation();\n"
        "    if (typeof ev.stopImmediatePropagation === 'function') {\n"
        "      ev.stopImmediatePropagation();\n"
        "    }\n"
        "    interceptRunClickAndAppendPrompt(runHost, submitBtn, inputEl);\n"
        "  }\n\n"
    )
