"""Module: @role: Google AI Studioの自動Run送信・貼付反映判定・フォールバック制御を行うクライアントJavaScriptコードを生成する。"""


def build_monitor_autorun_js() -> str:
    """自動Runタイマー管理・貼付反映検証・Ctrl+Enterフォールバック処理のJS関数群を生成する。"""
    return (
        "  function clearAutoRunTimer() {\n"
        "    if (autoRunTimer !== null) {\n"
        "      window.clearTimeout(autoRunTimer);\n"
        "      autoRunTimer = null;\n"
        "    }\n"
        "    if (autoRunVerifyTimer !== null) {\n"
        "      window.clearTimeout(autoRunVerifyTimer);\n"
        "      autoRunVerifyTimer = null;\n"
        "      osTriggerRunInFlight = false;\n"
        "    }\n"
        "    autoRunDeadline = 0;\n"
        "    pendingAutoRunContext = null;\n"
        "    lastAutoRunDiagReason = '';\n"
        "  }\n\n"
        "  function isPasteReflectedForContext(ctxSnapshot, snap) {\n"
        "    if (!snap || !snap.hasContent) return false;\n"
        "    // waitAndPasteText側でDOM挿入後の内容一致を検証済みの場合、置換前後長差に依存せず反映済とする\n"
        "    if (ctxSnapshot.domPasteVerified) return true;\n"
        "    const pasteDetected = pasteEventSeq > ctxSnapshot.pasteSeqBefore;\n"
        "    const textUpdated = snap.text !== ctxSnapshot.inputTextBefore && snap.text.trim().length > 0;\n"
        "    const chipUpdated = snap.chipSignature !== ctxSnapshot.chipSignatureBefore && snap.chipCount > ctxSnapshot.chipCountBefore;\n"
        "    if (pasteDetected && (textUpdated || chipUpdated)) return true;\n"
        "    // pasteイベント捕捉漏れやチップ変換時でもOS貼付成功済みかつ明確な内容増加があれば反映済みと判定\n"
        "    if (ctxSnapshot.responsePasted) {\n"
        "      if (!ctxSnapshot.hadContentBefore) return true;\n"
        "      if (chipUpdated) return true;\n"
        "      if ((snap.text.length - ctxSnapshot.inputTextBefore.length) >= 16) return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function hasRunStartedForContext(ctxSnapshot) {\n"
        "    if (isInferring() || wasInferring) return true;\n"
        "    const curTurn = getTurnContext();\n"
        "    if (curTurn.userTurnCount > ctxSnapshot.userTurnCountBefore) return true;\n"
        "    const curSnap = getPromptInputSnapshot(findPromptRunButton());\n"
        "    if (curSnap.hasContainer && !curSnap.hasContent) return true;\n"
        "    return false;\n"
        "  }\n\n"
        "  function hasMatchingRefWithIntactContent(ctxSnapshot, el) {\n"
        "    const refs = ctxSnapshot.modelTurnRefs || [];\n"
        "    const sigs = ctxSnapshot.modelTurnSigs || [];\n"
        "    const idx = refs.indexOf(el);\n"
        "    if (idx === -1) return false;\n"
        "    // AngularによるDOM要素再利用での誤昇格を防ぐため内容署名も突合する\n"
        "    return buildModelTurnsContentSignature([el]) === (sigs[idx] || '');\n"
        "  }\n\n"
        "  function hasSameModelTurnsForSnapshot(ctxSnapshot, curTurn) {\n"
        "    if (!curTurn) return false;\n"
        "    // 新規チャット引き継ぎ時はAI応答ターン0件の初期状態も同一スレッドとして扱う\n"
        "    if (\n"
        "      ctxSnapshot.isNewChatHandoff &&\n"
        "      !(ctxSnapshot.modelTurnRefs || []).length &&\n"
        "      ctxSnapshot.userTurnCountBefore === 0\n"
        "    ) {\n"
        "      return !curTurn.modelTurns.length && curTurn.userTurnCount === 0;\n"
        "    }\n"
        "    if (!curTurn.modelTurns.length) return false;\n"
        "    if (curTurn.userTurnCount > ctxSnapshot.userTurnCountBefore) return false;\n"
        "    const refs = ctxSnapshot.modelTurnRefs || [];\n"
        "    const sigs = ctxSnapshot.modelTurnSigs || [];\n"
        "    // 仮想スクロールで先頭ターンが欠落しても残存ターンの内容一致なら同一と判定\n"
        "    if (refs.length > 0 && curTurn.modelTurns.every((el) => hasMatchingRefWithIntactContent(ctxSnapshot, el))) {\n"
        "      if (curTurn.modelTurns.some((el) => Boolean(sigs[refs.indexOf(el)]))) {\n"
        "        return true;\n"
        "      }\n"
        "    }\n"
        "    return Boolean(ctxSnapshot.modelContentSig) && buildModelContentSignature(curTurn) === ctxSnapshot.modelContentSig;\n"
        "  }\n\n"
        "  function isThreadUrlCompatibleForSnapshot(ctxSnapshot, canPromote) {\n"
        "    const beforeLoc = parseThreadLocation(ctxSnapshot.resolvedUrl || ctxSnapshot.url);\n"
        "    const currentLoc = parseThreadLocation(window.location.href);\n"
        "    if (!beforeLoc || !currentLoc) {\n"
        "      return window.location.href === ctxSnapshot.url;\n"
        "    }\n"
        "    if (\n"
        "      beforeLoc.origin !== currentLoc.origin ||\n"
        "      beforeLoc.accountPrefix !== currentLoc.accountPrefix ||\n"
        "      (beforeLoc.authUser && currentLoc.authUser && beforeLoc.authUser !== currentLoc.authUser) ||\n"
        "      !currentLoc.isPromptRoute\n"
        "    ) {\n"
        "      return false;\n"
        "    }\n"
        "    if (!beforeLoc.isNewChat) {\n"
        "      return currentLoc.threadKey === beforeLoc.threadKey;\n"
        "    }\n"
        "    if (currentLoc.isNewChat) {\n"
        "      return true;\n"
        "    }\n"
        "    // 新規チャット自動保存による/prompts/<id>昇格のみ許可し以後はロック\n"
        "    if (canPromote) {\n"
        "      ctxSnapshot.resolvedUrl = window.location.href;\n"
        "      return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function isAutoRunThreadIntact(ctxSnapshot) {\n"
        "    const curTurn = getTurnContext();\n"
        "    const sameTurn = hasSameModelTurnsForSnapshot(ctxSnapshot, curTurn);\n"
        "    if (!sameTurn) return false;\n"
        "    return isThreadUrlCompatibleForSnapshot(ctxSnapshot, sameTurn);\n"
        "  }\n\n"
        "  function isAutoRunPostSubmitThreadIntact(ctxSnapshot) {\n"
        "    const refs = ctxSnapshot.modelTurnRefs || [];\n"
        "    const sigs = ctxSnapshot.modelTurnSigs || [];\n"
        "    const curTurn = getTurnContext();\n"
        "    if (ctxSnapshot.isNewChatHandoff && !refs.length && ctxSnapshot.userTurnCountBefore === 0) {\n"
        "      const hasNewChatActivity =\n"
        "        curTurn.userTurnCount > 0 || isInferring() || wasInferring || !curTurn.modelTurns.length;\n"
        "      if (!isThreadUrlCompatibleForSnapshot(ctxSnapshot, hasNewChatActivity)) {\n"
        "        return false;\n"
        "      }\n"
        "      return hasNewChatActivity || document.querySelectorAll('ms-chat-turn').length > 0;\n"
        "    }\n"
        "    const hasConnectedIntactRef = refs.some((el, idx) => (\n"
        "      el && el.isConnected && Boolean(sigs[idx]) && buildModelTurnsContentSignature([el]) === sigs[idx]\n"
        "    ));\n"
        "    const hasMatchingTurn = hasConnectedIntactRef || hasSameModelTurnsForSnapshot(ctxSnapshot, curTurn);\n"
        "    if (!isThreadUrlCompatibleForSnapshot(ctxSnapshot, hasMatchingTurn)) {\n"
        "      return false;\n"
        "    }\n"
        "    if (hasMatchingTurn) return true;\n"
        "    return document.querySelectorAll('ms-chat-turn').length > 0;\n"
        "  }\n\n"
        "  function tryNativeCtrlEnterFallback(ctxSnapshot, reasonPrefix) {\n"
        "    if (!hasTriggerRunTransport || !isMonitoringActive()) {\n"
        "      reportBridgeError(\n"
        "        'aiskel 自動Run送信エラー',\n"
        "        reasonPrefix + '\\nコマンド: ' + (ctxSnapshot.commandsKey || '')\n"
        "      );\n"
        "      return;\n"
        "    }\n"
        "    if (!document.hasFocus() || document.visibilityState !== 'visible') {\n"
        "      reportBridgeError('aiskel 自動送信中止', 'タブが非アクティブのためCtrl+Enterフォールバックを中止しました。');\n"
        "      return;\n"
        "    }\n"
        "    if (autoRunVerifyTimer !== null) {\n"
        "      window.clearTimeout(autoRunVerifyTimer);\n"
        "      autoRunVerifyTimer = null;\n"
        "    }\n"
        "    osTriggerRunInFlight = true;\n"
        "    dispatchTriggerRun(\n"
        "      {\n"
        "        tab_title: document.title || '',\n"
        "        page_focused: document.hasFocus() && document.visibilityState === 'visible',\n"
        "      },\n"
        "      (ok, msg) => {\n"
        "        if (!isMonitoringActive() || !isAutoRunPostSubmitThreadIntact(ctxSnapshot)) {\n"
        "          osTriggerRunInFlight = false;\n"
        "          return;\n"
        "        }\n"
        "        if (!ok) {\n"
        "          osTriggerRunInFlight = false;\n"
        "          reportBridgeError(\n"
        "            'aiskel 自動Run送信エラー',\n"
        "            reasonPrefix + '\\nOS Ctrl+Enterフォールバックも失敗: ' + (msg || '不明なエラー')\n"
        "          );\n"
        "          return;\n"
        "        }\n"
        "        if (autoRunVerifyTimer !== null) {\n"
        "          window.clearTimeout(autoRunVerifyTimer);\n"
        "        }\n"
        "        autoRunVerifyTimer = window.setTimeout(() => {\n"
        "          autoRunVerifyTimer = null;\n"
        "          osTriggerRunInFlight = false;\n"
        "          if (!isMonitoringActive() || !isAutoRunPostSubmitThreadIntact(ctxSnapshot)) {\n"
        "            return;\n"
        "          }\n"
        "          if (!hasRunStartedForContext(ctxSnapshot)) {\n"
        "            reportBridgeError(\n"
        "              'aiskel 自動Run送信エラー',\n"
        "              reasonPrefix + '\\nOS Ctrl+Enter送信後も推論開始を確認できませんでした（手動でRunを押してください）'\n"
        "            );\n"
        "          } else if (ctxSnapshot.commandOk) {\n"
        "            clearErrorPanel();\n"
        "          }\n"
        "        }, AUTO_RUN_VERIFY_DELAY_MS);\n"
        "      }\n"
        "    );\n"
        "  }\n\n"
        "  function shouldScheduleAutoRun(responseData, dispatchCtx) {\n"
        "    if (!responseData || !responseData.pasted || !isMonitoringActive()) {\n"
        "      return false;\n"
        "    }\n"
        "    if (isInferring()) {\n"
        "      reportBridgeError('aiskel 自動送信スキップ', '推論中状態が残っているため自動送信をスキップしました。');\n"
        "      return false;\n"
        "    }\n"
        "    const serverAllows = Boolean(responseData.auto_run || responseData.auto_run_allowed);\n"
        "    if (!serverAllows) return false;\n"
        "    const effectiveEnabled = autoRunUserOverride !== null\n"
        "      ? autoRunUserOverride\n"
        "      : Boolean(responseData.auto_run);\n"
        "    if (!effectiveEnabled) return false;\n"
        "    if (!(dispatchCtx && dispatchCtx.allowBackgroundDomSubmit)) {\n"
        "      if (!document.hasFocus() || document.visibilityState !== 'visible') {\n"
        "        reportBridgeError('aiskel 自動送信スキップ', 'ブラウザタブが非アクティブまたは非表示のため自動送信をスキップしました。');\n"
        "        return false;\n"
        "      }\n"
        "    }\n"
        "    if (!isAutoRunThreadIntact(dispatchCtx)) {\n"
        "      reportBridgeError('aiskel 自動送信中止', '画面遷移またはスレッド変化を検知したため自動送信を中止しました。');\n"
        "      return false;\n"
        "    }\n"
        "    if (dispatchCtx && dispatchCtx.resetConsecutiveCounter) {\n"
        "      consecutiveAutoRuns = 0;\n"
        "      lastAutoRunCommandKey = '';\n"
        "    }\n"
        "    if (\n"
        "      (lastAutoRunCommandKey && dispatchCtx.commandsKey === lastAutoRunCommandKey) ||\n"
        "      consecutiveAutoRuns >= MAX_CONSECUTIVE_AUTO_RUNS\n"
        "    ) {\n"
        "      autoRunUserOverride = false;\n"
        "      bindingState = Object.assign({}, bindingState, { autoRunEnabled: false });\n"
        "      if (bindingUi) bindingUi.render(bindingState);\n"
        "      reportBridgeError(\n"
        "        'aiskel 自動送信一時停止',\n"
        "        '連続自動送信のループ防止のため自動送信を一時停止しました（コマンド: ' + dispatchCtx.commandsKey + '）'\n"
        "      );\n"
        "      return false;\n"
        "    }\n"
        "    return true;\n"
        "  }\n\n"
        "  function tryClickRunButtonAfterPaste() {\n"
        "    autoRunTimer = null;\n"
        "    const ctxSnapshot = pendingAutoRunContext;\n"
        "    if (!ctxSnapshot || !isMonitoringActive() || isInferring()) {\n"
        "      clearAutoRunTimer();\n"
        "      return;\n"
        "    }\n"
        "    if (!(ctxSnapshot && ctxSnapshot.allowBackgroundDomSubmit)) {\n"
        "      if (!document.hasFocus() || document.visibilityState !== 'visible') {\n"
        "        clearAutoRunTimer();\n"
        "        reportBridgeError('aiskel 自動送信中止', 'タブが非アクティブになったため自動送信を中止しました。');\n"
        "        return;\n"
        "      }\n"
        "    }\n"
        "    if (!isAutoRunThreadIntact(ctxSnapshot)) {\n"
        "      clearAutoRunTimer();\n"
        "      reportBridgeError('aiskel 自動送信中止', '画面またはスレッドが切り替わったため自動送信を中止しました。');\n"
        "      return;\n"
        "    }\n"
        "    const runBtn = findPromptRunButton();\n"
        "    const runHost = runBtn && typeof runBtn.closest === 'function'\n"
        "      ? (runBtn.closest('ms-run-button') || runBtn)\n"
        "      : null;\n"
        "    const snap = getPromptInputSnapshot(runBtn);\n"
        "    const reflected = isPasteReflectedForContext(ctxSnapshot, snap);\n"
        "    if (!runBtn || !runHost) {\n"
        "      lastAutoRunDiagReason = 'Runボタン(ms-run-button)が見つかりません';\n"
        "    } else if (snap.isAttachmentLoading) {\n"
        "      lastAutoRunDiagReason = '添付メディアの処理完了を待機しています';\n"
        "    } else if (isRunButtonDisabled(runHost) || isRunButtonDisabled(runBtn)) {\n"
        "      lastAutoRunDiagReason = 'Runボタンが無効(disabled)のままです';\n"
        "    } else if (hasRunButtonStopSignal(runBtn, runHost)) {\n"
        "      lastAutoRunDiagReason = 'Runボタンが停止(Stop)状態と判定されました';\n"
        "    } else if (!snap.hasContent) {\n"
        "      lastAutoRunDiagReason = '入力欄に貼り付けられたテキスト・添付チップを検出できません';\n"
        "    } else if (!reflected) {\n"
        "      lastAutoRunDiagReason = 'pasteイベントまたは入力内容の変化を確認できません';\n"
        "    }\n"
        "    if (runBtn && runHost && isSendableRunButton(runBtn, runHost) && reflected && !snap.isAttachmentLoading) {\n"
        "      clearAutoRunTimer();\n"
        "      consecutiveAutoRuns += 1;\n"
        "      lastAutoRunCommandKey = ctxSnapshot.commandsKey;\n"
        "      runBtn.click();\n"
        "      // click()が無視されるケースを検出しOSネイティブCtrl+Enterへフォールバックする\n"
        "      autoRunVerifyTimer = window.setTimeout(() => {\n"
        "        autoRunVerifyTimer = null;\n"
        "        if (!isMonitoringActive() || !isAutoRunPostSubmitThreadIntact(ctxSnapshot)) {\n"
        "          return;\n"
        "        }\n"
        "        if (hasRunStartedForContext(ctxSnapshot)) {\n"
        "          if (ctxSnapshot.commandOk) clearErrorPanel();\n"
        "          return;\n"
        "        }\n"
        "        tryNativeCtrlEnterFallback(ctxSnapshot, 'Runボタンのクリック後に推論開始を検出できませんでした');\n"
        "      }, AUTO_RUN_VERIFY_DELAY_MS);\n"
        "      return;\n"
        "    }\n"
        "    if (Date.now() < autoRunDeadline) {\n"
        "      autoRunTimer = window.setTimeout(tryClickRunButtonAfterPaste, AUTO_RUN_POLL_MS);\n"
        "    } else {\n"
        "      const diag = lastAutoRunDiagReason || '貼り付け反映待ちがタイムアウトしました';\n"
        "      clearAutoRunTimer();\n"
        "      // 添付処理未完了でのタイムアウト時は未完了送信を防ぐためCtrl+Enterを抑止\n"
        "      if (reflected && !snap.isAttachmentLoading) {\n"
        "        consecutiveAutoRuns += 1;\n"
        "        lastAutoRunCommandKey = ctxSnapshot.commandsKey;\n"
        "        tryNativeCtrlEnterFallback(ctxSnapshot, diag);\n"
        "      } else {\n"
        "        reportBridgeError(\n"
        "          'aiskel 自動送信タイムアウト',\n"
        "          '自動Runをスキップしました: ' + diag + '\\nコマンド: ' + (ctxSnapshot.commandsKey || '')\n"
        "        );\n"
        "      }\n"
        "    }\n"
        "  }\n\n"
        "  function scheduleAutoRunAfterPaste(dispatchCtx) {\n"
        "    clearAutoRunTimer();\n"
        "    if (!isMonitoringActive() || isInferring()) return;\n"
        "    pendingAutoRunContext = dispatchCtx;\n"
        "    autoRunDeadline = Date.now() + AUTO_RUN_TIMEOUT_MS;\n"
        "    autoRunTimer = window.setTimeout(tryClickRunButtonAfterPaste, AUTO_RUN_INITIAL_DELAY_MS);\n"
        "  }\n\n"
    )
