        "      'document_loading',\n"
        "      'auth_redirect',\n"
        "      'invalid_route',\n"
        "      'sign_in_required',\n"
        "      'auth_or_permission_error',\n"
        "      'authuser_mismatch',\n"
        "      'account_loading',\n"
        "      'account_unconfirmed',\n"
        "      'model_loading',\n"
        "      'model_unready',\n"
        "      'page_loading',\n"
        "    ];\n"
        "    if (!opts.allowUnreadyComposer) {\n"
        "      blockingReasons.push('composer_unready');\n"
        "    }\n"
        "    return reasons.some((r) => blockingReasons.includes(r));\n"
        "  }\n\n"
