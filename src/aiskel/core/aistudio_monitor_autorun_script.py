        "        if (typeof clearPendingSubmit === 'function') clearPendingSubmit();\n"
        "        const errTitle = postClickReadiness.hasAuthError ? 'aiskel 自動Run送信エラー' : 'aiskel 自動Run送信中止';\n"
        "        const errPrefix = postClickReadiness.hasAuthError\n"
        "          ? '送信直後に未認証または権限エラーを検出しました: '\n"
        "          : '送信直後にページ初期化または認証未完了状態を検出しました: ';\n"
        "        reportBridgeError(errTitle, errPrefix + describeReadinessBlockReason(postClickReadiness));\n"
        "        return;\n"
        "      }\n"
        "      tryNativeCtrlEnterFallback(ctxSnapshot, 'Runボタンのクリック後に推論開始を検出できませんでした');\n"
        "    }, AUTO_RUN_VERIFY_DELAY_MS);\n"
        "  }\n\n"
        "  function tryClickRunButtonAfterPaste() {\n"
        "    autoRunTimer = null;\n"
        "    const ctxSnapshot = pendingAutoRunContext;\n"
        "    if (!ctxSnapshot || !isMonitoringActive() || isInferring()) {\n"
        "      clearAutoRunTimer();\n"
        "      return;\n"
        "    }\n"
        "    const deleteBusy = cleanupTurnsInFlight || (typeof isTurnDeleteInFlight === 'function' && isTurnDeleteInFlight());\n"
        "    if (autoRunCleanupInFlight || (deleteBusy && Date.now() < autoRunDeadline)) {\n"
        "      autoRunTimer = window.setTimeout(tryClickRunButtonAfterPaste, AUTO_RUN_POLL_MS);\n"
        "      return;\n"
        "    }\n"
        "    if (!(ctxSnapshot && ctxSnapshot.allowBackgroundDomSubmit)) {\n"
        "      if (!document.hasFocus() || document.visibilityState !== 'visible') {\n"
        "        clearAutoRunTimer();\n"
        "        reportBridgeError('aiskel 自動送信中止', 'タブが非アクティブになったため自動送信を中止しました。');\n"
        "        return;\n"
        "      }\n"
        "    }\n"
        "    const isAuthRedirect = typeof isAuthRedirectLocation === 'function' && isAuthRedirectLocation(window.location.href);\n"
        "    if (isAuthRedirect) {\n"
        "      ctxSnapshot.authReadyStableSince = 0;\n"
