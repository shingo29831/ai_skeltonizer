        "  }\n\n"
        "  function isThreadUrlCompatibleForSnapshot(ctxSnapshot, canPromote) {\n"
        "    const beforeLoc = parseThreadLocation(ctxSnapshot.resolvedUrl || ctxSnapshot.url);\n"
