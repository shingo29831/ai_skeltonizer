        "      return false;\n"
        "    }\n"
        "    if (hasMatchingTurn) return true;\n"
        "    return document.querySelectorAll('ms-chat-turn').length > 0;\n"
        "  }\n\n"
        "  function tryNativeCtrlEnterFallback(ctxSnapshot, reasonPrefix) {\n"
        "    if (!isMonitoringActive()) {\n"
        "      clearAutoRunTimer();\n"
        "      return;\n"
        "    }\n"
        "    const readiness = typeof getPageAuthReadinessState === 'function' ? getPageAuthReadinessState() : null;\n"
        "    if (readiness && hasBlockingAuthOrInitReadiness(readiness)) {\n"
        "      reportBridgeError(\n"
        "        'aiskel 自動Run送信中止',\n"
        "        reasonPrefix + '\\n認証・ページ初期化が完了していないためCtrl+Enter送信を抑止しました: ' + describeReadinessBlockReason(readiness)\n"
        "      );\n"
        "      return;\n"
        "    }\n"
        "    if (!hasTriggerRunTransport) {\n"
        "      reportBridgeError(\n"
        "        'aiskel 自動Run送信エラー',\n"
        "        reasonPrefix + '\\nコマンド: ' + (ctxSnapshot.commandsKey || '')\n"
        "      );\n"
        "      return;\n"
        "    }\n"
        "    if (!document.hasFocus() || document.visibilityState !== 'visible') {\n"
        "      reportBridgeError('aiskel 自動送信中止', 'タブが非アクティブのためCtrl+Enterフォールバックを中止しました。');\n"
        "      return;\n"
        "    }\n"
        "    if (autoRunVerifyTimer !== null) {\n"
        "      window.clearTimeout(autoRunVerifyTimer);\n"
        "      autoRunVerifyTimer = null;\n"
        "    }\n"
        "    if (typeof markSubmitPending === 'function') {\n"
        "      markSubmitPending();\n"
        "    }\n"
        "    if (!pendingCopyResponseSubmit && typeof capturePendingCopyResponseOnSubmit === 'function') {\n"
        "      capturePendingCopyResponseOnSubmit(true, ctxSnapshot);\n"
        "    }\n"
        "    osTriggerRunInFlight = true;\n"
