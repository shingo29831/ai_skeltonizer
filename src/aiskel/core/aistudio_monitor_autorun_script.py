        "      return 'モデルの初期化完了を待機しています';\n"
        "    }\n"
        "    if (reasons.includes('page_loading') || reasons.includes('document_loading')) {\n"
        "      return 'Google AI Studioのページ初期ロード完了を待機しています';\n"
        "    }\n"
        "    if (reasons.includes('invalid_route')) return 'プロンプト画面への遷移完了を待機しています';\n"
        "    if (reasons.includes('composer_unready')) return 'プロンプト入力欄の準備完了を待機しています';\n"
        "    if (reasons.includes('run_button_missing')) return 'Runボタンの表示を待機しています';\n"
        "    if (readiness.inferring) return '推論処理の完了を待機しています';\n"
        "    if (readiness.attachmentLoading) return '添付メディアの処理完了を待機しています';\n"
        "    if (!readiness.sendableRunButton) return 'Runボタンが送信可能になるのを待機しています';\n"
        "    return 'ページ初期化完了を待機しています';\n"
        "  }\n\n"
        "  function isReadinessReadyToSubmit(readiness) {\n"
        "    if (!readiness) return true;\n"
        "    return Boolean(readiness.ready && readiness.canSendNow);\n"
        "  }\n\n"
        "  function hasBlockingAuthOrInitReadiness(readiness, options) {\n"
        "    if (!readiness) return false;\n"
