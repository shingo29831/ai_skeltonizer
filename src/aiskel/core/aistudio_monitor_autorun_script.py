        "    }\n"
        "    if (dispatchCtx && dispatchCtx.resetConsecutiveCounter) {\n"
        "      consecutiveAutoRuns = 0;\n"
        "      lastAutoRunCommandKey = '';\n"
        "    }\n"
        "    if (\n"
        "      (lastAutoRunCommandKey && dispatchCtx.commandsKey === lastAutoRunCommandKey) ||\n"
        "      consecutiveAutoRuns >= MAX_CONSECUTIVE_AUTO_RUNS\n"
        "    ) {\n"
        "      autoRunUserOverride = false;\n"
        "      bindingState = Object.assign({}, bindingState, { autoRunEnabled: false });\n"
        "      if (bindingUi) bindingUi.render(bindingState);\n"
        "      reportBridgeError(\n"
        "        'aiskel 自動送信一時停止',\n"
        "        '連続自動送信のループ防止のため自動送信を一時停止しました（コマンド: ' + dispatchCtx.commandsKey + '）'\n"
        "      );\n"
        "      return false;\n"
        "    }\n"
        "    return true;\n"
        "  }\n\n"
        "  function submitAutoRunWithButton(ctxSnapshot, runBtn) {\n"
        "    const preClickReadiness = typeof getPageAuthReadinessState === 'function' ? getPageAuthReadinessState() : null;\n"
        "    if (preClickReadiness && !isReadinessReadyToSubmit(preClickReadiness)) {\n"
        "      ctxSnapshot.authReadyStableSince = 0;\n"
        "      const hardLimit = ctxSnapshot.hardDeadline || autoRunDeadline;\n"
        "      if (Date.now() < Math.min(autoRunDeadline, hardLimit)) {\n"
        "        lastAutoRunDiagReason = describeReadinessBlockReason(preClickReadiness);\n"
        "        pendingAutoRunContext = ctxSnapshot;\n"
        "        autoRunTimer = window.setTimeout(tryClickRunButtonAfterPaste, AUTO_RUN_POLL_MS);\n"
        "        return;\n"
        "      }\n"
        "      clearAutoRunTimer();\n"
        "      reportBridgeError(\n"
        "        'aiskel 自動Run送信中止',\n"
        "        '認証・初期化完了を確認できなかったため自動送信を中止しました: ' + describeReadinessBlockReason(preClickReadiness)\n"
        "      );\n"
        "      return;\n"
        "    }\n"
        "    clearAutoRunTimer();\n"
        "    consecutiveAutoRuns += 1;\n"
        "    lastAutoRunCommandKey = ctxSnapshot.commandsKey;\n"
        "    if (typeof markSubmitPending === 'function') {\n"
        "      markSubmitPending();\n"
        "    }\n"
        "    if (typeof capturePendingCopyResponseOnSubmit === 'function') {\n"
        "      capturePendingCopyResponseOnSubmit(true, ctxSnapshot);\n"
        "    }\n"
        "    runBtn.click();\n"
        "    // click()が無視されるケースを検出しOSネイティブCtrl+Enterへフォールバックする\n"
        "    autoRunVerifyTimer = window.setTimeout(() => {\n"
        "      autoRunVerifyTimer = null;\n"
        "      if (!isMonitoringActive() || !isAutoRunPostSubmitThreadIntact(ctxSnapshot)) {\n"
        "        if (typeof clearPendingSubmit === 'function') clearPendingSubmit();\n"
        "        return;\n"
        "      }\n"
        "      if (hasRunStartedForContext(ctxSnapshot)) {\n"
        "        if (ctxSnapshot.commandOk) clearErrorPanel();\n"
        "        return;\n"
        "      }\n"
        "      const postClickReadiness = typeof getPageAuthReadinessState === 'function' ? getPageAuthReadinessState() : null;\n"
