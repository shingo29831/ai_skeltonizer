"""Module: @role: Google AI Studio拡張機能のBackground Service Worker用JavaScriptを生成する。"""
import json
from typing import Optional

from .background_handlers import (
    build_background_binding_handlers_js,
    build_background_handoff_handlers_js,
)
from .network import (
    DEFAULT_BRIDGE_HOST,
    DEFAULT_BRIDGE_PORT,
    format_host_for_url,
    resolve_client_host,
)

def build_background_js(
    host: str = DEFAULT_BRIDGE_HOST,
    port: int = DEFAULT_BRIDGE_PORT,
    token: Optional[str] = None,
) -> str:
    """ページCSPやMixed Contentを回避してローカルブリッジへAPI中継およびタブ紐づけ管理を行うService Workerを生成する。"""
    url_host = format_host_for_url(resolve_client_host(host))
    base_url = f"http://{url_host}:{port}"
    token_literal = json.dumps(token or "")
    base_url_literal = json.dumps(base_url)
    return (
        "'use strict';\n\n"
        f"const BRIDGE_BASE_URL = {base_url_literal};\n"
        f"const BRIDGE_TOKEN = {token_literal};\n"
        "const AISTUDIO_TAB_PATTERNS = ['https://aistudio.google.com/*'];\n"
        "const pendingHandoffsByTab = new Map();\n"
        "const suppressedAutoBindTabIds = new Set();\n\n"
        "function appendHandoffHash(urlStr, handoffId) {\n"
        "  try {\n"
        "    const u = new URL(urlStr);\n"
        "    const raw = (u.hash || '').replace(/^#/, '');\n"
        "    const parts = raw ? raw.split('&').filter((p) => p && !p.startsWith('aiskel_handoff=')) : [];\n"
        "    parts.push('aiskel_handoff=' + encodeURIComponent(handoffId));\n"
        "    u.hash = parts.join('&');\n"
        "    return u.toString();\n"
        "  } catch (_e) {\n"
        "    const sep = urlStr.indexOf('#') === -1 ? '#' : '&';\n"
        "    return urlStr + sep + 'aiskel_handoff=' + encodeURIComponent(handoffId);\n"
        "  }\n"
        "}\n\n"
        "function createTabPreservingContext(baseProps, senderTab, cb) {\n"
        "  const fullProps = Object.assign({}, baseProps);\n"
        "  if (senderTab) {\n"
        "    if (senderTab.windowId != null) fullProps.windowId = senderTab.windowId;\n"
        "    if (typeof senderTab.index === 'number') fullProps.index = senderTab.index + 1;\n"
        "    if (senderTab.id != null) fullProps.openerTabId = senderTab.id;\n"
        "    if (senderTab.cookieStoreId) fullProps.cookieStoreId = senderTab.cookieStoreId;\n"
        "  }\n"
        "  chrome.tabs.create(fullProps, (tab) => {\n"
        "    if (!chrome.runtime.lastError && tab && tab.id != null) {\n"
        "      cb(tab);\n"
        "      return;\n"
        "    }\n"
        "    // cookieStoreId/openerTabId非対応や権限制約時は基本プロパティでフォールバック\n"
        "    chrome.tabs.create(baseProps, (fallbackTab) => {\n"
        "      if (chrome.runtime.lastError || !fallbackTab || fallbackTab.id == null) {\n"
        "        cb(null);\n"
        "        return;\n"
        "      }\n"
        "      cb(fallbackTab);\n"
        "    });\n"
        "  });\n"
        "}\n\n"
        "function formatTabId(tabId) {\n"
        "  return 'chrome-tab:' + String(tabId);\n"
        "}\n\n"
        "function getSenderTabId(sender) {\n"
        "  if (sender && sender.tab && sender.tab.id != null) {\n"
        "    return formatTabId(sender.tab.id);\n"
        "  }\n"
        "  return '';\n"
        "}\n\n"
        "async function bridgeRequest(path, method, bodyObj) {\n"
        "  const headers = {};\n"
        "  if (BRIDGE_TOKEN) {\n"
        "    headers['X-Aiskel-Token'] = BRIDGE_TOKEN;\n"
        "  }\n"
        "  const init = { method, headers };\n"
        "  if (bodyObj !== undefined) {\n"
        "    headers['Content-Type'] = 'application/json';\n"
        "    init.body = JSON.stringify(bodyObj);\n"
        "  }\n"
        "  const res = await fetch(BRIDGE_BASE_URL + path, init);\n"
        "  const data = await res.json().catch(() => ({}));\n"
        "  const apiOk = res.status >= 200 && res.status < 300 && Boolean(data && data.ok === true);\n"
        "  return {\n"
        "    reachable: true,\n"
        "    connected: apiOk,\n"
        "    status: res.status,\n"
        "    data,\n"
        "    error: apiOk ? '' : String((data && data.message) || ('HTTP ' + res.status)),\n"
        "  };\n"
        "}\n\n"
        "function enrichBindingData(data, currentTabId, isConnected) {\n"
        "  const copy = Object.assign({}, data || {});\n"
        "  copy.current_tab_id = currentTabId || '';\n"
        "  copy.is_current_tab_bound = Boolean(isConnected && copy.bound && currentTabId && copy.tab_id === currentTabId);\n"
        "  return copy;\n"
        "}\n\n"
        "function broadcastBindingUpdated(bindingData, extraFields) {\n"
        "  const payloadData = extraFields ? Object.assign({}, bindingData || {}, extraFields) : bindingData;\n"
        "  try {\n"
        "    chrome.tabs.query({ url: AISTUDIO_TAB_PATTERNS }, (tabs) => {\n"
        "      if (chrome.runtime.lastError || !Array.isArray(tabs)) return;\n"
        "      for (const tab of tabs) {\n"
        "        if (tab.id == null) continue;\n"
        "        try {\n"
        "          chrome.tabs.sendMessage(\n"
        "            tab.id,\n"
        "            { type: 'AISKEL_BINDING_UPDATED', binding: payloadData, tab_id: formatTabId(tab.id) },\n"
        "            () => { void chrome.runtime.lastError; }\n"
        "          );\n"
        "        } catch (_e) {}\n"
        "      }\n"
        "    });\n"
        "  } catch (_e) {}\n"
        "}\n\n"
        "function resolveTargetTab(message, sender, cb) {\n"
        "  const explicitId = message && message.tabId != null ? message.tabId : (sender && sender.tab ? sender.tab.id : null);\n"
        "  if (explicitId == null) {\n"
        "    cb(null);\n"
        "    return;\n"
        "  }\n"
        "  try {\n"
        "    chrome.tabs.get(explicitId, (tab) => {\n"
        "      if (chrome.runtime.lastError || !tab) {\n"
        "        cb(sender && sender.tab ? sender.tab : { id: explicitId, title: message.tab_title || '', url: message.tab_url || '' });\n"
        "        return;\n"
        "      }\n"
        "      cb(tab);\n"
        "    });\n"
        "  } catch (_e) {\n"
        "    cb(sender && sender.tab ? sender.tab : { id: explicitId, title: message.tab_title || '', url: message.tab_url || '' });\n"
        "  }\n"
        "}\n\n"
        "chrome.tabs.onRemoved.addListener((tabId) => {\n"
        "  if (tabId == null) return;\n"
        "  const tabIdStr = formatTabId(tabId);\n"
        "  pendingHandoffsByTab.delete(tabIdStr);\n"
        "  suppressedAutoBindTabIds.delete(tabIdStr);\n"
        "  bridgeRequest('/api/unbind', 'POST', { tab_id: tabIdStr })\n"
        "    .then((res) => {\n"
        "      if (res.connected && res.data) {\n"
        "        broadcastBindingUpdated(res.data);\n"
        "      }\n"
        "    })\n"
        "    .catch(() => {});\n"
        "});\n\n"
        "chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {\n"
        "  if (!message || !message.type) {\n"
        "    return false;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_EXECUTE') {\n"
        "    const payload = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) {\n"
        "      payload.tab_id = senderTabId;\n"
        "    } else if (!payload.tab_id) {\n"
        "      payload.tab_id = 'unknown-tab';\n"
        "    }\n"
        "    bridgeRequest('/api/execute', 'POST', payload)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_TRIGGER_RUN') {\n"
        "    const payload = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) {\n"
        "      payload.tab_id = senderTabId;\n"
        "    }\n"
        "    bridgeRequest('/api/trigger_run', 'POST', payload)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_RUN_COMMAND') {\n"
        "    const payload = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) {\n"
        "      payload.tab_id = senderTabId;\n"
        "    }\n"
        "    bridgeRequest('/api/run_command', 'POST', payload)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_STATUS') {\n"
        "    const currentTabId = getSenderTabId(sender) || (message.tab_id || '');\n"
        "    const isTabActive = sender && sender.tab ? Boolean(sender.tab.active) : true;\n"
        "    // Content Script新規読込時のみリロード前セッションの抑止フラグを解除\n"
        "    if (message.client_boot && currentTabId) {\n"
        "      suppressedAutoBindTabIds.delete(currentTabId);\n"
        "    }\n"
        "    // 新規タブの/api/bind完了前に古い紐づけ状態を取得して競合上書きするのを防止\n"
        "    const pendingHandoff = currentTabId ? pendingHandoffsByTab.get(currentTabId) : null;\n"
        "    const waitPending = pendingHandoff && pendingHandoff.bindPromise\n"
        "      ? pendingHandoff.bindPromise.catch(() => null)\n"
        "      : Promise.resolve();\n"
        "    waitPending\n"
        "      .then(() => bridgeRequest('/api/binding', 'GET'))\n"
        "      .then((res) => {\n"
        "        if (!res.reachable) {\n"
        "          suppressedAutoBindTabIds.clear();\n"
        "        }\n"
        "        res.data = enrichBindingData(res.data, currentTabId, res.connected);\n"
        "        if (res.connected) {\n"
        "          res.data.is_tab_active = isTabActive;\n"
        "          res.data.auto_bind_suppressed = Boolean(currentTabId && suppressedAutoBindTabIds.has(currentTabId));\n"
        "        }\n"
        "        sendResponse(res);\n"
        "      })\n"
        "      .catch((err) => {\n"
        "        suppressedAutoBindTabIds.clear();\n"
        "        sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) });\n"
        "      });\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_PROMPT') {\n"
        "    const pattern = typeof message.pattern === 'string' && message.pattern.trim() ? message.pattern.trim() : 'default';\n"
        "    bridgeRequest('/api/prompt?pattern=' + encodeURIComponent(pattern), 'GET')\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_SUMMARY_PROMPT') {\n"
        "    const pattern = typeof message.pattern === 'string' && message.pattern.trim() ? message.pattern.trim() : 'default';\n"
        "    const body = { pattern };\n"
        "    if (message.two_stage !== undefined) {\n"
        "      body.two_stage = message.two_stage;\n"
        "    }\n"
        "    bridgeRequest('/api/summary_prompt', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_BLOAT_TARGETS') {\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    const body = senderTabId ? { tab_id: senderTabId } : {};\n"
        "    bridgeRequest('/api/bloat/targets', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_SPLIT_PROMPT') {\n"
        "    const body = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) body.tab_id = senderTabId;\n"
        "    bridgeRequest('/api/split/prompt', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_ORGANIZE_TARGETS') {\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    const body = senderTabId ? { tab_id: senderTabId } : {};\n"
        "    bridgeRequest('/api/organize/targets', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_ORGANIZE_PROMPT') {\n"
        "    const body = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) body.tab_id = senderTabId;\n"
        "    bridgeRequest('/api/organize/prompt', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_CONFIG_PROMPT') {\n"
        "    const body = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) body.tab_id = senderTabId;\n"
        "    bridgeRequest('/api/config/prompt', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_SET_HANDOFF_MAX_TABS') {\n"
        "    const currentTabId = message.tabId != null ? formatTabId(message.tabId) : (getSenderTabId(sender) || '');\n"
        "    const body = { patch_handoff_max_tabs: message.patch_handoff_max_tabs };\n"
        "    if (currentTabId) {\n"
        "      body.tab_id = currentTabId;\n"
        "    }\n"
        "    bridgeRequest('/api/handoff/max_tabs', 'POST', body)\n"
        "      .then((res) => {\n"
        "        const rawData = res.data;\n"
        "        if (res.connected && rawData) {\n"
        "          broadcastBindingUpdated(rawData);\n"
        "        }\n"
        "        res.data = enrichBindingData(rawData, currentTabId, res.connected);\n"
        "        sendResponse(res);\n"
        "      })\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_INSERT_SUMMARY_PROMPT') {\n"
        "    if (message.tabId == null) {\n"
        "      sendResponse({ ok: false, error: '対象タブを指定してください' });\n"
        "      return false;\n"
        "    }\n"
        "    try {\n"
        "      chrome.tabs.sendMessage(message.tabId, { type: 'AISKEL_INSERT_SUMMARY_PROMPT' }, (resp) => {\n"
        "        if (chrome.runtime.lastError) {\n"
        "          sendResponse({\n"
        "            ok: false,\n"
        "            error: '対象タブへ送信できませんでした。ページを再読み込みしてからお試しください (' + chrome.runtime.lastError.message + ')',\n"
        "          });\n"
        "          return;\n"
        "        }\n"
        "        sendResponse(resp && typeof resp === 'object' ? resp : { ok: true });\n"
        "      });\n"
        "    } catch (err) {\n"
        "      sendResponse({ ok: false, error: String(err) });\n"
        "    }\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_START_CONFIG_INFER') {\n"
        "    if (message.tabId == null) {\n"
        "      sendResponse({ ok: false, error: '対象タブを指定してください' });\n"
        "      return false;\n"
        "    }\n"
        "    try {\n"
        "      chrome.tabs.sendMessage(message.tabId, { type: 'AISKEL_START_CONFIG_INFER' }, (resp) => {\n"
        "        if (chrome.runtime.lastError) {\n"
        "          sendResponse({\n"
        "            ok: false,\n"
        "            error: '対象タブへ送信できませんでした。ページを再読み込みしてからお試しください (' + chrome.runtime.lastError.message + ')',\n"
        "          });\n"
        "          return;\n"
        "        }\n"
        "        sendResponse(resp && typeof resp === 'object' ? resp : { ok: true });\n"
        "      });\n"
        "    } catch (err) {\n"
        "      sendResponse({ ok: false, error: String(err) });\n"
        "    }\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_REVERIFY_RESPONSE') {\n"
        "    if (message.tabId == null) {\n"
        "      sendResponse({ ok: false, error: '対象タブを指定してください' });\n"
        "      return false;\n"
        "    }\n"
        "    try {\n"
        "      chrome.tabs.sendMessage(message.tabId, { type: 'AISKEL_REVERIFY_RESPONSE' }, (resp) => {\n"
        "        if (chrome.runtime.lastError) {\n"
        "          sendResponse({\n"
        "            ok: false,\n"
        "            error: '対象タブへ送信できませんでした。ページを再読み込みしてからお試しください (' + chrome.runtime.lastError.message + ')',\n"
        "          });\n"
        "          return;\n"
        "        }\n"
        "        sendResponse(resp && typeof resp === 'object' ? resp : { ok: false, error: '応答を取得できませんでした' });\n"
        "      });\n"
        "    } catch (err) {\n"
        "      sendResponse({ ok: false, error: String(err) });\n"
        "    }\n"
        "    return true;\n"
        "  }\n"
        + build_background_binding_handlers_js()
        + build_background_handoff_handlers_js()
        + "  return false;\n"
        + "});\n"
    )
