"""Module: @role: 拡張機能Background Service Workerのコマンド実行・プロンプト取得・タブ転送メッセージハンドラJSスニペットを生成する。"""

def build_background_command_handlers_js() -> str:
    """コマンド実行・状態取得・プロンプト取得・設定変更・タブ操作中継のメッセージハンドラJSを返す。"""
    return (
        "  if (message.type === 'AISKEL_EXECUTE') {\n"
        "    const payload = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) {\n"
        "      payload.tab_id = senderTabId;\n"
        "    } else if (!payload.tab_id) {\n"
        "      payload.tab_id = 'unknown-tab';\n"
        "    }\n"
        "    const cmdLabel = Array.isArray(payload.commands) && payload.commands.length\n"
        "      ? payload.commands.join(' && ')\n"
        "      : (typeof payload.command === 'string' && payload.command.trim() ? payload.command.trim() : 'aiskel execute');\n"
        "    const finishCommand = beginLocalCommand({\n"
        "      command: cmdLabel,\n"
        "      kind: 'execute',\n"
        "      tab_id: payload.tab_id || '',\n"
        "    });\n"
        "    bridgeRequest('/api/execute', 'POST', payload)\n"
        "      .then((res) => {\n"
        "        finishCommand();\n"
        "        sendResponse(res);\n"
        "      })\n"
        "      .catch((err) => {\n"
        "        finishCommand();\n"
        "        sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) });\n"
        "      });\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_TRIGGER_RUN') {\n"
        "    const payload = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) {\n"
        "      payload.tab_id = senderTabId;\n"
        "    }\n"
        "    bridgeRequest('/api/trigger_run', 'POST', payload)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_RUN_COMMAND') {\n"
        "    const payload = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) {\n"
        "      payload.tab_id = senderTabId;\n"
        "    }\n"
        "    const cmdLabel = typeof payload.command === 'string' && payload.command.trim()\n"
        "      ? payload.command.trim()\n"
        "      : 'aiskel command';\n"
        "    const finishCommand = beginLocalCommand({\n"
        "      command: cmdLabel,\n"
        "      kind: 'run_command',\n"
        "      tab_id: payload.tab_id || '',\n"
        "    });\n"
        "    bridgeRequest('/api/run_command', 'POST', payload)\n"
        "      .then((res) => {\n"
        "        finishCommand();\n"
        "        sendResponse(res);\n"
        "      })\n"
        "      .catch((err) => {\n"
        "        finishCommand();\n"
        "        sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) });\n"
        "      });\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_EXECUTION_STATUS') {\n"
        "    const currentTabId = getSenderTabId(sender) || (message.tab_id || '');\n"
        "    bridgeRequest('/api/binding', 'GET')\n"
        "      .then((res) => {\n"
        "        syncBridgeExecutionState(res.reachable, res.connected ? res.data : null);\n"
        "        sendResponse({\n"
        "          reachable: Boolean(res.reachable),\n"
        "          connected: Boolean(res.connected),\n"
        "          status: res.status || 0,\n"
        "          execution: getMergedExecutionState(),\n"
        "          data: res.connected ? enrichBindingData(res.data, currentTabId, true) : {},\n"
        "          error: res.error || '',\n"
        "        });\n"
        "      })\n"
        "      .catch((err) => {\n"
        "        syncBridgeExecutionState(false, null);\n"
        "        sendResponse({\n"
        "          reachable: false,\n"
        "          connected: false,\n"
        "          status: 0,\n"
        "          execution: getMergedExecutionState(),\n"
        "          data: {},\n"
        "          error: String(err),\n"
        "        });\n"
        "      });\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_STATUS') {\n"
        "    const currentTabId = getSenderTabId(sender) || (message.tab_id || '');\n"
        "    const isTabActive = sender && sender.tab ? Boolean(sender.tab.active) : true;\n"
        "    // Content Script新規読込時のみリロード前セッションの抑止フラグを解除\n"
        "    if (message.client_boot && currentTabId) {\n"
        "      suppressedAutoBindTabIds.delete(currentTabId);\n"
        "    }\n"
        "    // 新規タブの/api/bind完了前に古い紐づけ状態を取得して競合上書きするのを防止\n"
        "    const pendingHandoff = currentTabId ? pendingHandoffsByTab.get(currentTabId) : null;\n"
        "    const waitPending = pendingHandoff && pendingHandoff.bindPromise\n"
        "      ? pendingHandoff.bindPromise.catch(() => null)\n"
        "      : Promise.resolve();\n"
        "    waitPending\n"
        "      .then(() => bridgeRequest('/api/binding', 'GET'))\n"
        "      .then((res) => {\n"
        "        if (!res.reachable) {\n"
        "          suppressedAutoBindTabIds.clear();\n"
        "        }\n"
        "        syncBridgeExecutionState(res.reachable, res.connected ? res.data : null);\n"
        "        res.data = enrichBindingData(res.data, currentTabId, res.connected);\n"
        "        if (res.connected) {\n"
        "          res.data.is_tab_active = isTabActive;\n"
        "          res.data.auto_bind_suppressed = Boolean(currentTabId && suppressedAutoBindTabIds.has(currentTabId));\n"
        "        }\n"
        "        sendResponse(res);\n"
        "      })\n"
        "      .catch((err) => {\n"
        "        suppressedAutoBindTabIds.clear();\n"
        "        syncBridgeExecutionState(false, null);\n"
        "        sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) });\n"
        "      });\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_PROMPT') {\n"
        "    const pattern = typeof message.pattern === 'string' && message.pattern.trim() ? message.pattern.trim() : 'default';\n"
        "    bridgeRequest('/api/prompt?pattern=' + encodeURIComponent(pattern), 'GET')\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_SUMMARY_PROMPT') {\n"
        "    const pattern = typeof message.pattern === 'string' && message.pattern.trim() ? message.pattern.trim() : 'default';\n"
        "    const body = { pattern };\n"
        "    if (message.two_stage !== undefined) {\n"
        "      body.two_stage = message.two_stage;\n"
        "    }\n"
        "    bridgeRequest('/api/summary_prompt', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_BLOAT_TARGETS') {\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    const body = senderTabId ? { tab_id: senderTabId } : {};\n"
        "    bridgeRequest('/api/bloat/targets', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_SPLIT_PROMPT') {\n"
        "    const body = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) body.tab_id = senderTabId;\n"
        "    bridgeRequest('/api/split/prompt', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_ORGANIZE_TARGETS') {\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    const body = senderTabId ? { tab_id: senderTabId } : {};\n"
        "    bridgeRequest('/api/organize/targets', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_ORGANIZE_PROMPT') {\n"
        "    const body = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) body.tab_id = senderTabId;\n"
        "    bridgeRequest('/api/organize/prompt', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_GET_CONFIG_PROMPT') {\n"
        "    const body = Object.assign({}, message.payload || {});\n"
        "    const senderTabId = getSenderTabId(sender);\n"
        "    if (senderTabId) body.tab_id = senderTabId;\n"
        "    bridgeRequest('/api/config/prompt', 'POST', body)\n"
        "      .then((res) => sendResponse(res))\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_SET_HANDOFF_MAX_TABS') {\n"
        "    const currentTabId = message.tabId != null ? formatTabId(message.tabId) : (getSenderTabId(sender) || '');\n"
        "    const body = { patch_handoff_max_tabs: message.patch_handoff_max_tabs };\n"
        "    if (currentTabId) {\n"
        "      body.tab_id = currentTabId;\n"
        "    }\n"
        "    bridgeRequest('/api/handoff/max_tabs', 'POST', body)\n"
        "      .then((res) => {\n"
        "        syncBridgeExecutionState(res.reachable, res.connected ? res.data : null);\n"
        "        const rawData = res.data;\n"
        "        if (res.connected && rawData) {\n"
        "          broadcastBindingUpdated(rawData);\n"
        "        }\n"
        "        res.data = enrichBindingData(rawData, currentTabId, res.connected);\n"
        "        sendResponse(res);\n"
        "      })\n"
        "      .catch((err) => sendResponse({ reachable: false, connected: false, status: 0, data: {}, error: String(err) }));\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_INSERT_SUMMARY_PROMPT') {\n"
        "    if (message.tabId == null) {\n"
        "      sendResponse({ ok: false, error: '対象タブを指定してください' });\n"
        "      return false;\n"
        "    }\n"
        "    try {\n"
        "      chrome.tabs.sendMessage(message.tabId, { type: 'AISKEL_INSERT_SUMMARY_PROMPT' }, (resp) => {\n"
        "        if (chrome.runtime.lastError) {\n"
        "          sendResponse({\n"
        "            ok: false,\n"
        "            error: '対象タブへ送信できませんでした。ページを再読み込みしてからお試しください (' + chrome.runtime.lastError.message + ')',\n"
        "          });\n"
        "          return;\n"
        "        }\n"
        "        sendResponse(resp && typeof resp === 'object' ? resp : { ok: true });\n"
        "      });\n"
        "    } catch (err) {\n"
        "      sendResponse({ ok: false, error: String(err) });\n"
        "    }\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_START_CONFIG_INFER') {\n"
        "    if (message.tabId == null) {\n"
        "      sendResponse({ ok: false, error: '対象タブを指定してください' });\n"
        "      return false;\n"
        "    }\n"
        "    try {\n"
        "      chrome.tabs.sendMessage(message.tabId, { type: 'AISKEL_START_CONFIG_INFER' }, (resp) => {\n"
        "        if (chrome.runtime.lastError) {\n"
        "          sendResponse({\n"
        "            ok: false,\n"
        "            error: '対象タブへ送信できませんでした。ページを再読み込みしてからお試しください (' + chrome.runtime.lastError.message + ')',\n"
        "          });\n"
        "          return;\n"
        "        }\n"
        "        sendResponse(resp && typeof resp === 'object' ? resp : { ok: true });\n"
        "      });\n"
        "    } catch (err) {\n"
        "      sendResponse({ ok: false, error: String(err) });\n"
        "    }\n"
        "    return true;\n"
        "  }\n"
        "  if (message.type === 'AISKEL_REVERIFY_RESPONSE') {\n"
        "    if (message.tabId == null) {\n"
        "      sendResponse({ ok: false, error: '対象タブを指定してください' });\n"
        "      return false;\n"
        "    }\n"
        "    try {\n"
        "      chrome.tabs.sendMessage(message.tabId, { type: 'AISKEL_REVERIFY_RESPONSE' }, (resp) => {\n"
        "        if (chrome.runtime.lastError) {\n"
        "          sendResponse({\n"
        "            ok: false,\n"
        "            error: '対象タブへ送信できませんでした。ページを再読み込みしてからお試しください (' + chrome.runtime.lastError.message + ')',\n"
        "          });\n"
        "          return;\n"
        "        }\n"
        "        sendResponse(resp && typeof resp === 'object' ? resp : { ok: false, error: '応答を取得できませんでした' });\n"
        "      });\n"
        "    } catch (err) {\n"
        "      sendResponse({ ok: false, error: String(err) });\n"
        "    }\n"
        "    return true;\n"
        "  }\n"
    )
