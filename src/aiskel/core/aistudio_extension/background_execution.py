"""Module: @role: 拡張機能Background Service Workerの実行状態追跡・マージ・バッジ表示・タイマー制御JSスニペットを生成する。"""

def build_background_execution_js() -> str:
    """ローカル/ブリッジ実行状態の正規化・統合・ツールバーバッジ更新・通知制御のJSコード群を返す。"""
    return (
        "function parseTimestampMs(value) {\n"
        "  if (typeof value === 'number' && Number.isFinite(value) && value > 0) {\n"
        "    return value < 1e12 ? Math.round(value * 1000) : Math.round(value);\n"
        "  }\n"
        "  if (typeof value === 'string' && value.trim()) {\n"
        "    const trimmed = value.trim();\n"
        "    if (/^\\d+(\\.\\d+)?$/.test(trimmed)) {\n"
        "      const num = Number(trimmed);\n"
        "      if (Number.isFinite(num) && num > 0) {\n"
        "        return num < 1e12 ? Math.round(num * 1000) : Math.round(num);\n"
        "      }\n"
        "    }\n"
        "    const parsed = Date.parse(trimmed);\n"
        "    if (Number.isFinite(parsed) && parsed > 0) {\n"
        "      return parsed;\n"
        "    }\n"
        "  }\n"
        "  return 0;\n"
        "}\n\n"
        "function normalizeExecutionItem(raw, fallbackData) {\n"
        "  const now = Date.now();\n"
        "  const obj = raw && typeof raw === 'object' ? raw : {};\n"
        "  const fb = fallbackData && typeof fallbackData === 'object' ? fallbackData : {};\n"
        "  const command = String(\n"
        "    obj.command || obj.cmd || obj.label || obj.name ||\n"
        "    (typeof raw === 'string' ? raw : '') ||\n"
        "    fb.running_command || fb.executing_command || fb.current_command || fb.command || ''\n"
        "  ).trim();\n"
        "  const kind = String(obj.kind || obj.type || fb.running_command_kind || fb.command_kind || fb.execution_kind || 'bridge').trim();\n"
        "  const tabId = String(obj.tab_id || fb.running_tab_id || fb.tab_id || '').trim();\n"
        "  let elapsedMs = 0;\n"
        "  if (typeof obj.elapsed_ms === 'number' && Number.isFinite(obj.elapsed_ms)) {\n"
        "    elapsedMs = Math.max(0, Math.round(obj.elapsed_ms));\n"
        "  } else if (typeof obj.elapsed_sec === 'number' && Number.isFinite(obj.elapsed_sec)) {\n"
        "    elapsedMs = Math.max(0, Math.round(obj.elapsed_sec * 1000));\n"
        "  } else if (typeof obj.elapsed_seconds === 'number' && Number.isFinite(obj.elapsed_seconds)) {\n"
        "    elapsedMs = Math.max(0, Math.round(obj.elapsed_seconds * 1000));\n"
        "  } else if (typeof fb.command_elapsed_ms === 'number' && Number.isFinite(fb.command_elapsed_ms)) {\n"
        "    elapsedMs = Math.max(0, Math.round(fb.command_elapsed_ms));\n"
        "  } else if (typeof fb.command_elapsed_sec === 'number' && Number.isFinite(fb.command_elapsed_sec)) {\n"
        "    elapsedMs = Math.max(0, Math.round(fb.command_elapsed_sec * 1000));\n"
        "  } else if (typeof fb.elapsed_sec === 'number' && Number.isFinite(fb.elapsed_sec)) {\n"
        "    elapsedMs = Math.max(0, Math.round(fb.elapsed_sec * 1000));\n"
        "  }\n"
        "  let startedAt = parseTimestampMs(\n"
        "    obj.started_at_ms || fb.started_at_ms ||\n"
        "    obj.started_at || obj.start_time || fb.command_started_at || fb.execution_started_at || fb.started_at\n"
        "  );\n"
        "  if ((!startedAt || (!obj.started_at_ms && !fb.started_at_ms && elapsedMs > 0)) && elapsedMs > 0) {\n"
        "    startedAt = Math.max(1, now - elapsedMs);\n"
        "  }\n"
        "  if (startedAt && elapsedMs === 0) {\n"
        "    elapsedMs = Math.max(0, now - startedAt);\n"
        "  }\n"
        "  return {\n"
        "    command: command || 'aiskel コマンド',\n"
        "    kind: kind || 'bridge',\n"
        "    tab_id: tabId,\n"
        "    started_at: startedAt || now,\n"
        "    elapsed_ms: elapsedMs,\n"
        "    source: 'bridge',\n"
        "  };\n"
        "}\n\n"
        "function extractBridgeExecutionState(data) {\n"
        "  if (!data || typeof data !== 'object') {\n"
        "    return { running: false, commands: [] };\n"
        "  }\n"
        "  const listCandidates = [data.running_commands, data.active_commands, data.executions];\n"
        "  for (const list of listCandidates) {\n"
        "    if (Array.isArray(list) && list.length > 0) {\n"
        "      const items = list\n"
        "        .filter((item) => item && (typeof item !== 'object' || (item.running !== false && item.active !== false && item.is_running !== false)))\n"
        "        .map((item) => normalizeExecutionItem(item, data));\n"
        "      if (items.length > 0) {\n"
        "        return { running: true, commands: items };\n"
        "      }\n"
        "    }\n"
        "  }\n"
        "  const objCandidates = [\n"
        "    data.execution,\n"
        "    data.command_execution,\n"
        "    data.active_execution,\n"
        "    data.running_command,\n"
        "    data.active_command,\n"
        "    data.current_command,\n"
        "  ];\n"
        "  for (const cand of objCandidates) {\n"
        "    if (!cand) continue;\n"
        "    if (typeof cand === 'object') {\n"
        "      const explicitStopped = cand.running === false || cand.active === false || cand.is_running === false || cand.is_executing === false;\n"
        "      if (explicitStopped) continue;\n"
        "      if (Array.isArray(cand.commands) && cand.commands.length > 0) {\n"
        "        const subItems = cand.commands\n"
        "          .filter((item) => item && (typeof item !== 'object' || (item.running !== false && item.active !== false && item.is_running !== false)))\n"
        "          .map((item) => normalizeExecutionItem(item, cand));\n"
        "        if (subItems.length > 0) {\n"
        "          return { running: true, commands: subItems };\n"
        "        }\n"
        "      }\n"
        "      const explicitRunning = cand.running === true || cand.active === true || cand.is_running === true || cand.is_executing === true;\n"
        "      const hasCommand = Boolean(String(cand.command || cand.cmd || cand.label || '').trim());\n"
        "      if (explicitRunning || hasCommand) {\n"
        "        return { running: true, commands: [normalizeExecutionItem(cand, data)] };\n"
        "      }\n"
        "    } else if (typeof cand === 'string' && cand.trim()) {\n"
        "      return { running: true, commands: [normalizeExecutionItem(cand, data)] };\n"
        "    }\n"
        "  }\n"
        "  const flatRunning = Boolean(\n"
        "    data.is_executing || data.executing || data.is_command_running || data.command_running || data.is_running || data.busy\n"
        "  );\n"
        "  if (flatRunning) {\n"
        "    return { running: true, commands: [normalizeExecutionItem(null, data)] };\n"
        "  }\n"
        "  return { running: false, commands: [] };\n"
        "}\n\n"
        "function isCompatibleCommandKind(localKind, bridgeKind) {\n"
        "  const lk = String(localKind || '');\n"
        "  const bk = String(bridgeKind || '');\n"
        "  if (!bk || bk === 'bridge') return true;\n"
        "  if (lk === bk) return true;\n"
        "  if (lk.indexOf('_handoff') !== -1 && (bk === 'auto_check' || bk === 'auto_apply')) return true;\n"
        "  return false;\n"
        "}\n\n"
        "function getMergedExecutionState() {\n"
        "  const now = Date.now();\n"
        "  const localItems = Array.from(activeLocalCommands.values()).map((item) => ({\n"
        "    command: item.command,\n"
        "    kind: item.kind,\n"
        "    tab_id: item.tab_id,\n"
        "    started_at: item.started_at,\n"
        "    elapsed_ms: Math.max(0, now - item.started_at),\n"
        "    source: 'extension',\n"
        "  }));\n"
        "  const bridgeItems = (bridgeExecutionState && bridgeExecutionState.running && Array.isArray(bridgeExecutionState.commands))\n"
        "    ? bridgeExecutionState.commands.map((item) => ({\n"
        "      command: item.command,\n"
        "      kind: item.kind,\n"
        "      tab_id: item.tab_id,\n"
        "      started_at: item.started_at || now,\n"
        "      elapsed_ms: item.started_at ? Math.max(0, now - item.started_at) : (item.elapsed_ms || 0),\n"
        "      source: 'bridge',\n"
        "    }))\n"
        "    : [];\n\n"
        "  let combined = [];\n"
        "  let source = 'idle';\n"
        "  if (localItems.length > 0 && bridgeItems.length > 0) {\n"
        "    const usedBridge = new Set();\n"
        "    let matchedAny = false;\n"
        "    combined = localItems.map((loc) => {\n"
        "      let matchIdx = -1;\n"
        "      for (let i = 0; i < bridgeItems.length; i += 1) {\n"
        "        if (usedBridge.has(i)) continue;\n"
        "        const br = bridgeItems[i];\n"
        "        if (!isCompatibleCommandKind(loc.kind, br.kind)) continue;\n"
        "        if (loc.tab_id && br.tab_id && loc.tab_id !== br.tab_id) continue;\n"
        "        matchIdx = i;\n"
        "        break;\n"
        "      }\n"
        "      if (matchIdx === -1) {\n"
        "        return loc;\n"
        "      }\n"
        "      usedBridge.add(matchIdx);\n"
        "      matchedAny = true;\n"
        "      const br = bridgeItems[matchIdx];\n"
        "      const preferBridgeCmd = Boolean(\n"
        "        br.command && br.command !== 'aiskel コマンド' &&\n"
        "        (loc.command === 'aiskel execute' || loc.command.indexOf('(パッチ適用)') !== -1)\n"
        "      );\n"
        "      const startedAt = (br.started_at && br.started_at < loc.started_at) ? br.started_at : loc.started_at;\n"
        "      return {\n"
        "        command: preferBridgeCmd ? br.command : loc.command,\n"
        "        kind: loc.kind || br.kind || 'command',\n"
        "        tab_id: loc.tab_id || br.tab_id || '',\n"
        "        started_at: startedAt,\n"
        "        elapsed_ms: Math.max(0, now - startedAt),\n"
        "        source: 'both',\n"
        "      };\n"
        "    });\n"
        "    for (let i = 0; i < bridgeItems.length; i += 1) {\n"
        "      if (!usedBridge.has(i)) {\n"
        "        combined.push(bridgeItems[i]);\n"
        "      }\n"
        "    }\n"
        "    source = matchedAny ? 'both' : 'extension';\n"
        "  } else if (localItems.length > 0) {\n"
        "    combined = localItems;\n"
        "    source = 'extension';\n"
        "  } else if (bridgeItems.length > 0) {\n"
        "    combined = bridgeItems;\n"
        "    source = 'bridge';\n"
        "  }\n\n"
        "  if (combined.length === 0) {\n"
        "    return {\n"
        "      running: false,\n"
        "      command: '',\n"
        "      kind: '',\n"
        "      tab_id: '',\n"
        "      started_at: 0,\n"
        "      elapsed_ms: 0,\n"
        "      count: 0,\n"
        "      commands: [],\n"
        "      source: 'idle',\n"
        "    };\n"
        "  }\n"
        "  const primary = combined[0];\n"
        "  return {\n"
        "    running: true,\n"
        "    command: combined.length > 1 ? (primary.command + ' (+' + (combined.length - 1) + '件)') : primary.command,\n"
        "    kind: primary.kind,\n"
        "    tab_id: primary.tab_id,\n"
        "    started_at: primary.started_at,\n"
        "    elapsed_ms: primary.elapsed_ms,\n"
        "    count: combined.length,\n"
        "    commands: combined,\n"
        "    source,\n"
        "  };\n"
        "}\n\n"
        "function formatActionElapsed(ms) {\n"
        "  const sec = Math.max(0, Math.floor(ms / 1000));\n"
        "  if (sec < 60) return sec + 's';\n"
        "  const min = Math.floor(sec / 60);\n"
        "  const rem = sec % 60;\n"
        "  return min + 'm' + String(rem).padStart(2, '0') + 's';\n"
        "}\n\n"
        "function updateExecutionBadge(execution) {\n"
        "  const state = execution || getMergedExecutionState();\n"
        "  try {\n"
        "    if (!chrome.action) return;\n"
        "    if (state.running) {\n"
        "      const badgeText = state.count > 1 ? ('R' + Math.min(99, state.count)) : 'RUN';\n"
        "      chrome.action.setBadgeText({ text: badgeText }, () => { void chrome.runtime.lastError; });\n"
        "      chrome.action.setBadgeBackgroundColor({ color: '#d97706' }, () => { void chrome.runtime.lastError; });\n"
        "      if (typeof chrome.action.setBadgeTextColor === 'function') {\n"
        "        chrome.action.setBadgeTextColor({ color: '#ffffff' }, () => { void chrome.runtime.lastError; });\n"
        "      }\n"
        "      const elapsedText = formatActionElapsed(state.elapsed_ms || 0);\n"
        "      chrome.action.setTitle({\n"
        "        title: BASE_ACTION_TITLE + ' - 実行中 (' + elapsedText + '): ' + (state.command || 'aiskel'),\n"
        "      }, () => { void chrome.runtime.lastError; });\n"
        "    } else {\n"
        "      chrome.action.setBadgeText({ text: '' }, () => { void chrome.runtime.lastError; });\n"
        "      chrome.action.setTitle({ title: BASE_ACTION_TITLE }, () => { void chrome.runtime.lastError; });\n"
        "    }\n"
        "  } catch (_e) {}\n"
        "}\n\n"
        "function broadcastExecutionUpdated(execution) {\n"
        "  const state = execution || getMergedExecutionState();\n"
        "  try {\n"
        "    chrome.runtime.sendMessage(\n"
        "      { type: 'AISKEL_EXECUTION_UPDATED', execution: state },\n"
        "      () => { void chrome.runtime.lastError; }\n"
        "    );\n"
        "  } catch (_e) {}\n"
        "  try {\n"
        "    chrome.tabs.query({ url: AISTUDIO_TAB_PATTERNS }, (tabs) => {\n"
        "      if (chrome.runtime.lastError || !Array.isArray(tabs)) return;\n"
        "      for (const tab of tabs) {\n"
        "        if (tab.id == null) continue;\n"
        "        try {\n"
        "          chrome.tabs.sendMessage(\n"
        "            tab.id,\n"
        "            { type: 'AISKEL_EXECUTION_UPDATED', execution: state, tab_id: formatTabId(tab.id) },\n"
        "            () => { void chrome.runtime.lastError; }\n"
        "          );\n"
        "        } catch (_e) {}\n"
        "      }\n"
        "    });\n"
        "  } catch (_e) {}\n"
        "}\n\n"
        "function ensureExecutionTickTimer(isRunning) {\n"
        "  if (isRunning && executionTickTimer === null) {\n"
        "    executionTickTimer = setInterval(() => {\n"
        "      const current = getMergedExecutionState();\n"
        "      if (!current.running) {\n"
        "        clearInterval(executionTickTimer);\n"
        "        executionTickTimer = null;\n"
        "        updateExecutionBadge(current);\n"
        "        return;\n"
        "      }\n"
        "      updateExecutionBadge(current);\n"
        "    }, 1000);\n"
        "  } else if (!isRunning && executionTickTimer !== null) {\n"
        "    clearInterval(executionTickTimer);\n"
        "    executionTickTimer = null;\n"
        "  }\n"
        "}\n\n"
        "function refreshExecutionIndicators(forceBroadcast) {\n"
        "  const state = getMergedExecutionState();\n"
        "  updateExecutionBadge(state);\n"
        "  ensureExecutionTickTimer(state.running);\n"
        "  const changed = state.running !== lastBroadcastRunning || state.command !== lastBroadcastCommand;\n"
        "  if (forceBroadcast || changed) {\n"
        "    lastBroadcastRunning = state.running;\n"
        "    lastBroadcastCommand = state.command;\n"
        "    broadcastExecutionUpdated(state);\n"
        "  }\n"
        "}\n\n"
        "function syncBridgeExecutionState(reachable, data) {\n"
        "  if (!reachable || !data) {\n"
        "    bridgeExecutionState = { running: false, commands: [] };\n"
        "  } else {\n"
        "    bridgeExecutionState = extractBridgeExecutionState(data);\n"
        "  }\n"
        "  refreshExecutionIndicators(false);\n"
        "}\n\n"
        "function beginLocalCommand(meta) {\n"
        "  const id = 'local-' + String(nextLocalCommandSeq++);\n"
        "  const rawCmd = String((meta && meta.command) || 'aiskel').trim();\n"
        "  const boundedCmd = rawCmd.length > 240 ? (rawCmd.slice(0, 237) + '...') : rawCmd;\n"
        "  activeLocalCommands.set(id, {\n"
        "    id,\n"
        "    command: boundedCmd || 'aiskel',\n"
        "    kind: String((meta && meta.kind) || 'command'),\n"
        "    tab_id: String((meta && meta.tab_id) || ''),\n"
        "    started_at: Date.now(),\n"
        "  });\n"
        "  refreshExecutionIndicators(true);\n"
        "  return () => endLocalCommand(id);\n"
        "}\n\n"
        "function endLocalCommand(id) {\n"
        "  if (!activeLocalCommands.has(id)) return;\n"
        "  activeLocalCommands.delete(id);\n"
        "  const hadBridgeRunning = Boolean(bridgeExecutionState && bridgeExecutionState.running);\n"
        "  if (activeLocalCommands.size === 0 && hadBridgeRunning) {\n"
        "    // ローカル実行完了直後の古いブリッジ状態残存を防ぐため即座にクリアし再同期する\n"
        "    bridgeExecutionState = { running: false, commands: [] };\n"
        "    refreshExecutionIndicators(true);\n"
        "    bridgeRequest('/api/binding', 'GET')\n"
        "      .then((res) => syncBridgeExecutionState(res.reachable, res.connected ? res.data : null))\n"
        "      .catch(() => {});\n"
        "    return;\n"
        "  }\n"
        "  refreshExecutionIndicators(true);\n"
        "}\n\n"
    )
