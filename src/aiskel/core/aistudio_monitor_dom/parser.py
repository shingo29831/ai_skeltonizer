        "            break;\n"
        "          }\n"
        "        }\n"
        "        if (endIdx !== -1) {\n"
        "          for (let k = i; k <= endIdx; k += 1) excluded.add(k);\n"
        "          i = endIdx + 1;\n"
        "          continue;\n"
        "        }\n"
        "      }\n"
        "      i += 1;\n"
        "    }\n"
        "    return excluded;\n"
        "  }\n\n"
        "  function scanCommandTokens(line) {\n"
        "    const tokens = [];\n"
        "    let buf = '';\n"
        "    let tokenStarted = false;\n"
        "    let inQuote = null;\n"
        "    for (let i = 0; i < line.length; i += 1) {\n"
        "      const ch = line[i];\n"
        "      if (inQuote !== null) {\n"
        "        if (ch === inQuote) {\n"
        "          inQuote = null;\n"
        "        } else {\n"
        "          buf += ch;\n"
        "        }\n"
        "        continue;\n"
        "      }\n"
        "      if (ch === '\\'' || ch === '\"') {\n"
        "        inQuote = ch;\n"
        "        tokenStarted = true;\n"
        "        continue;\n"
        "      }\n"
        "      if (/\\s/.test(ch)) {\n"
        "        if (tokenStarted) {\n"
        "          tokens.push(buf);\n"
        "          buf = '';\n"
        "          tokenStarted = false;\n"
        "        }\n"
        "        continue;\n"
        "      }\n"
        "      if (ch === '#' && !tokenStarted) {\n"
        "        break;\n"
        "      }\n"
        "      buf += ch;\n"
        "      tokenStarted = true;\n"
        "    }\n"
        "    if (tokenStarted) {\n"
        "      tokens.push(buf);\n"
        "    }\n"
        "    return tokens;\n"
        "  }\n\n"
        "  function hasCopyTargetArgument(line) {\n"
        "    if (!COMMAND_PREFIX_RE.test(line)) return false;\n"
        "    const tokens = scanCommandTokens(line);\n"
        "    if (tokens.length < 3) return false;\n"
        "    let i = 2;\n"
        "    while (i < tokens.length) {\n"
        "      const tok = tokens[i];\n"
        "      if (!tok) {\n"
        "        i += 1;\n"
