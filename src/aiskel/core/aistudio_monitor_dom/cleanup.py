        "    for (const t of list) {\n"
        "      if (t && t.nodeType === 1 && !uniqueTurns.includes(t)) uniqueTurns.push(t);\n"
        "    }\n"
        "    activeBatchDeleteInFlight = true;\n"
        "    const results = [];\n"
