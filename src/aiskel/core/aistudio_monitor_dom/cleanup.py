        "            abortReason = res.reason;\n"
        "            break;\n"
        "          }\n"
        "          if (stopOnError) break;\n"
        "        } else {\n"
        "          skippedCount += 1;\n"
        "        }\n"
        "        if (i + 1 < uniqueTurns.length && interTurnDelayMs > 0) {\n"
        "          await sleepCleanupMs(interTurnDelayMs);\n"
        "        }\n"
        "      }\n"
        "      return {\n"
        "        ok: failedCount === 0 && !abortReason,\n"
        "        reason: abortReason || undefined,\n"
        "        deletedCount,\n"
        "        failedCount,\n"
        "        skippedCount,\n"
        "        results,\n"
        "      };\n"
        "    } finally {\n"
        "      activeBatchDeleteInFlight = false;\n"
        "    }\n"
