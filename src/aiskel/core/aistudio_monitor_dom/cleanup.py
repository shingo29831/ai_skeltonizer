        "  async function closeOpenCdkMenus(timeoutMs) {\n"
        "    const limit = typeof timeoutMs === 'number' ? timeoutMs : 800;\n"
        "    const deadline = Date.now() + limit;\n"
        "    let lastAttemptAt = 0;\n"
        "    while (Date.now() < deadline) {\n"
        "      if (hasOpenCdkDialog()) return false;\n"
        "      const panels = getOpenCdkMenuPanels();\n"
        "      if (!panels.length) return true;\n"
        "      if (Date.now() - lastAttemptAt >= 160) {\n"
        "        lastAttemptAt = Date.now();\n"
        "        const escTargets = [document.activeElement || document, ...panels];\n"
        "        for (const target of escTargets) {\n"
        "          try {\n"
        "            target.dispatchEvent(\n"
        "              new KeyboardEvent('keydown', { key: 'Escape', code: 'Escape', keyCode: 27, bubbles: true, cancelable: true })\n"
        "            );\n"
        "          } catch (_e) {}\n"
        "        }\n"
        "        const backdrops = Array.from(document.querySelectorAll('.cdk-overlay-container .cdk-overlay-backdrop'));\n"
        "        const topBackdrop = backdrops.reverse().find((b) => {\n"
        "          const st = window.getComputedStyle(b);\n"
