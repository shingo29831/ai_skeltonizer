        "        try {\n"
        "          target.dispatchEvent(new MouseEvent(type, { bubbles: true, cancelable: true, view: window }));\n"
        "        } catch (_e) {}\n"
        "      }\n"
        "      for (const type of ['pointerenter', 'mouseenter']) {\n"
        "        try {\n"
