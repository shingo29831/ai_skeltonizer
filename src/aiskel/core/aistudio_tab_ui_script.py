"""Module: @role: 開いたAI Studioタブ上に表示するVSCode紐づけ制御UIのクライアントJavaScriptコードを生成する。"""
from .aistudio_error_notice_script import build_error_notice_ui_js
from .aistudio_tab_binding_dom_script import build_tab_binding_ui_dom_js
from .aistudio_tab_binding_state_script import build_tab_binding_ui_render_js



def build_tab_binding_ui_js() -> str:
    """Trusted Types安全かつShadow DOM隔離されたページ内VSCode紐づけUIのスクリプトを返す。"""
    return build_tab_binding_ui_dom_js() + build_tab_binding_ui_render_js()
def build_error_notice_ui_js() -> str:
    """エラー詳細の表示とワンクリックコピーを提供するShadow DOM隔離パネルのスクリプトを返す。"""
    return (
        "  let activeErrorHost = null;\n"
        "  function copyTextToClipboard(text) {\n"
        "    const value = String(text || '');\n"
        "    if (navigator.clipboard && typeof navigator.clipboard.writeText === 'function') {\n"
        "      return navigator.clipboard.writeText(value).then(() => true).catch(() => fallbackCopyText(value));\n"
        "    }\n"
        "    return Promise.resolve(fallbackCopyText(value));\n"
        "  }\n\n"
        "  function fallbackCopyText(text) {\n"
        "    try {\n"
        "      const ta = document.createElement('textarea');\n"
        "      ta.value = text;\n"
        "      ta.setAttribute('readonly', 'true');\n"
        "      ta.style.position = 'fixed';\n"
        "      ta.style.left = '-9999px';\n"
        "      ta.style.top = '0';\n"
        "      (document.body || document.documentElement).appendChild(ta);\n"
        "      ta.select();\n"
        "      const ok = Boolean(document.execCommand && document.execCommand('copy'));\n"
        "      ta.remove();\n"
        "      return ok;\n"
        "    } catch (_e) {\n"
        "      return false;\n"
        "    }\n"
        "  }\n\n"
        "  function clearErrorPanel() {\n"
        "    if (activeErrorHost && activeErrorHost.parentElement) {\n"
        "      activeErrorHost.remove();\n"
        "    }\n"
        "    activeErrorHost = null;\n"
        "  }\n\n"
        "  function showErrorPanel(title, detail, copyText) {\n"
        "    const parent = document.body || document.documentElement;\n"
        "    if (!parent) return;\n"
        "    clearErrorPanel();\n"
        "    const host = document.createElement('div');\n"
        "    host.setAttribute('data-aiskel-ui', 'true');\n"
        "    const bottomOffset = hasBindingTransport ? '84px' : '20px';\n"
        "    const shadow = host.attachShadow({ mode: 'open' });\n"
        "    applyShadowCss(shadow, [\n"
        "      ':host{all:initial !important;position:fixed !important;top:auto !important;left:auto !important;right:16px !important;bottom:' + bottomOffset + ' !important;z-index:2147483647 !important;display:block !important;visibility:visible !important;opacity:1 !important;width:auto !important;height:auto !important;margin:0 !important;padding:0 !important;border:0 !important;background:transparent !important;transform:none !important;pointer-events:auto !important;font-family:system-ui,-apple-system,sans-serif !important;}',\n"
        "      '.err-card{width:min(420px,calc(100vw - 32px));border-radius:10px;background:rgba(30,15,20,0.96);color:#fef2f2;border:1px solid rgba(248,113,113,0.55);box-shadow:0 10px 28px rgba(0,0,0,0.45);overflow:hidden;backdrop-filter:blur(8px);}',\n"
        "      '.err-head{display:flex;align-items:center;justify-content:space-between;gap:8px;padding:8px 10px;background:rgba(185,28,28,0.85);font-size:12px;font-weight:700;}',\n"
        "      '.err-title{flex:1;min-width:0;overflow:hidden;text-overflow:ellipsis;white-space:nowrap;}',\n"
        "      '.err-actions{display:flex;align-items:center;gap:6px;flex-shrink:0;}',\n"
        "      '.err-btn{border:none;border-radius:5px;padding:4px 8px;font-size:11px;font-weight:600;cursor:pointer;background:rgba(255,255,255,0.18);color:#fff;}',\n"
        "      '.err-btn:hover{background:rgba(255,255,255,0.28);}',\n"
        "      '.err-btn-copy{background:#f8fafc;color:#7f1d1d;}',\n"
        "      '.err-btn-copy:hover{background:#e2e8f0;}',\n"
        "      '.err-body{padding:10px 12px;font-size:12px;line-height:1.45;max-height:180px;overflow-y:auto;white-space:pre-wrap;word-break:break-word;user-select:text;-webkit-user-select:text;color:#fee2e2;}',\n"
        "    ].join(''));\n"
        "    const card = document.createElement('div');\n"
        "    card.className = 'err-card';\n"
        "    const head = document.createElement('div');\n"
        "    head.className = 'err-head';\n"
        "    const titleEl = document.createElement('span');\n"
        "    titleEl.className = 'err-title';\n"
        "    titleEl.textContent = String(title || 'aiskel エラー');\n"
        "    const actions = document.createElement('div');\n"
        "    actions.className = 'err-actions';\n"
        "    const copyBtn = document.createElement('button');\n"
        "    copyBtn.type = 'button';\n"
        "    copyBtn.className = 'err-btn err-btn-copy';\n"
        "    copyBtn.textContent = 'コピー';\n"
        "    const closeBtn = document.createElement('button');\n"
        "    closeBtn.type = 'button';\n"
        "    closeBtn.className = 'err-btn';\n"
        "    closeBtn.title = '閉じる';\n"
        "    closeBtn.textContent = '×';\n"
        "    actions.appendChild(copyBtn);\n"
        "    actions.appendChild(closeBtn);\n"
        "    head.appendChild(titleEl);\n"
        "    head.appendChild(actions);\n"
        "    const body = document.createElement('div');\n"
        "    body.className = 'err-body';\n"
        "    const detailStr = String(detail || '');\n"
        "    body.textContent = detailStr;\n"
        "    card.appendChild(head);\n"
        "    card.appendChild(body);\n"
        "    shadow.appendChild(card);\n"
        "    const fullCopy = String(copyText || (String(title || '') + '\\n' + detailStr)).trim();\n"
        "    copyBtn.addEventListener('click', () => {\n"
        "      copyTextToClipboard(fullCopy).then((ok) => {\n"
        "        copyBtn.textContent = ok ? 'コピー完了 ✓' : 'コピー失敗';\n"
        "        window.setTimeout(() => { copyBtn.textContent = 'コピー'; }, 1800);\n"
        "      });\n"
        "    });\n"
        "    closeBtn.addEventListener('click', () => clearErrorPanel());\n"
        "    parent.appendChild(host);\n"
        "    activeErrorHost = host;\n"
        "  }\n\n"
    )


