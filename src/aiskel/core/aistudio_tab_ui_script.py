"""Module: @role: 開いたAI Studioタブ上に表示するVSCode紐づけ制御UIのクライアントJavaScriptコードを生成する。"""


def build_tab_binding_ui_js() -> str:
    """Trusted Types安全かつShadow DOM隔離されたページ内VSCode紐づけUIのスクリプトを返す。"""
    return (
        "  function createBindingUiController(actions) {\n"
        "    const MINIMIZED_KEY = 'aiskel_tab_ui_minimized';\n"
        "    let minimized = false;\n"
        "    try {\n"
        "      minimized = window.sessionStorage.getItem(MINIMIZED_KEY) === '1';\n"
        "    } catch (_e) {}\n"
        "    let actionPending = false;\n"
        "    let currentState = null;\n\n"
        "    const host = document.createElement('div');\n"
        "    host.setAttribute('data-aiskel-ui', 'true');\n"
        "    host.style.cssText = 'position:fixed;right:16px;bottom:16px;z-index:2147483647;font-family:system-ui,-apple-system,sans-serif;';\n"
        "    const shadow = host.attachShadow({ mode: 'open' });\n\n"
        "    const styleEl = document.createElement('style');\n"
        "    styleEl.textContent = [\n"
        "      '.panel{display:flex;align-items:center;gap:10px;padding:8px 12px;border-radius:10px;background:rgba(15,23,42,0.94);color:#f8fafc;border:1px solid rgba(148,163,184,0.35);box-shadow:0 8px 24px rgba(0,0,0,0.35);max-width:360px;backdrop-filter:blur(8px);}',\n"
        "      '.pill{display:none;align-items:center;gap:6px;padding:6px 10px;border-radius:999px;background:rgba(15,23,42,0.92);color:#f8fafc;border:1px solid rgba(148,163,184,0.35);box-shadow:0 4px 14px rgba(0,0,0,0.3);font-size:12px;font-weight:600;cursor:pointer;}',\n"
        "      '.dot{width:8px;height:8px;border-radius:999px;flex-shrink:0;background:#64748b;}',\n"
        "      '.meta{display:flex;flex-direction:column;min-width:0;flex:1;}',\n"
        "      '.title{font-size:12px;font-weight:600;line-height:1.3;white-space:nowrap;overflow:hidden;text-overflow:ellipsis;}',\n"
        "      '.sub{font-size:11px;color:#cbd5e1;line-height:1.25;white-space:nowrap;overflow:hidden;text-overflow:ellipsis;}',\n"
        "      '.btns{display:flex;align-items:center;gap:6px;flex-shrink:0;}',\n"
        "      '.btn{border:none;border-radius:6px;padding:5px 9px;font-size:11px;font-weight:600;cursor:pointer;white-space:nowrap;transition:opacity 0.15s;}',\n"
        "      '.btn:disabled{opacity:0.55;cursor:wait;}',\n"
        "      '.btn-primary{background:#2563eb;color:#fff;}',\n"
        "      '.btn-primary:hover:not(:disabled){background:#1d4ed8;}',\n"
        "      '.btn-ghost{background:rgba(148,163,184,0.18);color:#e2e8f0;}',\n"
        "      '.btn-ghost:hover:not(:disabled){background:rgba(148,163,184,0.3);}',\n"
        "      '.btn-min{background:transparent;color:#94a3b8;padding:4px 6px;font-size:13px;line-height:1;}',\n"
        "      '.btn-min:hover{color:#fff;}',\n"
        "    ].join('');\n"
        "    shadow.appendChild(styleEl);\n\n"
        "    const panel = document.createElement('div');\n"
        "    panel.className = 'panel';\n"
        "    const dot = document.createElement('span');\n"
        "    dot.className = 'dot';\n"
        "    const meta = document.createElement('div');\n"
        "    meta.className = 'meta';\n"
        "    const titleEl = document.createElement('div');\n"
        "    titleEl.className = 'title';\n"
        "    const subEl = document.createElement('div');\n"
        "    subEl.className = 'sub';\n"
        "    meta.appendChild(titleEl);\n"
        "    meta.appendChild(subEl);\n\n"
        "    const btns = document.createElement('div');\n"
        "    btns.className = 'btns';\n"
        "    const primaryBtn = document.createElement('button');\n"
        "    primaryBtn.type = 'button';\n"
        "    primaryBtn.className = 'btn btn-primary';\n"
        "    const minBtn = document.createElement('button');\n"
        "    minBtn.type = 'button';\n"
        "    minBtn.className = 'btn btn-min';\n"
        "    minBtn.title = '最小化';\n"
        "    minBtn.textContent = '−';\n"
        "    btns.appendChild(primaryBtn);\n"
        "    btns.appendChild(minBtn);\n"
        "    panel.appendChild(dot);\n"
        "    panel.appendChild(meta);\n"
        "    panel.appendChild(btns);\n\n"
        "    const pill = document.createElement('button');\n"
        "    pill.type = 'button';\n"
        "    pill.className = 'pill';\n"
        "    const pillDot = document.createElement('span');\n"
        "    pillDot.className = 'dot';\n"
        "    const pillLabel = document.createElement('span');\n"
        "    pill.appendChild(pillDot);\n"
        "    pill.appendChild(pillLabel);\n\n"
        "    shadow.appendChild(panel);\n"
        "    shadow.appendChild(pill);\n\n"
        "    function ensureMounted() {\n"
        "      const parent = document.body || document.documentElement;\n"
        "      if (parent && !host.isConnected) {\n"
        "        parent.appendChild(host);\n"
        "      }\n"
        "    }\n\n"
        "    function setMinimized(next) {\n"
        "      minimized = Boolean(next);\n"
        "      try {\n"
        "        window.sessionStorage.setItem(MINIMIZED_KEY, minimized ? '1' : '0');\n"
        "      } catch (_e) {}\n"
        "      panel.style.display = minimized ? 'none' : 'flex';\n"
        "      pill.style.display = minimized ? 'flex' : 'none';\n"
        "    }\n\n"
        "    function render(state) {\n"
        "      ensureMounted();\n"
        "      currentState = state;\n"
        "      const projectLabel = state.projectName || 'VSCode';\n"
        "      let dotColor = '#64748b';\n"
        "      primaryBtn.disabled = actionPending;\n"
        "      if (!state.connected) {\n"
        "        if (state.reachable) {\n"
        "          dotColor = '#ef4444';\n"
        "          titleEl.textContent = 'aiskel 接続エラー (HTTP ' + (state.status || '?') + ')';\n"
        "          subEl.textContent = state.errorMessage || '拡張機能の更新や認証設定を確認してください';\n"
        "          primaryBtn.textContent = '再確認';\n"
        "          primaryBtn.className = 'btn btn-ghost';\n"
        "          pillLabel.textContent = 'aiskel: エラー';\n"
        "        } else {\n"
        "          dotColor = '#64748b';\n"
        "          titleEl.textContent = 'aiskel ブリッジ未接続';\n"
        "          subEl.textContent = 'aiskel s または aiskel listen 待機中';\n"
        "          primaryBtn.textContent = '再確認';\n"
        "          primaryBtn.className = 'btn btn-ghost';\n"
        "          pillLabel.textContent = 'aiskel: 未接続';\n"
        "        }\n"
        "      } else if (state.isCurrentTabBound) {\n"
        "        dotColor = '#22c55e';\n"
        "        titleEl.textContent = 'VSCodeと紐づけ中 (' + projectLabel + ')';\n"
        "        subEl.textContent = 'このタブの aiskel c を監視中';\n"
        "        primaryBtn.textContent = '解除';\n"
        "        primaryBtn.className = 'btn btn-ghost';\n"
        "        pillLabel.textContent = 'VSCode監視中';\n"
        "      } else if (state.bound) {\n"
        "        dotColor = '#f59e0b';\n"
        "        titleEl.textContent = '別タブが紐づけ中 (' + projectLabel + ')';\n"
        "        subEl.textContent = state.boundTabTitle ? '対象: ' + state.boundTabTitle : '他タブを監視中';\n"
        "        primaryBtn.textContent = 'このタブに切替';\n"
        "        primaryBtn.className = 'btn btn-primary';\n"
        "        pillLabel.textContent = 'VSCodeと紐づける';\n"
        "      } else {\n"
        "        dotColor = '#3b82f6';\n"
        "        titleEl.textContent = 'VSCode未紐づけ (' + projectLabel + ')';\n"
        "        subEl.textContent = 'ボタンでこのタブを監視対象にします';\n"
        "        primaryBtn.textContent = 'VSCodeと紐づける';\n"
        "        primaryBtn.className = 'btn btn-primary';\n"
        "        pillLabel.textContent = 'VSCodeと紐づける';\n"
        "      }\n"
        "      dot.style.background = dotColor;\n"
        "      pillDot.style.background = dotColor;\n"
        "      setMinimized(minimized);\n"
        "    }\n\n"
        "    primaryBtn.addEventListener('click', () => {\n"
        "      if (actionPending || !currentState) return;\n"
        "      actionPending = true;\n"
        "      primaryBtn.disabled = true;\n"
        "      const done = () => {\n"
        "        actionPending = false;\n"
        "        if (currentState) render(currentState);\n"
        "      };\n"
        "      if (!currentState.connected) {\n"
        "        actions.onRefresh(done);\n"
        "      } else if (currentState.isCurrentTabBound) {\n"
        "        actions.onUnbind(done);\n"
        "      } else {\n"
        "        actions.onBind(done);\n"
        "      }\n"
        "    });\n"
        "    minBtn.addEventListener('click', () => setMinimized(true));\n"
        "    pill.addEventListener('click', () => setMinimized(false));\n\n"
        "    return { render };\n"
        "  }\n\n"
    )
