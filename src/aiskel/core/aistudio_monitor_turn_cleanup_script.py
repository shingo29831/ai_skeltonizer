        "    pendingCopyResponseSubmit = null;\n"
        "    if (!pendingCopyResponsePaste) return false;\n"
        "    const info = pendingCopyResponsePaste;\n"
        "    const ctxRef = isAutoSubmit ? (autoCtxSnapshot || pendingAutoRunContext || null) : null;\n"
        "    if (isAutoSubmit && ctxRef && !ctxRef.isCopyResponseDispatch) {\n"
        "      pendingCopyResponsePaste = null;\n"
        "      return false;\n"
        "    }\n"
        "    if (\n"
        "      isAutoSubmit &&\n"
        "      ctxRef &&\n"
        "      ctxRef.copyResponsePasteToken &&\n"
