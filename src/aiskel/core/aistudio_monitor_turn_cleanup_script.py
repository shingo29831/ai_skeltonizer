        "      at: Date.now(),\n"
        "      threadKey: curThreadKey,\n"
        "      existingUserTurns: (ctx.userTurns || []).slice(),\n"
        "      sourcePaste: info,\n"
        "    };\n"
        "    return true;\n"
        "  }\n\n"
