        "    if (typeof isProtectedInstructionTurnText === 'function' && isProtectedInstructionTurnText(turnText)) {\n"
        "      pendingCopyResponseSubmit = null;\n"
        "      return false;\n"
        "    }\n"
        "    if (typeof markCopyResponseUserTurn === 'function') {\n"
        "      markCopyResponseUserTurn(latestUserTurn);\n"
        "    }\n"
        "    pendingCopyResponseSubmit = null;\n"
        "    return true;\n"
        "  }\n\n"
        "  function cancelScheduledTurnCleanup() {\n"
        "    if (cleanupScheduledTimer !== null) {\n"
        "      window.clearTimeout(cleanupScheduledTimer);\n"
        "      cleanupScheduledTimer = null;\n"
        "    }\n"
        "  }\n\n"
        "  function isBusyForTurnCleanup(ignoreCleanupSelf) {\n"
        "    return (\n"
        "      !isMonitoringActive() ||\n"
        "      isInferring() ||\n"
        "      wasInferring ||\n"
        "      userCancelledRun ||\n"
        "      settleTimer !== null ||\n"
        "      pendingSubmitCtx !== null ||\n"
        "      pendingCopyResponseSubmit !== null ||\n"
        "      autoRunTimer !== null ||\n"
        "      autoRunVerifyTimer !== null ||\n"
        "      autoRunCleanupInFlight ||\n"
        "      osTriggerRunInFlight ||\n"
