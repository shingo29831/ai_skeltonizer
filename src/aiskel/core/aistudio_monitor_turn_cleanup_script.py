        "    ) {\n"
        "      pendingCopyResponsePaste = null;\n"
        "      return false;\n"
        "    }\n"
        "    const curThreadKey = typeof getCleanupThreadKey === 'function' ? getCleanupThreadKey() : '';\n"
        "    if (info.threadKey && curThreadKey && curThreadKey !== info.threadKey) {\n"
        "      pendingCopyResponsePaste = null;\n"
        "      return false;\n"
        "    }\n"
