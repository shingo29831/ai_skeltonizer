        "        (info.capturedText && snap.text === info.capturedText) ||\n"
        "        (info.hadContentBefore && snap.text === info.inputTextBefore)\n"
        "      ) {\n"
        "        matchesCopyPaste = true;\n"
        "      }\n"
        "    } else if (snap.hasText && !snap.hasChips) {\n"
        "      if (typeof hasAiskelCopyPayloadStructure === 'function' && hasAiskelCopyPayloadStructure(snap.text, null)) {\n"
        "        matchesCopyPaste = true;\n"
        "      } else if (info.capturedText && snap.text === info.capturedText) {\n"
        "        matchesCopyPaste = true;\n"
