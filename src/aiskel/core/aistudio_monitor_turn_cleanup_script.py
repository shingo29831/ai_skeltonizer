        "      pendingCopyResponsePaste = null;\n"
        "      return false;\n"
        "    }\n"
        "    if (typeof isProtectedInstructionTurnText === 'function' && isProtectedInstructionTurnText(snap.text)) {\n"
        "      pendingCopyResponsePaste = null;\n"
        "      return false;\n"
        "    }\n"
        "    let matchesCopyPaste = false;\n"
        "    if (isAutoSubmit && ctxRef && ctxRef.isCopyResponseDispatch) {\n"
