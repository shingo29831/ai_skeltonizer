"""Module: @role: Google AI Studio応答テキストからのaiskel cコマンド抽出・パッチ完結性検証・停止合図検知のJSヘルパー群を生成する。"""
import json

from .aistudio_prompts import PATCH_HANDOFF_STOP_SIGNAL

def build_monitor_dom_parser_js() -> str:
    """コマンド抽出・パッチ構文検出・引き継ぎ停止合図検知を行うJSヘルパー関数群を返す。"""
    stop_signal_literal = json.dumps(PATCH_HANDOFF_STOP_SIGNAL)
    return (
        f"  const HANDOFF_STOP_SIGNAL = {stop_signal_literal};\n"
        "  const HANDOFF_STOP_SIGNAL_LINE_RE = new RegExp(\n"
        "    '^[ \\\\t]*`?' + HANDOFF_STOP_SIGNAL.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&') + '`?[ \\\\t。.]*$'\n"
        "  );\n"
        "  const HANDOFF_FENCE_OPEN_RE = /^[ \\t]*(`{3,}|~{3,})(.*)$/;\n\n"
        "  function findValidPatchLineIndices(lines) {\n"
        "    const excluded = new Set();\n"
        "    let i = 0;\n"
        "    while (i < lines.length) {\n"
        "      if (PATCH_START_RE.test(lines[i])) {\n"
        "        let hasMid = false;\n"
        "        let endIdx = -1;\n"
        "        for (let j = i + 1; j < lines.length; j += 1) {\n"
        "          if (PATCH_START_RE.test(lines[j])) break;\n"
        "          if (PATCH_MID_RE.test(lines[j])) {\n"
        "            hasMid = true;\n"
        "            continue;\n"
        "          }\n"
        "          if (PATCH_END_RE.test(lines[j])) {\n"
        "            if (hasMid) endIdx = j;\n"
        "            break;\n"
        "          }\n"
        "        }\n"
        "        if (endIdx !== -1) {\n"
        "          for (let k = i; k <= endIdx; k += 1) excluded.add(k);\n"
        "          i = endIdx + 1;\n"
        "          continue;\n"
        "        }\n"
        "      }\n"
        "      i += 1;\n"
        "    }\n"
        "    return excluded;\n"
        "  }\n\n"
        "  function scanCommandTokens(line) {\n"
        "    const tokens = [];\n"
        "    let buf = '';\n"
        "    let tokenStarted = false;\n"
        "    let inQuote = null;\n"
        "    for (let i = 0; i < line.length; i += 1) {\n"
        "      const ch = line[i];\n"
        "      if (inQuote !== null) {\n"
        "        if (ch === inQuote) {\n"
        "          inQuote = null;\n"
        "        } else {\n"
        "          buf += ch;\n"
        "        }\n"
        "        continue;\n"
        "      }\n"
        "      if (ch === '\\'' || ch === '\"') {\n"
        "        inQuote = ch;\n"
        "        tokenStarted = true;\n"
        "        continue;\n"
        "      }\n"
        "      if (/\\s/.test(ch)) {\n"
        "        if (tokenStarted) {\n"
        "          tokens.push(buf);\n"
        "          buf = '';\n"
        "          tokenStarted = false;\n"
        "        }\n"
        "        continue;\n"
        "      }\n"
        "      if (ch === '#' && !tokenStarted) {\n"
        "        break;\n"
        "      }\n"
        "      buf += ch;\n"
        "      tokenStarted = true;\n"
        "    }\n"
        "    if (tokenStarted) {\n"
        "      tokens.push(buf);\n"
        "    }\n"
        "    return tokens;\n"
        "  }\n\n"
        "  function hasCopyTargetArgument(line) {\n"
        "    if (!COMMAND_PREFIX_RE.test(line)) return false;\n"
        "    const tokens = scanCommandTokens(line);\n"
        "    if (tokens.length < 3) return false;\n"
        "    let i = 2;\n"
        "    while (i < tokens.length) {\n"
        "      const tok = tokens[i];\n"
        "      if (!tok) {\n"
        "        i += 1;\n"
        "        continue;\n"
        "      }\n"
        "      if (ALLOWED_BOOL_FLAGS.has(tok) || tok.startsWith('--max-chars=')) {\n"
        "        i += 1;\n"
        "        continue;\n"
        "      }\n"
        "      if (tok === '--max-chars') {\n"
        "        i += 2;\n"
        "        continue;\n"
        "      }\n"
        "      if (tok.startsWith('-')) {\n"
        "        i += 1;\n"
        "        continue;\n"
        "      }\n"
        "      if (tok === '...' || tok === '…' || (tok.startsWith('<') && tok.includes('>'))) {\n"
        "        i += 1;\n"
        "        continue;\n"
        "      }\n"
        "      return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function extractCommandsFromBlock(blockText) {\n"
        "    if (!blockText) return [];\n"
        "    const lines = blockText.split(/\\r?\\n/);\n"
        "    const patchIndices = findValidPatchLineIndices(lines);\n"
        "    const found = [];\n"
        "    for (let i = 0; i < lines.length; i += 1) {\n"
        "      if (patchIndices.has(i)) continue;\n"
        "      const line = lines[i].replace(/^\\s*(?:[$>]\\s+)?/, '').trim();\n"
        "      if (!line || line.startsWith('#')) continue;\n"
        "      if (hasCopyTargetArgument(line)) {\n"
        "        found.push(line);\n"
        "      }\n"
        "    }\n"
        "    return found;\n"
        "  }\n\n"
        "  function extractLatestCommands(turns) {\n"
        "    const { codeTexts, inlineCodeTexts, bodyTexts } = collectResponseTexts(turns);\n"
        "    const allSources = codeTexts.concat(inlineCodeTexts, bodyTexts);\n"
        "    const unique = [];\n"
        "    const seen = new Set();\n"
        "    for (const src of allSources) {\n"
        "      for (const cmd of extractCommandsFromBlock(src)) {\n"
        "        if (!seen.has(cmd)) {\n"
        "          seen.add(cmd);\n"
        "          unique.push(cmd);\n"
        "        }\n"
        "      }\n"
        "    }\n"
        "    return unique;\n"
        "  }\n\n"
        "  function hasPatchBlockInTurns(turns) {\n"
        "    if (!Array.isArray(turns) || !turns.length) return false;\n"
        "    const commitTagPattern = '(?:^|\\\\n)[ \\\\t]*<' + 'commit>[ \\\\t]*(?:\\\\n|$)';\n"
        "    const structureHintRe = new RegExp(\n"
        "      '(?:^|\\\\n)[ \\\\t]*(?:ファイルパス|File(?:\\\\s+path)?|Path|削除|移動|名前変更|リネーム|ファイル移動|move|mv|rename)[ \\\\t]*[:：]|' + commitTagPattern,\n"
        "      'i'\n"
        "    );\n"
        "    const { codeTexts, bodyTexts } = collectResponseTexts(turns);\n"
        "    for (const src of codeTexts.concat(bodyTexts)) {\n"
        "      if (!src || !structureHintRe.test(src)) continue;\n"
        "      const lines = src.split(/\\r?\\n/);\n"
        "      if (findValidPatchLineIndices(lines).size > 0) return true;\n"
        "    }\n"
        "    const fullText = extractFullResponseText(turns);\n"
        "    if (!fullText || !structureHintRe.test(fullText)) return false;\n"
        "    return findValidPatchLineIndices(fullText.split(/\\r?\\n/)).size > 0;\n"
        "  }\n\n"
        "  function hasUnclosedPatchStructure(text) {\n"
        "    if (!text) return false;\n"
        "    const lines = text.split(/\\r?\\n/);\n"
        "    let inPatchBlock = false;\n"
        "    for (const line of lines) {\n"
        "      if (PATCH_START_RE.test(line)) {\n"
        "        inPatchBlock = true;\n"
        "      } else if (PATCH_END_RE.test(line)) {\n"
        "        inPatchBlock = false;\n"
        "      }\n"
        "    }\n"
        "    if (inPatchBlock) return true;\n"
        "    const openCommitRe = new RegExp('(?:^|\\\\n)[ \\\\t]*<' + 'commit>(?:\\\\s|$)', 'i');\n"
        "    const closeCommitRe = new RegExp('</' + 'commit>', 'i');\n"
        "    if (openCommitRe.test(text) && !closeCommitRe.test(text)) {\n"
        "      return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function hasIncompletePatchInTurns(turns) {\n"
        "    if (!Array.isArray(turns) || !turns.length) return false;\n"
        "    if (!hasPatchBlockInTurns(turns)) return false;\n"
        "    const { codeTexts, bodyTexts } = collectResponseTexts(turns);\n"
        "    for (const src of codeTexts.concat(bodyTexts)) {\n"
        "      if (hasUnclosedPatchStructure(src)) return true;\n"
        "    }\n"
        "    return hasUnclosedPatchStructure(extractFullResponseText(turns));\n"
        "  }\n\n"
        "  function findExcludedStopSignalLineIndices(lines) {\n"
        "    // パッチ内自己言及やコードブロック内例示による誤停止を防ぐため対象範囲を除外\n"
        "    const excluded = findValidPatchLineIndices(lines);\n"
        "    let fenceChar = '';\n"
        "    let fenceLen = 0;\n"
        "    for (let i = 0; i < lines.length; i += 1) {\n"
        "      const line = lines[i];\n"
        "      if (fenceChar) {\n"
        "        excluded.add(i);\n"
        "        const trimmed = line.trim();\n"
        "        if (trimmed.length >= fenceLen) {\n"
        "          let allSame = true;\n"
        "          for (let k = 0; k < trimmed.length; k += 1) {\n"
        "            if (trimmed[k] !== fenceChar) {\n"
        "              allSame = false;\n"
        "              break;\n"
        "            }\n"
        "          }\n"
        "          if (allSame) {\n"
        "            fenceChar = '';\n"
        "            fenceLen = 0;\n"
        "          }\n"
        "        }\n"
        "        continue;\n"
        "      }\n"
        "      const m = HANDOFF_FENCE_OPEN_RE.exec(line);\n"
        "      if (m) {\n"
        "        const marker = m[1];\n"
        "        const info = m[2] || '';\n"
        "        if (marker[0] === '~' || !info.includes('`')) {\n"
        "          fenceChar = marker[0];\n"
        "          fenceLen = marker.length;\n"
        "          excluded.add(i);\n"
        "        }\n"
        "      }\n"
        "    }\n"
        "    return excluded;\n"
        "  }\n\n"
        "  function hasHandoffStopSignalInText(text) {\n"
        "    if (!text || !String(text).includes(HANDOFF_STOP_SIGNAL)) return false;\n"
        "    const lines = String(text).split(/\\r?\\n/);\n"
        "    const excludedIndices = findExcludedStopSignalLineIndices(lines);\n"
        "    for (let i = 0; i < lines.length; i += 1) {\n"
        "      if (excludedIndices.has(i)) continue;\n"
        "      if (HANDOFF_STOP_SIGNAL_LINE_RE.test(lines[i])) return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function hasHandoffStopSignalInTurns(turns) {\n"
        "    if (!Array.isArray(turns) || !turns.length) return false;\n"
        "    const { bodyTexts } = collectResponseTexts(turns);\n"
        "    for (const src of bodyTexts) {\n"
        "      if (hasHandoffStopSignalInText(src)) return true;\n"
        "    }\n"
        "    return hasHandoffStopSignalInText(extractFullResponseText(turns));\n"
        "  }\n\n"
    )
