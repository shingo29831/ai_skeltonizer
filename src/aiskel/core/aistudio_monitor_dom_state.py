"""Module: @role: Google AI StudioのDOM可視性・推論状態・Runボタン・スレッドURL/アカウント判定のJSヘルパー群を生成する。"""

def build_monitor_dom_state_js() -> str:
    """DOM可視性・推論状態・スレッドURL・アカウント判定を行うJSヘルパー関数群を返す。"""
    return (
        "  function isElementVisible(el) {\n"
        "    if (!el || !el.isConnected) return false;\n"
        "    if (el.closest('[hidden], [aria-hidden=\"true\"]')) return false;\n"
        "    const style = window.getComputedStyle(el);\n"
        "    if (style.display === 'none' || style.visibility === 'hidden' || style.visibility === 'collapse') {\n"
        "      return false;\n"
        "    }\n"
        "    if (parseFloat(style.opacity || '1') <= 0.01) return false;\n"
        "    // display:contents/inlineは自身Rectが0でも子要素・子テキストで可視性を判定\n"
        "    if (style.display === 'contents') {\n"
        "      for (let child = el.firstChild; child; child = child.nextSibling) {\n"
        "        if (child.nodeType === 1 && isElementVisible(child)) return true;\n"
        "        if (child.nodeType === 3 && (child.nodeValue || '').trim() && typeof document.createRange === 'function') {\n"
        "          try {\n"
        "            const range = document.createRange();\n"
        "            range.selectNodeContents(child);\n"
        "            const textRect = range.getBoundingClientRect();\n"
        "            if (textRect.width > 0 && textRect.height > 0) return true;\n"
        "          } catch (_e) {}\n"
        "        }\n"
        "      }\n"
        "      return false;\n"
        "    }\n"
        "    const rects = el.getClientRects();\n"
        "    if (rects && rects.length > 0) {\n"
        "      const rect = el.getBoundingClientRect();\n"
        "      if (rect.width > 0 && rect.height > 0) return true;\n"
        "    }\n"
        "    if (style.display === 'inline') {\n"
        "      for (let child = el.firstElementChild; child; child = child.nextElementSibling) {\n"
        "        if (isElementVisible(child)) return true;\n"
        "      }\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function isRunButtonDisabled(runButton) {\n"
        "    if (!runButton || !isElementVisible(runButton)) return true;\n"
        "    if (runButton.disabled || runButton.hasAttribute('disabled') || runButton.getAttribute('aria-disabled') === 'true') {\n"
        "      return true;\n"
        "    }\n"
        "    const innerBtn = runButton.querySelector('button');\n"
        "    if (innerBtn && (innerBtn.disabled || innerBtn.hasAttribute('disabled') || innerBtn.getAttribute('aria-disabled') === 'true')) {\n"
        "      return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function parseThreadLocation(rawUrl) {\n"
        "    try {\n"
        "      const u = new URL(rawUrl || window.location.href);\n"
        "      let rawPath = (u.pathname || '/').replace(/\\/+$/, '') || '/';\n"
        "      let accountPrefix = '';\n"
        "      const uMatch = /^\\/u\\/(\\d+)(?=\\/|$)/.exec(rawPath);\n"
        "      if (uMatch) {\n"
        "        accountPrefix = '/u/' + uMatch[1];\n"
        "        rawPath = rawPath.slice(accountPrefix.length) || '/';\n"
        "      }\n"
        "      rawPath = rawPath.replace(/^\\/app(?=\\/|$)/, '') || '/';\n"
        "      const authUser = (u.searchParams.get('authuser') || '').trim().toLowerCase();\n"
        "      const isNewChat = rawPath === '/' || rawPath === '/prompts' || rawPath === '/prompts/new_chat';\n"
        "      const isPromptRoute = isNewChat || rawPath.startsWith('/prompts/');\n"
        "      return {\n"
        "        origin: u.origin,\n"
        "        accountPrefix,\n"
        "        authUser,\n"
        "        normalizedPath: rawPath,\n"
        "        isNewChat,\n"
        "        isPromptRoute,\n"
        "        threadKey: isNewChat ? '__NEW_CHAT__' : rawPath,\n"
        "      };\n"
        "    } catch (_e) {\n"
        "      return null;\n"
        "    }\n"
        "  }\n\n"
        "  function isNewChatUrl(rawUrl) {\n"
        "    const loc = parseThreadLocation(rawUrl);\n"
        "    return Boolean(loc && loc.isNewChat);\n"
        "  }\n\n"
        "  function isChatConversationEmpty() {\n"
        "    // 既存スレッドのSPA履歴描画完了前に空チャットと誤判定するのを防ぐためURLパスも検証\n"
        "    if (!isNewChatUrl(window.location.href)) return false;\n"
        "    if (isInferring()) return false;\n"
        "    const loaders = document.querySelectorAll('ms-chat-loading-indicator, .thinking-progress-icon');\n"
        "    for (const loader of loaders) {\n"
        "      if (isElementVisible(loader)) return false;\n"
        "    }\n"
        "    const allTurns = document.querySelectorAll('ms-chat-turn');\n"
        "    for (const turn of allTurns) {\n"
        "      if (turn.querySelector('[data-turn-role=\"User\"], [data-turn-role=\"Model\"]')) {\n"
        "        return false;\n"
        "      }\n"
        "      if ((turn.textContent || '').trim()) {\n"
        "        return false;\n"
        "      }\n"
        "    }\n"
        "    return true;\n"
        "  }\n\n"
        "  const STOP_BUTTON_LABEL_RE = /(?:^|\\b)(?:stop|cancel|abort|interrupt)(?:\\b|$)|停止|中断|キャンセル/i;\n\n"
        "  function isSvgStopOrSpinnerIcon(svgEl, allowRectStop = true) {\n"
        "    if (!svgEl || !isElementVisible(svgEl)) return false;\n"
        "    const cls = typeof svgEl.className === 'string'\n"
        "      ? svgEl.className\n"
        "      : ((svgEl.className && svgEl.className.baseVal) || '');\n"
        "    if (/\\b(?:spin|spinner|loading|progress)\\b/i.test(cls)) {\n"
        "      return true;\n"
        "    }\n"
        "    if (!allowRectStop) return false;\n"
        "    // 送信矢印SVGとの誤認を防ぐためpath等を含まない純粋な四角形のみStopアイコンと判定\n"
        "    const hasRect = Boolean(svgEl.querySelector('rect'));\n"
        "    const hasArrowShape = Boolean(svgEl.querySelector('path, polygon, polyline, line'));\n"
        "    return hasRect && !hasArrowShape;\n"
        "  }\n\n"
        "  function hasRunButtonStopSignal(runBtn, runHost) {\n"
        "    const host = runHost || (runBtn && typeof runBtn.closest === 'function'\n"
        "      ? (runBtn.closest('ms-run-button') || runBtn)\n"
        "      : null);\n"
        "    if (!host || !isElementVisible(host)) return false;\n"
        "    const targets = [];\n"
        "    if (runBtn && isElementVisible(runBtn)) targets.push(runBtn);\n"
        "    if (host !== runBtn) targets.push(host);\n"
        "    for (const el of targets) {\n"
        "      const attrs = [\n"
        "        el.getAttribute('aria-label') || '',\n"
        "        el.getAttribute('title') || '',\n"
        "        el.getAttribute('mattooltip') || '',\n"
        "        el.getAttribute('data-tooltip') || '',\n"
        "      ];\n"
        "      for (const val of attrs) {\n"
        "        if (val && STOP_BUTTON_LABEL_RE.test(val)) return true;\n"
        "      }\n"
        "    }\n"
        "    const icons = host.querySelectorAll('span.material-symbols-outlined, mat-icon');\n"
        "    for (const icon of icons) {\n"
        "      if (!isElementVisible(icon)) continue;\n"
        "      const iconText = (icon.textContent || '').trim().toLowerCase();\n"
        "      if (iconText === 'progress_activity' || iconText === 'stop' || iconText === 'stop_circle' || iconText === 'cancel') {\n"
        "        return true;\n"
        "      }\n"
        "    }\n"
        "    const progressNodes = host.querySelectorAll('mat-spinner, mat-progress-spinner, [role=\"progressbar\"], .thinking-progress-icon.in-progress');\n"
        "    for (const node of progressNodes) {\n"
        "      if (isElementVisible(node)) return true;\n"
        "    }\n"
        "    if (runBtn && isElementVisible(runBtn)) {\n"
        "      const btnText = (runBtn.textContent || '').trim();\n"
        "      if (btnText && STOP_BUTTON_LABEL_RE.test(btnText)) return true;\n"
        "    }\n"
        "    // Run/送信ラベルが明示されている場合、ショートカット枠線等の<rect>SVGによるStop誤認のみ抑止しスピナーは維持\n"
        "    const explicitRunLabel = targets.some((el) => {\n"
        "      const lbl = [el.getAttribute('aria-label') || '', el.getAttribute('title') || '', el.textContent || ''].join(' ');\n"
        "      return /(?:^|\\b)(?:run|send|submit)(?:\\b|$)|送信|実行/i.test(lbl);\n"
        "    });\n"
        "    const svgs = host.querySelectorAll('svg');\n"
        "    for (const svg of svgs) {\n"
        "      if (isSvgStopOrSpinnerIcon(svg, !explicitRunLabel)) return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function isSendableRunButton(runBtn, runHost) {\n"
        "    if (!runBtn || !runHost) return false;\n"
        "    if (isRunButtonDisabled(runHost) || isRunButtonDisabled(runBtn)) return false;\n"
        "    return !hasRunButtonStopSignal(runBtn, runHost);\n"
        "  }\n\n"
        "  function getTurnContext() {\n"
        "    const allTurns = Array.from(document.querySelectorAll('ms-chat-turn'));\n"
        "    let userTurnCount = 0;\n"
        "    let lastUserIndex = -1;\n"
        "    for (let i = 0; i < allTurns.length; i += 1) {\n"
        "      if (allTurns[i].querySelector('[data-turn-role=\"User\"]')) {\n"
        "        userTurnCount += 1;\n"
        "        lastUserIndex = i;\n"
        "      }\n"
        "    }\n"
        "    const modelTurns = [];\n"
        "    const modelIndices = [];\n"
        "    for (let i = lastUserIndex + 1; i < allTurns.length; i += 1) {\n"
        "      if (allTurns[i].querySelector('[data-turn-role=\"Model\"]')) {\n"
        "        modelTurns.push(allTurns[i]);\n"
        "        modelIndices.push(i);\n"
        "      }\n"
        "    }\n"
        "    return { userTurnCount, modelTurns, modelIndices };\n"
        "  }\n\n"
        "  function isInferring() {\n"
        "    // ファイル添付等の他スピナー誤検知を防ぐためms-run-button配下の停止/スピナー表示に限定して判定\n"
        "    const runHosts = document.querySelectorAll('ms-run-button');\n"
        "    for (const host of runHosts) {\n"
        "      if (!isElementVisible(host)) continue;\n"
        "      const innerBtn = host.querySelector('button, [role=\"button\"]');\n"
        "      if (hasRunButtonStopSignal(innerBtn || host, host)) {\n"
        "        return true;\n"
        "      }\n"
        "    }\n"
        "    // 思考フェーズから本応答への遷移途切れで早期確定しないよう進行中思考・プログレスも継続扱い\n"
        "    const ctx = getTurnContext();\n"
        "    for (const turn of ctx.modelTurns) {\n"
        "      const thinkingNodes = turn.querySelectorAll(\n"
        "        '.thinking-progress-icon.in-progress, ms-chat-loading-indicator, mat-spinner, mat-progress-spinner, [role=\"progressbar\"], [data-streaming=\"true\"]'\n"
        "      );\n"
        "      for (const el of thinkingNodes) {\n"
        "        if (isElementVisible(el) && !el.closest('[data-aiskel-ui=\"true\"]')) return true;\n"
        "      }\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function detectLoggedInAccountEmail() {\n"
        "    const selectors = [\n"
        "      'header a[aria-label*=\"@\"]',\n"
        "      'header button[aria-label*=\"@\"]',\n"
        "      'ms-header a[aria-label*=\"@\"]',\n"
        "      'ms-header button[aria-label*=\"@\"]',\n"
        "      '[role=\"banner\"] a[aria-label*=\"@\"]',\n"
        "      '[role=\"banner\"] button[aria-label*=\"@\"]',\n"
        "      'a[href*=\"accounts.google.com\"][aria-label*=\"@\"]',\n"
        "      'a[href*=\"SignOutOptions\"][aria-label*=\"@\"]',\n"
        "      'button[aria-label*=\"Google\"][aria-label*=\"@\"]',\n"
        "      'a[aria-label*=\"Google\"][aria-label*=\"@\"]',\n"
        "      '[data-email*=\"@\"]',\n"
        "    ];\n"
        "    const emailRe = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}/;\n"
        "    for (const sel of selectors) {\n"
        "      const nodes = document.querySelectorAll(sel);\n"
        "      for (const node of nodes) {\n"
        "        if (node.closest('ms-chat-turn')) continue;\n"
        "        const raw = node.getAttribute('data-email') || node.getAttribute('aria-label') || '';\n"
        "        const m = emailRe.exec(raw);\n"
        "        if (m) return m[0];\n"
        "      }\n"
        "    }\n"
        "    return '';\n"
        "  }\n\n"
        "  function buildSameAccountNewChatUrl(currentUrl) {\n"
        "    try {\n"
        "      const parsed = new URL(currentUrl || window.location.href);\n"
        "      const uMatch = /^\\/u\\/(\\d+)(?:\\/|$)/.exec(parsed.pathname || '');\n"
        "      const targetPath = uMatch ? ('/u/' + uMatch[1] + '/prompts/new_chat') : '/prompts/new_chat';\n"
        "      const target = new URL(parsed.origin + targetPath);\n"
        "      const authuser = parsed.searchParams.get('authuser');\n"
        "      if (authuser) {\n"
        "        target.searchParams.set('authuser', authuser);\n"
        "      } else if (!uMatch) {\n"
        "        const email = detectLoggedInAccountEmail();\n"
        "        if (email) {\n"
        "          target.searchParams.set('authuser', email);\n"
        "        }\n"
        "      }\n"
        "      return target.toString();\n"
        "    } catch (_e) {\n"
        "      return 'https://aistudio.google.com/prompts/new_chat';\n"
        "    }\n"
        "  }\n\n"
    )
