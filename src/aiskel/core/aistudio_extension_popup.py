def build_popup_js() -> str:
    """拡張機能ポップアップでAI Studioタブ一覧を取得・選択・紐づけ制御するスクリプトを生成する。"""
    return (
        "'use strict';\n\n"
        "const connBadge = document.getElementById('conn-badge');\n"
        "const projectInfo = document.getElementById('project-info');\n"
        "const errorBox = document.getElementById('error-box');\n"
        "const tabList = document.getElementById('tab-list');\n"
        "const refreshBtn = document.getElementById('refresh-btn');\n"
        "const remainTabsLabel = document.getElementById('remain-tabs-label');\n"
        "const maxTabsDecBtn = document.getElementById('max-tabs-dec');\n"
        "const maxTabsInput = document.getElementById('max-tabs-input');\n"
        "const maxTabsIncBtn = document.getElementById('max-tabs-inc');\n"
        "let currentMaxAutoTabs = 1;\n"
        "let maxTabsUpdating = false;\n"
        "let popupConnected = false;\n\n"
        "function clearElement(el) {\n"
        "  while (el.firstChild) {\n"
        "    el.removeChild(el.firstChild);\n"
        "  }\n"
        "}\n\n"
        "function sendRuntimeMessage(msg) {\n"
        "  return new Promise((resolve) => {\n"
        "    try {\n"
        "      chrome.runtime.sendMessage(msg, (res) => {\n"
        "        if (chrome.runtime.lastError) {\n"
        "          resolve({ ok: false, error: chrome.runtime.lastError.message });\n"
        "          return;\n"
        "        }\n"
        "        resolve(res || {});\n"
        "      });\n"
        "    } catch (err) {\n"
        "      resolve({ ok: false, error: String(err) });\n"
        "    }\n"
        "  });\n"
        "}\n\n"
        "function renderTabs(tabs, connected) {\n"
        "  clearElement(tabList);\n"
        "  if (!tabs || tabs.length === 0) {\n"
        "    const emptyDiv = document.createElement('div');\n"
        "    emptyDiv.className = 'empty';\n"
        "    const msg = document.createElement('div');\n"
        "    msg.textContent = 'Google AI Studio のタブが開かれていません';\n"
        "    msg.style.marginBottom = '10px';\n"
        "    const openBtn = document.createElement('button');\n"
        "    openBtn.type = 'button';\n"
        "    openBtn.className = 'btn-primary';\n"
        "    openBtn.textContent = 'Google AI Studio を開く';\n"
        "    openBtn.addEventListener('click', async () => {\n"
        "      await sendRuntimeMessage({ type: 'AISKEL_OPEN_AISTUDIO' });\n"
        "      window.setTimeout(refresh, 400);\n"
        "    });\n"
        "    emptyDiv.appendChild(msg);\n"
        "    emptyDiv.appendChild(openBtn);\n"
        "    tabList.appendChild(emptyDiv);\n"
        "    return;\n"
        "  }\n\n"
        "  for (const tab of tabs) {\n"
        "    const card = document.createElement('div');\n"
        "    card.className = 'tab-card' + (tab.is_bound ? ' bound' : '');\n\n"
        "    const header = document.createElement('div');\n"
        "    header.className = 'tab-header';\n"
        "    const title = document.createElement('span');\n"
        "    title.className = 'tab-title';\n"
        "    title.textContent = tab.title || 'Google AI Studio';\n"
        "    header.appendChild(title);\n\n"
        "    if (tab.is_bound) {\n"
        "      const tag = document.createElement('span');\n"
        "      tag.className = 'badge ok';\n"
        "      tag.textContent = '監視中';\n"
        "      header.appendChild(tag);\n"
        "    } else if (tab.active) {\n"
        "      const tag = document.createElement('span');\n"
        "      tag.className = 'badge';\n"
        "      tag.textContent = '表示中';\n"
        "      header.appendChild(tag);\n"
        "    }\n\n"
        "    const urlEl = document.createElement('div');\n"
        "    urlEl.className = 'tab-url';\n"
        "    urlEl.textContent = tab.url || '';\n\n"
        "    const actions = document.createElement('div');\n"
        "    actions.className = 'tab-actions';\n\n"
        "    const bindBtn = document.createElement('button');\n"
        "    bindBtn.type = 'button';\n"
        "    bindBtn.disabled = !connected;\n"
        "    if (tab.is_bound) {\n"
        "      bindBtn.className = 'btn-danger';\n"
        "      bindBtn.textContent = '紐づけ解除';\n"
        "      bindBtn.addEventListener('click', async () => {\n"
        "        bindBtn.disabled = true;\n"
        "        await sendRuntimeMessage({ type: 'AISKEL_UNBIND_TAB', tabId: tab.id, explicit: true });\n"
        "        await refresh();\n"
        "      });\n"
        "    } else {\n"
        "      bindBtn.className = 'btn-primary';\n"
        "      bindBtn.textContent = 'VSCodeと紐づける';\n"
        "      bindBtn.addEventListener('click', async () => {\n"
        "        bindBtn.disabled = true;\n"
        "        await sendRuntimeMessage({ type: 'AISKEL_BIND_TAB', tabId: tab.id });\n"
        "        await refresh();\n"
        "      });\n"
        "    }\n\n"
        "    const focusBtn = document.createElement('button');\n"
        "    focusBtn.type = 'button';\n"
        "    focusBtn.className = 'btn-secondary';\n"
        "    focusBtn.textContent = '開く';\n"
        "    focusBtn.addEventListener('click', async () => {\n"
        "      await sendRuntimeMessage({ type: 'AISKEL_FOCUS_TAB', tabId: tab.id });\n"
        "    });\n\n"
        "    const insertBtn = document.createElement('button');\n"
        "    insertBtn.type = 'button';\n"
        "    insertBtn.className = 'btn-insert';\n"
        "    insertBtn.disabled = !connected;\n"
        "    insertBtn.textContent = '要約+プロンプトを挿入';\n"
        "    insertBtn.addEventListener('click', async () => {\n"
        "      insertBtn.disabled = true;\n"
        "      insertBtn.textContent = '挿入中...';\n"
        "      errorBox.hidden = true;\n"
        "      const res = await sendRuntimeMessage({ type: 'AISKEL_INSERT_SUMMARY_PROMPT', tabId: tab.id });\n"
        "      if (res && res.ok) {\n"
        "        insertBtn.textContent = '挿入しました ✓';\n"
        "        window.setTimeout(() => {\n"
        "          insertBtn.textContent = '要約+プロンプトを挿入';\n"
        "          insertBtn.disabled = !connected;\n"
        "        }, 1800);\n"
        "      } else {\n"
        "        insertBtn.textContent = '要約+プロンプトを挿入';\n"
        "        insertBtn.disabled = !connected;\n"
        "        errorBox.hidden = false;\n"
        "        errorBox.textContent = (res && res.error) ? String(res.error) : 'チャット欄への挿入に失敗しました';\n"
        "      }\n"
        "    });\n\n"
        "    actions.appendChild(bindBtn);\n"
        "    actions.appendChild(focusBtn);\n"
        "    actions.appendChild(insertBtn);\n"
        "    card.appendChild(header);\n"
        "    card.appendChild(urlEl);\n"
        "    card.appendChild(actions);\n"
        "    tabList.appendChild(card);\n"
        "  }\n"
        "}\n\n"
        "function updateMaxTabsControls(connected, binding) {\n"
        "  popupConnected = Boolean(connected);\n"
        "  if (connected && typeof binding.patch_handoff_max_tabs === 'number') {\n"
        "    currentMaxAutoTabs = Math.max(0, Math.min(999, Math.floor(binding.patch_handoff_max_tabs)));\n"
        "    if (document.activeElement !== maxTabsInput) {\n"
        "      maxTabsInput.value = String(currentMaxAutoTabs);\n"
        "    }\n"
        "    remainTabsLabel.textContent = typeof binding.remaining_auto_tabs === 'number' ? '(残: ' + binding.remaining_auto_tabs + ')' : '';\n"
        "  } else {\n"
        "    remainTabsLabel.textContent = '';\n"
        "  }\n"
        "  const disabled = !connected || maxTabsUpdating;\n"
        "  maxTabsInput.disabled = disabled;\n"
        "  maxTabsDecBtn.disabled = disabled || currentMaxAutoTabs <= 0;\n"
        "  maxTabsIncBtn.disabled = disabled || currentMaxAutoTabs >= 999;\n"
        "}\n\n"
        "async function submitMaxAutoTabs(rawValue) {\n"
        "  if (!popupConnected || maxTabsUpdating) return;\n"
        "  const trimmed = String(rawValue).trim();\n"
        "  if (!/^-?\\d+$/.test(trimmed)) {\n"
        "    maxTabsInput.value = String(currentMaxAutoTabs);\n"
        "    return;\n"
        "  }\n"
        "  const parsed = Number.parseInt(trimmed, 10);\n"
        "  const clamped = Math.max(0, Math.min(999, parsed));\n"
        "  maxTabsInput.value = String(clamped);\n"
        "  maxTabsUpdating = true;\n"
        "  updateMaxTabsControls(popupConnected, { patch_handoff_max_tabs: currentMaxAutoTabs });\n"
        "  const res = await sendRuntimeMessage({ type: 'AISKEL_SET_HANDOFF_MAX_TABS', patch_handoff_max_tabs: clamped });\n"
        "  maxTabsUpdating = false;\n"
        "  let hadError = false;\n"
        "  if (!res || !res.connected) {\n"
        "    hadError = true;\n"
        "    errorBox.hidden = false;\n"
        "    errorBox.textContent = (res && res.error) ? String(res.error) : '自動新タブ回数の更新に失敗しました';\n"
        "  }\n"
        "  await refresh({ preserveError: hadError });\n"
        "}\n\n"
        "async function refresh(options) {\n"
        "  refreshBtn.disabled = true;\n"
        "  const res = await sendRuntimeMessage({ type: 'AISKEL_LIST_TABS' });\n"
        "  refreshBtn.disabled = false;\n"
        "  const reachable = Boolean(res && res.reachable);\n"
        "  const connected = Boolean(res && res.connected);\n"
        "  const binding = (res && res.binding) || {};\n"
        "  updateMaxTabsControls(connected, binding);\n"
        "  if (connected) {\n"
        "    connBadge.className = binding.bound ? 'badge ok' : 'badge warn';\n"
        "    connBadge.textContent = binding.bound ? '紐づけ済' : '未紐づけ';\n"
        "    projectInfo.textContent = '対象: ' + (binding.project_name || binding.project_root || 'VSCode');\n"
        "    projectInfo.title = binding.project_root || '';\n"
        "    if (!(options && options.preserveError)) {\n"
        "      errorBox.hidden = true;\n"
        "    }\n"
        "  } else if (reachable) {\n"
        "    connBadge.className = 'badge err';\n"
        "    connBadge.textContent = 'エラー (' + (res.status || '?') + ')';\n"
        "    projectInfo.textContent = 'ブリッジ応答エラー';\n"
        "    projectInfo.title = '';\n"
        "    errorBox.hidden = false;\n"
        "    errorBox.textContent = 'ブリッジからエラー応答を受信しました (HTTP ' + (res.status || '?') + '): ' + (res.error || '拡張機能の再読み込みやトークン設定を確認してください。');\n"
        "  } else {\n"
        "    connBadge.className = 'badge';\n"
        "    connBadge.textContent = '未接続';\n"
        "    projectInfo.textContent = 'VSCode / aiskel ブリッジ未接続';\n"
        "    projectInfo.title = '';\n"
        "    errorBox.hidden = false;\n"
        "    errorBox.textContent = 'ローカルブリッジに接続できません。ターミナルで `aiskel s` または `aiskel listen` を起動してから更新してください。';\n"
        "  }\n"
        "  renderTabs((res && res.tabs) || [], connected);\n"
        "}\n\n"
        "maxTabsDecBtn.addEventListener('click', () => submitMaxAutoTabs(currentMaxAutoTabs - 1));\n"
        "maxTabsIncBtn.addEventListener('click', () => submitMaxAutoTabs(currentMaxAutoTabs + 1));\n"
        "maxTabsInput.addEventListener('change', () => submitMaxAutoTabs(maxTabsInput.value));\n"
        "maxTabsInput.addEventListener('keydown', (ev) => {\n"
        "  if (ev.key === 'Enter' && !ev.isComposing && ev.keyCode !== 229) {\n"
        "    ev.preventDefault();\n"
        "    submitMaxAutoTabs(maxTabsInput.value);\n"
        "    maxTabsInput.blur();\n"
        "  }\n"
        "});\n"
        "refreshBtn.addEventListener('click', () => refresh());\n"
        "refresh();\n"
    )
