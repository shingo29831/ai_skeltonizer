        "    if (!commands.length) return;\n"
        "    const turnId = buildTurnIdentifier(ctx, finishedRunSeq);\n"
        "    const commandsKey = commands.join('||');\n"
        "    const dedupKey = turnId + '::' + commandsKey;\n"
        "    if (executedKeys.has(dedupKey) || inFlightKeys.has(dedupKey)) return;\n"
        "    const preRunBtn = findPromptRunButton();\n"
        "    const preSnap = getPromptInputSnapshot(preRunBtn);\n"
        "    const dispatchCtx = {\n"
        "      url: window.location.href,\n"
        "      turnBaseId: buildBaseTurnIdentifier(ctx),\n"
        "      commandsKey,\n"
        "      pasteSeqBefore: pasteEventSeq,\n"
        "      inputTextBefore: preSnap.text,\n"
        "      chipCountBefore: preSnap.chipCount,\n"
