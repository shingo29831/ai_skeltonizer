        "    'mat-icon',\n"
        "    '.material-symbols-outlined',\n"
        "    'svg',\n"
        "    'ms-code-block-header',\n"
        "    '.code-block-header',\n"
        "    '.actions-container',\n"
        "  ].join(', ');\n\n"
        "  let wasInferring = false;\n"
        "  let userCancelledRun = false;\n"
        "  let userCancelRequestedAt = 0;\n"
        "  let resubmitRequestedAt = 0;\n"
        "  let settleTimer = null;\n"
        "  let throttleTimer = null;\n"
        "  let activePollTimer = null;\n"
        "  let autoRunTimer = null;\n"
        "  let autoRunDeadline = 0;\n"
        "  let pendingAutoRunContext = null;\n"
        "  let pasteEventSeq = 0;\n"
        "  let autoRunServerDefault = false;\n"
        "  let autoRunAllowed = false;\n"
        "  let autoRunUserOverride = null;\n"
        "  let consecutiveAutoRuns = 0;\n"
        "  let lastAutoRunCommandKey = '';\n"
        "  let stableChecks = 0;\n"
        "  let lastStableSignature = '';\n"
        "  let preInferenceSignature = '';\n"
        "  let preInferenceModelTurns = [];\n"
        "  let sawModelMutationDuringRun = false;\n"
        "  let sawSignatureChangeDuringRun = false;\n"
        "  let runSeq = 0;\n"
        "  let currentRunSeq = 0;\n"
        "  const executedKeys = new Set();\n"
        "  const inFlightKeys = new Set();\n"
        f"{binding_transport_snippet}"
        "  const hasBindingTransport = typeof bindingTransport !== 'undefined' && bindingTransport !== null;\n"
        "  let monitoringBound = !hasBindingTransport;\n"
        "  let bindingState = {\n"
        "    reachable: !hasBindingTransport,\n"
        "    connected: !hasBindingTransport,\n"
        "    status: 0,\n"
        "    errorMessage: '',\n"
        "    bound: !hasBindingTransport,\n"
        "    isCurrentTabBound: !hasBindingTransport,\n"
        "    projectName: '',\n"
        "    projectRoot: '',\n"
        "    boundTabTitle: '',\n"
        "    boundTabId: '',\n"
        "    currentTabId: '',\n"
        "    autoRunDefault: false,\n"
        "    autoRunAllowed: false,\n"
        "    autoRunEnabled: false,\n"
        "  };\n"
        "  let bindingUi = null;\n\n"
        "  function isMonitoringActive() {\n"
