        "    if (!autoRunAllowed) return false;\n"
        "    return autoRunUserOverride !== null ? autoRunUserOverride : autoRunServerDefault;\n"
        "  }\n\n"
        f"{dom_helpers_js}"
        "  function hasTurnDomChanged(ctx) {\n"
        "    if (ctx.modelTurns.length !== preInferenceModelTurns.length) return true;\n"
        "    for (let i = 0; i < ctx.modelTurns.length; i += 1) {\n"
        "      if (ctx.modelTurns[i] !== preInferenceModelTurns[i]) return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function markExecuted(dedupKey) {\n"
        "    executedKeys.add(dedupKey);\n"
        "    if (executedKeys.size > 100) {\n"
        "      const first = executedKeys.values().next().value;\n"
        "      executedKeys.delete(first);\n"
        "    }\n"
        "  }\n\n"
        "  function showToast(message, isError) {\n"
        "    const toast = document.createElement('div');\n"
        "    toast.setAttribute('data-aiskel-ui', 'true');\n"
        "    toast.textContent = message;\n"
        "    toast.style.cssText = [\n"
        "      'position:fixed',\n"
        "      'right:16px',\n"
        f"      'bottom:' + (hasBindingTransport ? '76px' : '20px'),\n"
        "      'z-index:2147483647',\n"
        "      'padding:10px 14px',\n"
        "      'border-radius:8px',\n"
        "      'font-size:13px',\n"
        "      'font-family:system-ui,sans-serif',\n"
        "      'pointer-events:none',\n"
        "      'box-shadow:0 4px 14px rgba(0,0,0,0.35)',\n"
        "      'color:#fff',\n"
        "      isError ? 'background:#b91c1c' : 'background:#1e293b',\n"
        "    ].join(';');\n"
        "    document.body.appendChild(toast);\n"
        "    window.setTimeout(() => toast.remove(), 3600);\n"
        "  }\n\n"
        "  function dispatchCommands(payload, onDone) {\n"
        "    if (hasBindingTransport && typeof bindingTransport.getLocalTabId === 'function') {\n"
        "      const localTabId = bindingTransport.getLocalTabId();\n"
        "      if (localTabId && !payload.tab_id) {\n"
        "        payload.tab_id = localTabId;\n"
        "      }\n"
        "    }\n"
        f"{send_snippet}"
        "  }\n\n"
        "  function resetSettleState() {\n"
        "    if (settleTimer !== null) {\n"
        "      window.clearTimeout(settleTimer);\n"
        "      settleTimer = null;\n"
        "    }\n"
        "    stableChecks = 0;\n"
        "    lastStableSignature = '';\n"
        "  }\n\n"
        "  function clearAutoRunTimer() {\n"
        "    if (autoRunTimer !== null) {\n"
        "      window.clearTimeout(autoRunTimer);\n"
        "      autoRunTimer = null;\n"
        "    }\n"
        "    autoRunDeadline = 0;\n"
        "    pendingAutoRunContext = null;\n"
        "  }\n\n"
        "  function shouldScheduleAutoRun(responseData, dispatchCtx) {\n"
        "    if (!responseData || !responseData.pasted || !isMonitoringActive() || isInferring()) {\n"
        "      return false;\n"
        "    }\n"
        "    const serverAllows = Boolean(responseData.auto_run || responseData.auto_run_allowed);\n"
        "    if (!serverAllows) return false;\n"
        "    const effectiveEnabled = autoRunUserOverride !== null\n"
        "      ? autoRunUserOverride\n"
        "      : Boolean(responseData.auto_run);\n"
        "    if (!effectiveEnabled) return false;\n"
        "    if (!document.hasFocus() || document.visibilityState !== 'visible') {\n"
        "      return false;\n"
        "    }\n"
        "    if (\n"
        "      window.location.href !== dispatchCtx.url ||\n"
        "      buildBaseTurnIdentifier(getTurnContext()) !== dispatchCtx.turnBaseId\n"
        "    ) {\n"
        "      showToast('aiskel 画面遷移を検知したため自動送信を中止しました', true);\n"
        "      return false;\n"
        "    }\n"
        "    if (\n"
        "      (lastAutoRunCommandKey && dispatchCtx.commandsKey === lastAutoRunCommandKey) ||\n"
        "      consecutiveAutoRuns >= MAX_CONSECUTIVE_AUTO_RUNS\n"
        "    ) {\n"
        "      autoRunUserOverride = false;\n"
        "      bindingState = Object.assign({}, bindingState, { autoRunEnabled: false });\n"
        "      if (bindingUi) bindingUi.render(bindingState);\n"
        "      showToast('aiskel 連続自動送信のループ防止のため自動送信を一時停止しました', true);\n"
        "      return false;\n"
        "    }\n"
        "    return true;\n"
        "  }\n\n"
        "  function tryClickRunButtonAfterPaste() {\n"
        "    autoRunTimer = null;\n"
        "    const ctxSnapshot = pendingAutoRunContext;\n"
        "    if (!ctxSnapshot || !isMonitoringActive() || isInferring()) {\n"
        "      clearAutoRunTimer();\n"
        "      return;\n"
        "    }\n"
        "    if (!document.hasFocus() || document.visibilityState !== 'visible') {\n"
        "      clearAutoRunTimer();\n"
        "      showToast('aiskel タブが非アクティブになったため自動送信を中止しました', true);\n"
        "      return;\n"
        "    }\n"
        "    if (\n"
        "      window.location.href !== ctxSnapshot.url ||\n"
        "      buildBaseTurnIdentifier(getTurnContext()) !== ctxSnapshot.turnBaseId\n"
        "    ) {\n"
        "      clearAutoRunTimer();\n"
        "      showToast('aiskel 画面またはスレッドが切り替わったため自動送信を中止しました', true);\n"
        "      return;\n"
        "    }\n"
        "    const runBtn = findPromptRunButton();\n"
        "    const runHost = runBtn && typeof runBtn.closest === 'function'\n"
        "      ? (runBtn.closest('ms-run-button') || runBtn)\n"
        "      : null;\n"
        "    if (runBtn && runHost && isSendableRunButton(runBtn, runHost)) {\n"
        "      const snap = getPromptInputSnapshot(runBtn);\n"
        "      const pasteDetected = pasteEventSeq > ctxSnapshot.pasteSeqBefore;\n"
        "      const textUpdated = snap.text !== ctxSnapshot.inputTextBefore && snap.text.trim().length > 0;\n"
        "      const chipUpdated = snap.chipSignature !== ctxSnapshot.chipSignatureBefore && snap.chipCount > ctxSnapshot.chipCountBefore;\n"
        "      // 既存書きかけ誤送信を防ぐため対象タブ自身のpaste完了と反映差分を確認してから送信\n"
        "      if (pasteDetected && (textUpdated || chipUpdated) && snap.hasContent) {\n"
        "        clearAutoRunTimer();\n"
        "        consecutiveAutoRuns += 1;\n"
        "        lastAutoRunCommandKey = ctxSnapshot.commandsKey;\n"
        "        runBtn.click();\n"
        "        return;\n"
        "      }\n"
        "    }\n"
        "    if (Date.now() < autoRunDeadline) {\n"
        "      autoRunTimer = window.setTimeout(tryClickRunButtonAfterPaste, AUTO_RUN_POLL_MS);\n"
        "    } else {\n"
        "      clearAutoRunTimer();\n"
        "      showToast('aiskel 貼り付け反映のタイムアウトにより自動送信をスキップしました（手動で実行してください）', true);\n"
        "    }\n"
        "  }\n\n"
        "  function scheduleAutoRunAfterPaste(dispatchCtx) {\n"
        "    clearAutoRunTimer();\n"
        "    if (!isMonitoringActive() || isInferring()) return;\n"
        "    pendingAutoRunContext = dispatchCtx;\n"
        "    autoRunDeadline = Date.now() + AUTO_RUN_TIMEOUT_MS;\n"
        "    autoRunTimer = window.setTimeout(tryClickRunButtonAfterPaste, AUTO_RUN_INITIAL_DELAY_MS);\n"
        "  }\n\n"
        "  function abortCancelledCycle() {\n"
        "    clearAutoRunTimer();\n"
        "    wasInferring = false;\n"
        "    userCancelledRun = false;\n"
        "    userCancelRequestedAt = 0;\n"
        "    stopActivePoll();\n"
        "    resetSettleState();\n"
        "  }\n\n"
        "  function handleAutoSubmitAction() {\n"
        "    clearAutoRunTimer();\n"
        "    if (userCancelledRun) {\n"
        "      abortCancelledCycle();\n"
        "    } else {\n"
        "      userCancelledRun = false;\n"
        "      userCancelRequestedAt = 0;\n"
        "    }\n"
        "    resubmitRequestedAt = Date.now();\n"
        "  }\n\n"
        "  function handleManualSubmitAction() {\n"
        "    consecutiveAutoRuns = 0;\n"
        "    lastAutoRunCommandKey = '';\n"
        "    handleAutoSubmitAction();\n"
        "  }\n\n"
        "  function beginNewInferenceCycle() {\n"
        "    wasInferring = true;\n"
        "    userCancelledRun = false;\n"
        "    userCancelRequestedAt = 0;\n"
        "    resubmitRequestedAt = 0;\n"
        "    runSeq += 1;\n"
        "    currentRunSeq = runSeq;\n"
        "    const ctx = getTurnContext();\n"
        "    preInferenceSignature = buildModelSignature(ctx);\n"
        "    preInferenceModelTurns = ctx.modelTurns.slice();\n"
        "    sawModelMutationDuringRun = false;\n"
        "    sawSignatureChangeDuringRun = false;\n"
        "    startActivePoll();\n"
        "  }\n\n"
        "  function finalizeInferenceCompleted(ctx, currentSig) {\n"
        "    if (!isMonitoringActive()) return;\n"
        "    const finishedRunSeq = currentRunSeq;\n"
        "    const hadChange = (\n"
        "      currentSig !== preInferenceSignature ||\n"
        "      sawSignatureChangeDuringRun ||\n"
        "      sawModelMutationDuringRun ||\n"
        "      hasTurnDomChanged(ctx)\n"
        "    );\n"
        "    const cancelled = userCancelledRun;\n"
        "    abortCancelledCycle();\n"
        "    if (cancelled) {\n"
        "      console.debug('[aiskel] ユーザーによる手動中断を検知したため自動実行をスキップしました');\n"
        "      return;\n"
        "    }\n"
        "    if (!ctx.modelTurns.length || !currentSig || !hadChange) return;\n"
