        "  let wasInferring = false;\n"
        "  let userCancelledRun = false;\n"
        "  let userCancelRequestedAt = 0;\n"
        "  let resubmitRequestedAt = 0;\n"
        "  let settleTimer = null;\n"
        "  let throttleTimer = null;\n"
        "  let activePollTimer = null;\n"
        "  let autoRunTimer = null;\n"
        "  let autoRunDeadline = 0;\n"
        "  let pendingAutoRunContext = null;\n"
        "  let pasteEventSeq = 0;\n"
        "  let autoRunServerDefault = false;\n"
        "  let autoRunAllowed = false;\n"
        "  let autoRunUserOverride = null;\n"
