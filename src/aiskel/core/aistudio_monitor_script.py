        "        turn_id: turnId,\n"
        "        commands,\n"
        "        source_url: dispatchCtx.url,\n"
        "        tab_title: document.title || '',\n"
        "        page_focused: document.hasFocus() && document.visibilityState === 'visible',\n"
        "      },\n"
        "      (succeeded, responseData) => {\n"
        "        inFlightKeys.delete(dedupKey);\n"
        "        if (succeeded) {\n"
        "          markExecuted(dedupKey);\n"
        "          if (shouldScheduleAutoRun(responseData, dispatchCtx)) {\n"
        "            scheduleAutoRunAfterPaste(dispatchCtx);\n"
        "          }\n"
        "        }\n"
        "      }\n"
        "    );\n"
        "  }\n\n"
        "  function scheduleSettleCheck() {\n"
        "    if (settleTimer !== null) return;\n"
        "    settleTimer = window.setTimeout(() => {\n"
        "      settleTimer = null;\n"
        "      if (isInferring()) {\n"
        "        resetSettleState();\n"
        "        return;\n"
        "      }\n"
        "      const ctx = getTurnContext();\n"
        "      const currentSig = buildModelSignature(ctx);\n"
        "      if (currentSig === lastStableSignature) {\n"
        "        stableChecks += 1;\n"
        "      } else {\n"
        "        lastStableSignature = currentSig;\n"
        "        stableChecks = 1;\n"
        "      }\n"
        "      if (stableChecks >= REQUIRED_STABLE_CHECKS) {\n"
        "        finalizeInferenceCompleted(ctx, currentSig);\n"
        "      } else {\n"
        "        scheduleSettleCheck();\n"
        "      }\n"
        "    }, SETTLE_STEP_MS);\n"
        "  }\n\n"
        "  function startActivePoll() {\n"
        "    if (activePollTimer !== null) return;\n"
        "    activePollTimer = window.setInterval(evaluateState, ACTIVE_POLL_MS);\n"
        "  }\n\n"
        "  function stopActivePoll() {\n"
        "    if (activePollTimer !== null) {\n"
        "      window.clearInterval(activePollTimer);\n"
        "      activePollTimer = null;\n"
        "    }\n"
        "  }\n\n"
        "  function evaluateState() {\n"
        "    if (!isMonitoringActive()) {\n"
        "      if (wasInferring || settleTimer !== null || activePollTimer !== null) {\n"
        "        abortCancelledCycle();\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    const inferringNow = isInferring();\n"
        "    if (inferringNow) {\n"
        "      const wasSettling = settleTimer !== null || stableChecks > 0;\n"
        "      const hasPendingResubmit = resubmitRequestedAt > 0 && (Date.now() - resubmitRequestedAt) <= RESUBMIT_WINDOW_MS;\n"
        "      resetSettleState();\n"
        "      // 安定化タイマー起動前の即時再送信でも新サイクルを開始させるためhasPendingResubmitを独立判定\n"
        "      if (!wasInferring || hasPendingResubmit || (wasSettling && userCancelledRun)) {\n"
        "        beginNewInferenceCycle();\n"
        "      } else {\n"
        "        if (userCancelledRun && userCancelRequestedAt > 0 && (Date.now() - userCancelRequestedAt) > CANCEL_EXPIRY_MS) {\n"
        "          userCancelledRun = false;\n"
        "          userCancelRequestedAt = 0;\n"
        "        }\n"
        "        const currentSig = buildModelSignature(getTurnContext());\n"
        "        if (currentSig !== preInferenceSignature) {\n"
        "          sawSignatureChangeDuringRun = true;\n"
        "        }\n"
        "      }\n"
        "      return;\n"
        "    }\n"
        "    if (wasInferring) {\n"
        "      scheduleSettleCheck();\n"
        "    }\n"
        "  }\n\n"
        "  function scheduleEvaluate() {\n"
        "    if (throttleTimer !== null) return;\n"
        "    throttleTimer = window.setTimeout(() => {\n"
        "      throttleTimer = null;\n"
        "      evaluateState();\n"
        "    }, CHECK_THROTTLE_MS);\n"
        "  }\n\n"
        "  function isIgnoredModelSubtree(el) {\n"
        "    return Boolean(el && el.closest && el.closest(IGNORED_SUBTREE_SELECTOR));\n"
        "  }\n\n"
        "  function isLatestModelTurn(turn, ctx) {\n"
        "    return Boolean(turn && ctx && ctx.modelTurns.includes(turn));\n"
        "  }\n\n"
        "  function hasMeaningfulResponseText(node) {\n"
        "    if (!node) return false;\n"
        "    if (node.nodeType === 3) {\n"
        "      return Boolean((node.nodeValue || '').trim());\n"
        "    }\n"
        "    if (node.nodeType !== 1) return false;\n"
        "    if (node.matches(IGNORED_SUBTREE_SELECTOR)) return false;\n"
        "    if (node.matches('ms-code-block')) {\n"
        "      const codeNodes = node.querySelectorAll('pre code, pre, code');\n"
        "      for (const codeEl of codeNodes) {\n"
        "        if (!isIgnoredModelSubtree(codeEl) && hasMeaningfulResponseText(codeEl)) {\n"
        "          return true;\n"
        "        }\n"
        "      }\n"
        "      return false;\n"
        "    }\n"
        "    for (let child = node.firstChild; child; child = child.nextSibling) {\n"
        "      if (hasMeaningfulResponseText(child)) return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function isInsideModelResponseContent(el, ctx) {\n"
        "    if (!el || !el.isConnected || isIgnoredModelSubtree(el)) return false;\n"
        "    const turn = el.closest('ms-chat-turn');\n"
        "    if (!isLatestModelTurn(turn, ctx)) return false;\n"
        "    if (el.closest('ms-code-block')) {\n"
        "      return Boolean(el.closest('ms-code-block pre, ms-code-block code'));\n"
        "    }\n"
        "    return Boolean(el.closest(RESPONSE_CONTENT_SELECTOR));\n"
        "  }\n\n"
        "  function nodeContainsMeaningfulResponseContent(node, inLatestModelTurn, ctx) {\n"
        "    if (!node || node.nodeType !== 1) return false;\n"
        "    if (node.matches(IGNORED_SUBTREE_SELECTOR)) return false;\n"
        "    if (!inLatestModelTurn) {\n"
        "      if (node.matches('ms-chat-turn')) {\n"
        "        return isLatestModelTurn(node, ctx) && nodeContainsMeaningfulResponseContent(node, true, ctx);\n"
        "      }\n"
        "      const turns = node.querySelectorAll('ms-chat-turn');\n"
        "      for (const turn of turns) {\n"
        "        if (isLatestModelTurn(turn, ctx) && nodeContainsMeaningfulResponseContent(turn, true, ctx)) {\n"
        "          return true;\n"
        "        }\n"
        "      }\n"
        "      return false;\n"
        "    }\n"
        "    if (node.matches(RESPONSE_CONTAINER_SELECTOR)) {\n"
        "      return hasMeaningfulResponseText(node);\n"
        "    }\n"
        "    const candidates = node.querySelectorAll(RESPONSE_CONTAINER_SELECTOR);\n"
        "    for (const cand of candidates) {\n"
        "      if (isIgnoredModelSubtree(cand)) continue;\n"
        "      if (hasMeaningfulResponseText(cand)) return true;\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
        "  function removedNodeMatchesPreInferenceTurn(node) {\n"
        "    if (!node || node.nodeType !== 1 || !preInferenceModelTurns.length) return false;\n"
        "    if (preInferenceModelTurns.includes(node)) {\n"
        "      return nodeContainsMeaningfulResponseContent(node, true, null);\n"
        "    }\n"
        "    for (const prevTurn of preInferenceModelTurns) {\n"
        "      if (node.contains(prevTurn) && nodeContainsMeaningfulResponseContent(prevTurn, true, null)) {\n"
        "        return true;\n"
        "      }\n"
        "    }\n"
        "    return false;\n"
        "  }\n\n"
