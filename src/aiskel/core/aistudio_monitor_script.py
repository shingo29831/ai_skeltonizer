        "    'ms-chat-loading-indicator',\n"
        "    '.thinking-progress-icon',\n"
        "    'button',\n"
        "    '[role=\"button\"]',\n"
        "    'mat-icon',\n"
        "    '.material-symbols-outlined',\n"
        "    'svg',\n"
        "    'ms-code-block-header',\n"
        "    '.code-block-header',\n"
        "    '.actions-container',\n"
