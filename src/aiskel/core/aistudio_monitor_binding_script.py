"""Module: @role: Google AI Studioタブとローカルブリッジ間の紐づけ同期・自動紐づけ・手動要約プロンプト挿入制御を行うクライアントJavaScriptコードを生成する。"""


def build_monitor_binding_js() -> str:
    """タブ紐づけ状態同期・自動バインド・バインドUIイベント接続処理のJSコードを生成する。"""
    return (
        "  function triggerAutoBind() {\n"
        "    if (!hasBindingTransport || autoBindInFlight || autoBindSuppressed) return;\n"
        "    autoBindInFlight = true;\n"
        "    // 通信中のブロードキャスト先着による二重抑制を防ぐため送信前状態を保持\n"
        "    const wasBoundBeforeRequest = monitoringBound;\n"
        "    bindingTransport.bindTab((res) => {\n"
        "      autoBindInFlight = false;\n"
        "      const data = (res && res.data) || {};\n"
        "      // 自動紐づけ通信中にユーザーが明示解除した場合はUserscriptを含め即座にロールバック\n"
        "      if (autoBindSuppressed && res && res.connected && data.is_current_tab_bound) {\n"
        "        bindingTransport.unbindTab((unbindRes) => {\n"
        "          applyBindingResponse(unbindRes, { skipAutoBind: true });\n"
        "        });\n"
        "        return;\n"
        "      }\n"
        "      applyBindingResponse(res, { skipAutoBind: true });\n"
        "      if (res && res.connected && data.is_current_tab_bound && !wasBoundBeforeRequest) {\n"
        "        showToast('このタブを VSCode (' + (data.project_name || 'aiskel') + ') と自動で紐づけました', false);\n"
        "      }\n"
        "    }, { autoBind: true });\n"
        "  }\n\n"
        "  function shouldAutoBindOnStatus(connected, data) {\n"
        "    if (!hasBindingTransport || !connected || !data) return false;\n"
        "    if (data.bound || autoBindSuppressed || autoBindInFlight) return false;\n"
        "    if (data.auto_bind_suppressed === true || data.is_tab_active === false) return false;\n"
        "    if (document.visibilityState !== 'visible') return false;\n"
        "    if (typeof isHandoffPendingOrActive === 'function' && isHandoffPendingOrActive()) return false;\n"
        "    return true;\n"
        "  }\n\n"
        "  function applyBindingResponse(res, options) {\n"
        "    const prevMonitoring = monitoringBound;\n"
        "    const reachable = Boolean(res && res.reachable);\n"
        "    const connected = Boolean(res && res.connected);\n"
        "    const status = (res && res.status) || 0;\n"
        "    const data = (res && res.data) || {};\n"
        "    const errorMessage = (res && res.error) ? String(res.error) : '';\n"
        "    if (!reachable) {\n"
        "      if (wasBridgeConnected) {\n"
        "        autoBindSuppressed = false;\n"
        "      }\n"
        "      wasBridgeConnected = false;\n"
        "    } else if (connected) {\n"
        "      wasBridgeConnected = true;\n"
        "      if ((data.explicit_unbind && !data.bound) || data.auto_bind_suppressed === true) {\n"
        "        autoBindSuppressed = true;\n"
        "      } else if (data.auto_bind_suppressed === false) {\n"
        "        autoBindSuppressed = false;\n"
        "      }\n"
        "      autoRunServerDefault = Boolean(data.auto_run_default);\n"
        "      autoRunAllowed = Boolean(data.auto_run_allowed);\n"
        "    } else if (reachable && (status === 401 || status === 403 || status === 404)) {\n"
        "      autoRunServerDefault = false;\n"
        "      autoRunAllowed = false;\n"
        "    }\n"
        "    bindingState = {\n"
        "      reachable,\n"
        "      connected,\n"
        "      status,\n"
        "      errorMessage,\n"
        "      bound: Boolean(connected && data.bound),\n"
        "      isCurrentTabBound: Boolean(connected && data.is_current_tab_bound),\n"
        "      projectName: String(data.project_name || ''),\n"
        "      projectRoot: String(data.project_root || ''),\n"
        "      boundTabTitle: String(data.tab_title || ''),\n"
        "      boundTabId: String(data.tab_id || ''),\n"
        "      currentTabId: String(data.current_tab_id || ''),\n"
        "      autoRunDefault: autoRunServerDefault,\n"
        "      autoRunAllowed,\n"
        "      autoRunEnabled: isAutoRunEffectiveEnabled(),\n"
        "    };\n"
        "    if (bindingUi) {\n"
        "      bindingUi.render(bindingState);\n"
        "    }\n"
        "    if (hasBindingTransport && typeof bindingTransport.notifyState === 'function') {\n"
        "      bindingTransport.notifyState(bindingState);\n"
        "    }\n"
        "    if (!hasBindingTransport) {\n"
        "      return;\n"
        "    }\n"
        "    // 一時的な通信失敗で推論中の監視状態を破棄しないよう、確定応答または非互換エラー時のみ更新\n"
        "    if (connected) {\n"
        "      monitoringBound = Boolean(data.is_current_tab_bound);\n"
        "    } else if (reachable && (status === 401 || status === 403 || status === 404)) {\n"
        "      monitoringBound = false;\n"
        "    }\n"
        "    if (!prevMonitoring && monitoringBound) {\n"
        "      abortCancelledCycle();\n"
        "      if (isInferring()) {\n"
        "        beginNewInferenceCycle();\n"
        "      }\n"
        "    } else if (prevMonitoring && !monitoringBound) {\n"
        "      abortCancelledCycle();\n"
        "    }\n"
        "    if (!(options && options.skipAutoBind) && shouldAutoBindOnStatus(connected, data)) {\n"
        "      triggerAutoBind();\n"
        "    }\n"
        "  }\n\n"
        "  function insertProjectSummaryAndPrompt(done) {\n"
        "    const finish = (ok, message) => {\n"
        "      if (typeof done === 'function') done(ok, message || '');\n"
        "    };\n"
        "    if (!hasBindingTransport || typeof bindingTransport.getSummaryPrompt !== 'function') {\n"
        "      finish(false, '要約・プロンプト取得機能が利用できません');\n"
        "      return;\n"
        "    }\n"
        "    if (typeof isHandoffPendingOrActive === 'function' && isHandoffPendingOrActive()) {\n"
        "      showToast('aiskel 新規タブ引き継ぎ処理中のため挿入をスキップしました', true);\n"
        "      finish(false, '新規タブ引き継ぎ処理中のため挿入をスキップしました');\n"
        "      return;\n"
        "    }\n"
        "    if (summaryPromptInsertInFlight) {\n"
        "      finish(false, '要約とプロンプトを取得中です');\n"
        "      return;\n"
        "    }\n"
        "    summaryPromptInsertInFlight = true;\n"
        "    bindingTransport.getSummaryPrompt('default', (res) => {\n"
        "      summaryPromptInsertInFlight = false;\n"
        "      if (!res || !res.reachable) {\n"
        "        showToast('VSCodeブリッジへ接続できませんでした', true);\n"
        "        finish(false, 'VSCodeブリッジへ接続できませんでした');\n"
        "        return;\n"
        "      }\n"
        "      const data = res.data || {};\n"
        "      if (!res.connected || !data.ok) {\n"
        "        const errMsg = (data && data.message) || res.error || ('HTTP ' + (res.status || '?'));\n"
        "        showToast('要約・プロンプト取得エラー: ' + errMsg, true);\n"
        "        finish(false, errMsg);\n"
        "        return;\n"
        "      }\n"
        "      const combined = data.combined_text || [data.prompt, data.summary].filter(Boolean).join('\\n\\n');\n"
        "      if (!combined || typeof pasteSummaryAndPromptToChat !== 'function') {\n"
        "        showToast('チャット欄への挿入処理を実行できませんでした', true);\n"
        "        finish(false, 'チャット欄への挿入処理を実行できませんでした');\n"
        "        return;\n"
        "      }\n"
        "      pasteSummaryAndPromptToChat(combined, { onDone: finish });\n"
        "    });\n"
        "  }\n\n"
        "  function refreshBindingStatus(done, options) {\n"
        "    if (!hasBindingTransport) {\n"
        "      if (done) done();\n"
        "      return;\n"
        "    }\n"
        "    bindingTransport.getStatus((res) => {\n"
        "      applyBindingResponse(res, options);\n"
        "      if (done) done();\n"
        "    }, options);\n"
        "  }\n\n"
        "  if (hasBindingTransport && typeof createBindingUiController === 'function') {\n"
        "    bindingUi = createBindingUiController({\n"
        "      onBind: (done) => {\n"
        "        autoBindSuppressed = false;\n"
        "        bindingTransport.bindTab((res) => {\n"
        "          applyBindingResponse(res);\n"
        "          if (res && res.connected && res.data && res.data.bound) {\n"
        "            showToast('このタブを VSCode (' + (res.data.project_name || 'aiskel') + ') と紐づけました', false);\n"
        "          } else if (res && res.reachable) {\n"
        "            showToast('紐づけエラー (HTTP ' + (res.status || '?') + '): ' + (res.error || '失敗しました'), true);\n"
        "          } else {\n"
        "            showToast('VSCodeブリッジへ接続できませんでした', true);\n"
        "          }\n"
        "          if (done) done();\n"
        "        });\n"
        "      },\n"
        "      onUnbind: (done) => {\n"
        "        autoBindSuppressed = true;\n"
        "        bindingTransport.unbindTab((res) => {\n"
        "          applyBindingResponse(res, { skipAutoBind: true });\n"
        "          if (res && res.connected) {\n"
        "            showToast('VSCodeとの紐づけを解除しました', false);\n"
        "          } else if (res && res.reachable) {\n"
        "            showToast('紐づけ解除エラー (HTTP ' + (res.status || '?') + '): ' + (res.error || '失敗しました'), true);\n"
        "          } else {\n"
        "            showToast('VSCodeブリッジへ接続できませんでした', true);\n"
        "          }\n"
        "          if (done) done();\n"
        "        });\n"
        "      },\n"
        "      onRefresh: (done) => refreshBindingStatus(done),\n"
        "      onInsertSummaryPrompt: (done) => {\n"
        "        insertProjectSummaryAndPrompt(() => {\n"
        "          if (done) done();\n"
        "        });\n"
        "      },\n"
        "      onToggleAutoRun: () => {\n"
        "        if (!autoRunAllowed) return;\n"
        "        const next = !isAutoRunEffectiveEnabled();\n"
        "        autoRunUserOverride = next;\n"
        "        if (!next) {\n"
        "          clearAutoRunTimer();\n"
        "        } else {\n"
        "          consecutiveAutoRuns = 0;\n"
        "          lastAutoRunCommandKey = '';\n"
        "        }\n"
        "        bindingState = Object.assign({}, bindingState, { autoRunEnabled: isAutoRunEffectiveEnabled() });\n"
        "        if (bindingUi) bindingUi.render(bindingState);\n"
        "        showToast(next ? 'aiskel 自動送信を ON にしました' : 'aiskel 自動送信を OFF にしました', false);\n"
        "      },\n"
        "    });\n"
        "    bindingUi.render(bindingState);\n"
        "    bindingTransport.onUpdate((res) => {\n"
        "      const data = (res && res.data) || {};\n"
        "      const isExplicitUnbind = Boolean(data.explicit_unbind && !data.bound);\n"
        "      if (isExplicitUnbind) {\n"
        "        autoBindSuppressed = true;\n"
        "      } else if (data.auto_bind_suppressed === false) {\n"
        "        autoBindSuppressed = false;\n"
        "      }\n"
        "      applyBindingResponse(res, { skipAutoBind: isExplicitUnbind });\n"
        "    });\n"
        "    if (typeof bindingTransport.onInsertSummaryPrompt === 'function') {\n"
        "      bindingTransport.onInsertSummaryPrompt((_msg, reply) => {\n"
        "        insertProjectSummaryAndPrompt((ok, message) => {\n"
        "          if (typeof reply === 'function') {\n"
        "            reply({ ok: Boolean(ok), error: ok ? '' : (message || '挿入に失敗しました') });\n"
        "          }\n"
        "        });\n"
        "      });\n"
        "    }\n"
        "    refreshBindingStatus(undefined, { isInitial: true });\n"
        "    window.setInterval(() => refreshBindingStatus(), BINDING_POLL_MS);\n"
        "    window.addEventListener('focus', () => refreshBindingStatus());\n"
        "    document.addEventListener('visibilitychange', () => {\n"
        "      if (document.visibilityState === 'visible') {\n"
        "        refreshBindingStatus();\n"
        "      }\n"
        "    });\n"
        "  }\n"
    )
