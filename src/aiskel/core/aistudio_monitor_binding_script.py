        "  function setActiveSummaryPromptPatternForThread(patternName) {\n"
        "    const key = getSummaryPromptThreadKey();\n"
        "    if (!patternName) {\n"
        "      activeSummaryPromptPatternByThread.delete(key);\n"
        "      activeSummaryPromptPatternByThread.delete('__NEW_CHAT__');\n"
        "      return;\n"
        "    }\n"
        "    activeSummaryPromptPatternByThread.set(key, String(patternName));\n"
        "  }\n\n"
        "  function clearActiveSummaryPromptPatternForThread() {\n"
        "    setActiveSummaryPromptPatternForThread('');\n"
        "  }\n\n"
        "  function getActiveSummaryPromptPatternForThread() {\n"
        "    const key = getSummaryPromptThreadKey();\n"
        "    if (activeSummaryPromptPatternByThread.has(key)) {\n"
        "      return activeSummaryPromptPatternByThread.get(key) || '';\n"
        "    }\n"
        "    // 新規チャット送信後の/prompts/<id>昇格時も挿入済みパターンを引き継ぐ\n"
        "    if (key !== '__NEW_CHAT__' && activeSummaryPromptPatternByThread.has('__NEW_CHAT__')) {\n"
        "      const inherited = activeSummaryPromptPatternByThread.get('__NEW_CHAT__') || '';\n"
        "      if (inherited) {\n"
        "        activeSummaryPromptPatternByThread.set(key, inherited);\n"
        "      }\n"
        "      activeSummaryPromptPatternByThread.delete('__NEW_CHAT__');\n"
        "      return inherited;\n"
        "    }\n"
        "    return '';\n"
        "  }\n\n"
        "  function triggerAutoBind() {\n"
        "    if (!hasBindingTransport || autoBindInFlight || autoBindSuppressed) return;\n"
        "    autoBindInFlight = true;\n"
        "    // 通信中のブロードキャスト先着による二重抑制を防ぐため送信前状態を保持\n"
        "    const wasBoundBeforeRequest = monitoringBound;\n"
        "    bindingTransport.bindTab((res) => {\n"
        "      autoBindInFlight = false;\n"
        "      const data = (res && res.data) || {};\n"
        "      // 自動紐づけ通信中にユーザーが明示解除した場合はUserscriptを含め即座にロールバック\n"
        "      if (autoBindSuppressed && res && res.connected && data.is_current_tab_bound) {\n"
        "        bindingTransport.unbindTab((unbindRes) => {\n"
        "          applyBindingResponse(unbindRes, { skipAutoBind: true });\n"
        "        });\n"
        "        return;\n"
        "      }\n"
        "      applyBindingResponse(res, { skipAutoBind: true });\n"
        "      if (res && res.connected && data.is_current_tab_bound && !wasBoundBeforeRequest) {\n"
        "        showToast('このタブを VSCode (' + (data.project_name || 'aiskel') + ') と自動で紐づけました', false);\n"
        "      }\n"
        "    }, { autoBind: true });\n"
        "  }\n\n"
        "  function shouldAutoBindOnStatus(connected, data) {\n"
        "    if (!hasBindingTransport || !connected || !data) return false;\n"
        "    if (data.bound || autoBindSuppressed || autoBindInFlight) return false;\n"
        "    if (data.auto_bind_suppressed === true || data.is_tab_active === false) return false;\n"
        "    if (document.visibilityState !== 'visible') return false;\n"
        "    if (typeof isHandoffPendingOrActive === 'function' && isHandoffPendingOrActive()) return false;\n"
        "    return true;\n"
        "  }\n\n"
        "  function applyBindingResponse(res, options) {\n"
        "    // 先発getStatus応答が後発claim/bind結果を巻き戻すレースコンディションを抑止\n"
        "    const statusReqSeq = options && typeof options._statusReqSeq === 'number' ? options._statusReqSeq : null;\n"
        "    if (statusReqSeq !== null) {\n"
        "      if (statusReqSeq < latestBindingSyncSeq) return;\n"
        "      latestBindingSyncSeq = statusReqSeq;\n"
        "    } else {\n"
        "      latestBindingSyncSeq = ++bindingSyncSeq;\n"
        "    }\n"
        "    const prevMonitoring = monitoringBound;\n"
        "    const reachable = Boolean(res && res.reachable);\n"
        "    const connected = Boolean(res && res.connected);\n"
        "    const status = (res && res.status) || 0;\n"
        "    const data = (res && res.data) || {};\n"
        "    const errorMessage = (res && res.error) ? String(res.error) : '';\n"
        "    if (!reachable) {\n"
        "      if (wasBridgeConnected) {\n"
        "        autoBindSuppressed = false;\n"
        "      }\n"
        "      wasBridgeConnected = false;\n"
        "    } else if (connected) {\n"
        "      wasBridgeConnected = true;\n"
        "      if ((data.explicit_unbind && !data.bound) || data.auto_bind_suppressed === true) {\n"
        "        autoBindSuppressed = true;\n"
        "      } else if (data.auto_bind_suppressed === false) {\n"
        "        autoBindSuppressed = false;\n"
        "      }\n"
        "      autoRunServerDefault = Boolean(data.auto_run_default);\n"
        "      autoRunAllowed = Boolean(data.auto_run_allowed);\n"
        "    } else if (reachable && (status === 401 || status === 403 || status === 404)) {\n"
        "      autoRunServerDefault = false;\n"
        "      autoRunAllowed = false;\n"
        "    }\n"
        "    bindingState = {\n"
        "      reachable,\n"
        "      connected,\n"
        "      status,\n"
        "      errorMessage,\n"
        "      bound: Boolean(connected && data.bound),\n"
        "      isCurrentTabBound: Boolean(connected && data.is_current_tab_bound),\n"
        "      projectName: String(data.project_name || ''),\n"
        "      projectRoot: String(data.project_root || ''),\n"
        "      commandCwd: String(data.command_cwd || data.project_root || ''),\n"
        "      boundTabTitle: String(data.tab_title || ''),\n"
        "      boundTabId: String(data.tab_id || ''),\n"
        "      currentTabId: String(data.current_tab_id || ''),\n"
        "      autoRunDefault: autoRunServerDefault,\n"
        "      autoRunAllowed,\n"
        "      autoRunEnabled: isAutoRunEffectiveEnabled(),\n"
        "      twoStageMode: (bindingState && bindingState.twoStageMode) || 'auto',\n"
        "      twoStageEnabled: data.two_stage_enabled !== false,\n"
        "      twoStageMinTokens: typeof data.two_stage_min_tokens === 'number' ? data.two_stage_min_tokens : 4000,\n"
        "      patchHandoffMaxTabs: typeof data.patch_handoff_max_tabs === 'number' ? data.patch_handoff_max_tabs : null,\n"
        "      remainingAutoTabs: typeof data.remaining_auto_tabs === 'number' ? data.remaining_auto_tabs : null,\n"
        "      isAutoGeneratedTab: Boolean(data.is_auto_generated_tab),\n"
        "      discoveryTaskActive: Boolean(data.discovery_task_active),\n"
        "      discoveryTaskIndex: typeof data.discovery_task_index === 'number' ? data.discovery_task_index : 0,\n"
        "      discoveryTaskTotal: typeof data.discovery_task_total === 'number' ? data.discovery_task_total : 0,\n"
        "      discoveryTaskTitle: String(data.discovery_task_title || ''),\n"
        "    };\n"
        "    const statusSentAt = options && typeof options._statusSentAt === 'number' ? options._statusSentAt : 0;\n"
        "    const isStaleExecPoll = Boolean(statusSentAt && typeof lastCommandEndedAt === 'number' && statusSentAt < lastCommandEndedAt);\n"
        "    if (typeof extractServerCommandExecutionState === 'function' && typeof serverCommandState !== 'undefined') {\n"
        "      if (!connected || !isStaleExecPoll) {\n"
        "        serverCommandState = extractServerCommandExecutionState(connected, data);\n"
        "      }\n"
        "    }\n"
        "    if (typeof getAutoSplitSummaryForUi === 'function') {\n"
        "      bindingState = Object.assign({}, bindingState, getAutoSplitSummaryForUi());\n"
        "    }\n"
        "    if (typeof getConfigInferSummaryForUi === 'function') {\n"
        "      bindingState = Object.assign({}, bindingState, getConfigInferSummaryForUi());\n"
        "    }\n"
        "    if (typeof getEffectiveCommandExecutionState === 'function') {\n"
        "      bindingState = Object.assign({}, bindingState, getEffectiveCommandExecutionState());\n"
        "    }\n"
        "    if (bindingUi) {\n"
        "      bindingUi.render(bindingState);\n"
        "    }\n"
        "    if (hasBindingTransport && typeof bindingTransport.notifyState === 'function') {\n"
        "      bindingTransport.notifyState(bindingState);\n"
        "    }\n"
        "    if (typeof syncRunningStatusPolling === 'function') {\n"
        "      syncRunningStatusPolling();\n"
        "    }\n"
        "    if (!hasBindingTransport) {\n"
        "      return;\n"
        "    }\n"
        "    // 推論中の単発通信失敗では維持し、非推論時失敗または連続到達不能時は監視を解除\n"
        "    if (connected) {\n"
        "      unreachableStreak = 0;\n"
        "      monitoringBound = Boolean(data.is_current_tab_bound);\n"
        "    } else if (reachable && (status === 401 || status === 403 || status === 404)) {\n"
        "      unreachableStreak = 0;\n"
        "      monitoringBound = false;\n"
        "    } else if (reachable) {\n"
        "      unreachableStreak = 0;\n"
        "    } else {\n"
        "      unreachableStreak += 1;\n"
        "      if ((!wasInferring && !isInferring()) || unreachableStreak >= 2) {\n"
        "        monitoringBound = false;\n"
        "      }\n"
        "    }\n"
        "    if (!isCurrentTabBoundToApp() || !monitoringBound || (connected && bindingState.projectRoot !== cachedSummaryPromptProjectRoot)) {\n"
        "      cachedSummaryPromptText = '';\n"
        "      cachedSummaryPromptBaseText = '';\n"
        "      cachedSummaryPromptProjectRoot = '';\n"
        "      cachedSummaryPromptTwoStageMode = '';\n"
        "    }\n"
        "    if (!monitoringBound || (connected && bindingState.projectRoot !== cachedSummaryPromptProjectRoot)) {\n"
        "      clearActiveSummaryPromptPatternForThread();\n"
        "    }\n"
        "    if (!prevMonitoring && monitoringBound) {\n"
        "      abortCancelledCycle();\n"
        "      if (isInferring()) {\n"
        "        beginNewInferenceCycle();\n"
        "      }\n"
        "    } else if (prevMonitoring && !monitoringBound) {\n"
        "      if (typeof clearTrackedCommands === 'function') {\n"
        "        clearTrackedCommands();\n"
        "      }\n"
        "      abortCancelledCycle();\n"
        "      if (typeof cancelActivePasteTask === 'function' && (!activePasteTask || activePasteTask.priority !== 'handoff')) {\n"
        "        cancelActivePasteTask({ notifyAbort: true });\n"
        "      }\n"
        "      if (typeof clearErrorPanel === 'function') {\n"
        "        clearErrorPanel();\n"
        "      }\n"
        "    }\n"
        "    if (\n"
        "      connected &&\n"
        "      data.is_current_tab_bound &&\n"
        "      data.pending_task_handoff &&\n"
        "      data.pending_task_handoff.handoff_id &&\n"
        "      hasHandoffTransport &&\n"
        "      typeof handoffTransport.openPendingTaskHandoff === 'function'\n"
        "    ) {\n"
        "      const pendingTask = data.pending_task_handoff;\n"
        "      const pendingHid = String(pendingTask.handoff_id || '');\n"
        "      if (pendingHid && !pendingTaskOpenInFlight && !openedTaskHandoffIds.has(pendingHid)) {\n"
        "        pendingTaskOpenInFlight = true;\n"
        "        openedTaskHandoffIds.add(pendingHid);\n"
        "        handoffTransport.openPendingTaskHandoff(pendingTask, (openRes) => {\n"
        "          pendingTaskOpenInFlight = false;\n"
        "          const openData = (openRes && openRes.data) || {};\n"
        "          if (openRes && openRes.connected && openData.found) {\n"
        "            showToast(\n"
        "              'aiskel 分割タスク (' + (openData.task_index || pendingTask.task_index || '?') + '/' +\n"
        "              (openData.total_tasks || pendingTask.total_tasks || '?') + ') を新タブで開始します',\n"
        "              false\n"
        "            );\n"
        "          } else if (!openRes || !openRes.reachable || !openRes.connected || openRes.status >= 500) {\n"
        "            // 未消費エラー（通信失敗・起動直後・409競合等）時は再試行できるよう履歴を解放する\n"
        "            openedTaskHandoffIds.delete(pendingHid);\n"
        "          }\n"
        "        });\n"
        "      }\n"
        "    }\n"
        "    if (!(options && options.skipAutoBind) && shouldAutoBindOnStatus(connected, data)) {\n"
        "      triggerAutoBind();\n"
        "    }\n"
        "  }\n\n"
        "  function isCurrentTabBoundToApp() {\n"
        "    if (!hasBindingTransport) return false;\n"
        "    return Boolean(bindingState && bindingState.connected && bindingState.isCurrentTabBound);\n"
        "  }\n\n"
        "  function buildSummaryPromptRequestOptions() {\n"
        "    const mode = (bindingState && bindingState.twoStageMode) || 'auto';\n"
        "    const twoStageParam = mode === 'on' ? true : (mode === 'off' ? false : 'auto');\n"
        "    return { mode, params: { pattern: 'default', two_stage: twoStageParam } };\n"
        "  }\n\n"
        "  function getCachedSummaryPromptIfValid() {\n"
        "    if (!isCurrentTabBoundToApp() || !isMonitoringActive()) return null;\n"
        "    const curRoot = (bindingState && bindingState.projectRoot) || '';\n"
        "    const curMode = (bindingState && bindingState.twoStageMode) || 'auto';\n"
        "    if (\n"
        "      !cachedSummaryPromptText ||\n"
        "      cachedSummaryPromptProjectRoot !== curRoot ||\n"
        "      cachedSummaryPromptTwoStageMode !== curMode\n"
        "    ) {\n"
        "      return null;\n"
        "    }\n"
        "    return { combinedText: cachedSummaryPromptText, promptText: cachedSummaryPromptBaseText };\n"
        "  }\n\n"
        "  function fetchSummaryPromptFromBridge(done) {\n"
        "    if (!hasBindingTransport || typeof bindingTransport.getSummaryPrompt !== 'function') {\n"
        "      done({ ok: false, reachable: false, error: '要約・プロンプト取得機能が利用できません', data: {} });\n"
        "      return;\n"
        "    }\n"
        "    const reqRoot = (bindingState && bindingState.projectRoot) || '';\n"
        "    const { mode, params } = buildSummaryPromptRequestOptions();\n"
        "    const summaryDetail = mode === 'on' ? '2段階探索インデックス生成' : (mode === 'off' ? 'プロジェクト要約生成' : '要約 / 2段階インデックス生成');\n"
        "    const trackId = typeof beginTrackedCommand === 'function'\n"
        "      ? beginTrackedCommand({\n"
        "          kind: 'summary_prompt',\n"
        "          label: '要約+プロンプト生成 (aiskel)',\n"
        "          detail: summaryDetail,\n"
        "        })\n"
        "      : 0;\n"
        "    let trackSettled = false;\n"
        "    const finishTrack = () => {\n"
        "      if (trackSettled) return;\n"
        "      trackSettled = true;\n"
        "      if (trackId && typeof endTrackedCommand === 'function') endTrackedCommand(trackId);\n"
        "    };\n"
        "    bindingTransport.getSummaryPrompt(params, (res) => {\n"
        "      finishTrack();\n"
        "      if (!res || !res.reachable) {\n"
        "        done({ ok: false, reachable: false, error: 'VSCodeブリッジへ接続できませんでした', data: {} });\n"
        "        return;\n"
        "      }\n"
        "      const data = res.data || {};\n"
        "      if (!res.connected || !data.ok) {\n"
        "        const errMsg = (data && data.message) || res.error || ('HTTP ' + (res.status || '?'));\n"
        "        done({ ok: false, reachable: true, error: errMsg, data });\n"
        "        return;\n"
        "      }\n"
        "      const combined = data.combined_text || [data.prompt, data.summary].filter(Boolean).join('\\n\\n');\n"
        "      if (!combined) {\n"
        "        done({ ok: false, reachable: true, error: '挿入する要約・プロンプトが空です', data });\n"
        "        return;\n"
        "      }\n"
        "      const promptText = typeof data.prompt === 'string' ? data.prompt : '';\n"
        "      const nowRoot = (bindingState && bindingState.projectRoot) || '';\n"
        "      const nowMode = (bindingState && bindingState.twoStageMode) || 'auto';\n"
        "      if (nowRoot === reqRoot && nowMode === mode && isCurrentTabBoundToApp() && isMonitoringActive()) {\n"
        "        cachedSummaryPromptText = combined;\n"
        "        cachedSummaryPromptBaseText = promptText;\n"
        "        cachedSummaryPromptProjectRoot = nowRoot;\n"
        "        cachedSummaryPromptTwoStageMode = nowMode;\n"
        "      }\n"
        "      const resolvedPattern = data.two_stage_used ? 'discovery' : String(data.pattern || 'default');\n"
        "      done({ ok: true, reachable: true, combinedText: combined, promptText, resolvedPattern, data });\n"
        "    });\n"
        "  }\n\n"
        "  function fetchSummaryPromptForSubmit(done) {\n"
        "    fetchSummaryPromptFromBridge((result) => {\n"
        "      if (result.ok) {\n"
        "        done(true, result.combinedText, result.promptText, '', result.resolvedPattern || '');\n"
        "        return;\n"
        "      }\n"
        "      done(false, '', '', result.error || '', '');\n"
        "    });\n"
        "  }\n\n"
        "  function insertProjectSummaryAndPrompt(done) {\n"
        "    let finished = false;\n"
        "    const finish = (ok, message, releaseLock) => {\n"
        "      if (finished) return;\n"
        "      finished = true;\n"
        "      if (releaseLock) {\n"
        "        summaryPromptInsertInFlight = false;\n"
        "      }\n"
        "      if (typeof done === 'function') done(ok, message || '');\n"
        "    };\n"
        "    if (!hasBindingTransport || typeof bindingTransport.getSummaryPrompt !== 'function') {\n"
        "      finish(false, '要約・プロンプト取得機能が利用できません', false);\n"
        "      return;\n"
        "    }\n"
        "    if (typeof isHandoffPendingOrActive === 'function' && isHandoffPendingOrActive()) {\n"
        "      showToast('aiskel 新規タブ引き継ぎ処理中のため挿入をスキップしました', true);\n"
        "      finish(false, '新規タブ引き継ぎ処理中のため挿入をスキップしました', false);\n"
        "      return;\n"
        "    }\n"
        "    if (typeof runPromptAppendInFlight !== 'undefined' && runPromptAppendInFlight) {\n"
        "      finish(false, '送信前の挿入処理を実行中です', false);\n"
        "      return;\n"
        "    }\n"
        "    if (summaryPromptInsertInFlight) {\n"
        "      finish(false, '要約とプロンプトを取得中です', false);\n"
        "      return;\n"
        "    }\n"
        "    summaryPromptInsertInFlight = true;\n"
        "    fetchSummaryPromptFromBridge((result) => {\n"
        "      if (!result.reachable) {\n"
        "        showToast('VSCodeブリッジへ接続できませんでした', true);\n"
        "        finish(false, result.error || 'VSCodeブリッジへ接続できませんでした', true);\n"
        "        return;\n"
        "      }\n"
        "      if (!result.ok) {\n"
        "        showToast('要約・プロンプト取得エラー: ' + result.error, true);\n"
        "        finish(false, result.error, true);\n"
        "        return;\n"
        "      }\n"
        "      if (typeof pasteSummaryAndPromptToChat !== 'function') {\n"
        "        showToast('チャット欄への挿入処理を実行できませんでした', true);\n"
        "        finish(false, 'チャット欄への挿入処理を実行できませんでした', true);\n"
        "        return;\n"
        "      }\n"
        "      const data = result.data || {};\n"
        "      const started = pasteSummaryAndPromptToChat(result.combinedText, {\n"
        "        onDone: (ok, msg) => {\n"
        "          if (ok && typeof setActiveSummaryPromptPatternForThread === 'function') {\n"
        "            setActiveSummaryPromptPatternForThread(result.resolvedPattern || (data.two_stage_used ? 'discovery' : 'default'));\n"
        "          }\n"
        "          if (ok && data.two_stage_used && typeof data.index_tokens === 'number' && typeof data.full_tokens === 'number' && data.full_tokens > 0) {\n"
        "            const pct = Math.max(0, Math.round((1 - data.index_tokens / data.full_tokens) * 100));\n"
        "            showToast('2段階探索インデックスを挿入しました (約 ' + data.index_tokens + ' tokens / フル比 ' + pct + '% 削減)', false);\n"
        "          }\n"
        "          finish(ok, msg, true);\n"
        "        },\n"
        "      });\n"
        "      // 貼付タスク開始失敗時はonDoneが呼ばれないため確実にロックを解放\n"
        "      if (!started) {\n"
        "        finish(false, 'チャット欄への挿入を開始できませんでした', true);\n"
        "      }\n"
        "    });\n"
        "  }\n\n"
        "  function refreshBindingStatus(done, options) {\n"
        "    if (!hasBindingTransport) {\n"
        "      if (done) done();\n"
        "      return;\n"
        "    }\n"
        "    const reqSeq = ++bindingSyncSeq;\n"
        "    const reqOptions = Object.assign({}, options || {}, { _statusReqSeq: reqSeq, _statusSentAt: Date.now() });\n"
        "    bindingTransport.getStatus((res) => {\n"
        "      applyBindingResponse(res, reqOptions);\n"
        "      if (done) done();\n"
        "    }, options);\n"
        "  }\n\n"
        "  if (hasBindingTransport && typeof createBindingUiController === 'function') {\n"
        "    bindingUi = createBindingUiController({\n"
        "      onBind: (done) => {\n"
        "        autoBindSuppressed = false;\n"
        "        bindingTransport.bindTab((res) => {\n"
        "          applyBindingResponse(res);\n"
        "          if (res && res.connected && res.data && res.data.bound) {\n"
        "            showToast('このタブを VSCode (' + (res.data.project_name || 'aiskel') + ') と紐づけました', false);\n"
        "          } else if (res && res.reachable) {\n"
        "            showToast('紐づけエラー (HTTP ' + (res.status || '?') + '): ' + (res.error || '失敗しました'), true);\n"
        "          } else {\n"
        "            showToast('VSCodeブリッジへ接続できませんでした', true);\n"
        "          }\n"
        "          if (done) done();\n"
        "        });\n"
        "      },\n"
        "      onUnbind: (done) => {\n"
        "        autoBindSuppressed = true;\n"
        "        bindingTransport.unbindTab((res) => {\n"
        "          applyBindingResponse(res, { skipAutoBind: true });\n"
        "          if (res && res.connected) {\n"
        "            showToast('VSCodeとの紐づけを解除しました', false);\n"
        "          } else if (res && res.reachable) {\n"
        "            showToast('紐づけ解除エラー (HTTP ' + (res.status || '?') + '): ' + (res.error || '失敗しました'), true);\n"
        "          } else {\n"
        "            showToast('VSCodeブリッジへ接続できませんでした', true);\n"
        "          }\n"
        "          if (done) done();\n"
        "        });\n"
        "      },\n"
        "      onRefresh: (done) => refreshBindingStatus(done),\n"
        "      onInsertSummaryPrompt: (done) => {\n"
        "        insertProjectSummaryAndPrompt(() => {\n"
        "          if (done) done();\n"
        "        });\n"
